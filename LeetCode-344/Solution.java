// ============================================================================
// 力扣 344. 反转字符串
// ----------------------------------------------------------------------------
// 题目描述
// 编写一个函数，其作用是将输入的字符串反转过来。输入字符串以字符数组
// char[] 的形式给出。
// 不要给另外的数组分配额外的空间，你必须原地修改输入数组、使用 O(1) 的
// 额外空间解决这一问题。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public void reverseString(char[] s)
//   注意返回类型是 void：答案直接写在传进来的 s 里，不用 return
//
// 输入 #1
//   s = ["h","e","l","l","o"]
// 输出 #1
//   ["o","l","l","e","h"]
//
// 输入 #2
//   s = ["H","a","n","n","a","H"]   ← 见下面"样例说明"，这个写法是错的
// 输出 #2
//   ["H","a","n","n","a","H"]       ← 想当然的输出，同样是错的
//   官方原题是 s = ["H","a","n","n","a","h"]（最后一个 h 是小写），
//   输出 ["h","a","n","n","a","H"]。首字母 H 大写、末字母 h 小写，
//   反转之后正好互相交换位置——这个样例专门用来抓"大小写没看仔细"。
//
// 输入 #3
//   s = ["A"]
// 输出 #3
//   ["A"]
//   补的边界样例：只有一个字符，反转后还是它自己。
//
// 输入 #4
//   s = ["a","b"]
// 输出 #4
//   ["b","a"]
//   补的样例：两个字符，正好交换一次。
//
// 输入 #5
//   s = ["a","b","c"]
// 输出 #5
//   ["c","b","a"]
//   补的样例：奇数长度，中间那个字符（b）位置不动，左右两边互换。
//
// 提示
//   1. 1 <= s.length <= 10^5
//   2. s[i] 都是 ASCII 可打印字符（大小写字母、数字、符号、空格都可能出现）
//
// 说明/提示
// 【样例说明】样例 2 是这题唯一的"陷阱"：H 和 h 长得几乎一样，反转后
//   却要互换位置，一旦看错大小写就会以为"输出和输入一样"，还以为自己
//   的代码错了。样例 5 说明奇数长度时中间字符不参与交换。
// 【评测用例规模与约定】
//   n 最大 10^5，题面明确要求 O(1) 额外空间，所以不能 new 一个新数组
//   反着拷贝回去。力扣难度：简单。
//
// 思路（对撞双指针：两头往中间走，边走边交换，和 283 的双指针是姊妹篇）
//   一、反转的本质是什么
//     反转一个数组 = 第 0 个和第 n-1 个换、第 1 个和第 n-2 个换……
//     每一对"位置加起来等于 n-1"的元素互换位置。
//     奇数长度时最中间那个字符的下标是 n/2（整除），它和自己是"一对"，
//     不用换。
//
//   二、双指针的分工
//     left：从 0 开始，指向还没交换的最左边。
//     right：从 n-1 开始，指向还没交换的最右边。
//     每轮：交换 s[left] 和 s[right]，然后 left++、right--，
//     两个指针往中间"对撞"，直到相遇。
//
//   三、循环条件为什么是 left < right（本题最值得想清楚的一点）
//     - left == right 时：两个指针落在同一个位置（奇数长度的中点），
//       自己和自己交换等于没换，还白做三次赋值，所以必须停。
//     - left > right 时：这一对 (left, right) 上一轮已经换过了
//       （上一轮换的是 (right, left) 这对），再换就换回去了，更不能做。
//     所以条件只能写 left < right，相遇即止。
//
//     int left = 0, right = s.length - 1;
//     while (left < right) {
//         char t = s[left];       // 经典三步交换，必须借助临时变量
//         s[left] = s[right];
//         s[right] = t;
//         left++;                 // 左指针往右走一步
//         right--;                // 右指针往左走一步
//     }
//
//   四、拿样例走一遍
//     样例 1：s = [h,e,l,l,o]，left=0，right=4
//       换 s[0] 和 s[4] → [o,e,l,l,h]，left=1，right=3
//       换 s[1] 和 s[3] → [o,l,l,e,h]，left=2，right=2
//       left == right，停。中点 l 没动，结果 [o,l,l,e,h] ✓
//     样例 2：s = [H,a,n,n,a,h]，left=0，right=5
//       换 s[0] 和 s[5] → [h,a,n,n,a,H]，left=1，right=4
//       换 s[1] 和 s[4] → [h,a,n,n,a,H]（a 和 a 换，看不出变化），left=2，right=3
//       换 s[2] 和 s[3] → [h,a,n,n,a,H]（n 和 n 换，同样看不出变化），left=3，right=2
//       left > right，停。结果 [h,a,n,n,a,H] ✓
//       注意样例 2 里中间几步"看起来没变"，其实每一步都在正确地交换——
//       这正是 H/h、a/a、n/n 这种对称样例的特点。
//     样例 3：s = [A]，left=0，right=0，left < right 不成立，
//       循环一次都不进，直接返回原数组 ✓
//
//   五、坑和边界
//     - 交换必须用临时变量 t。直接写 s[left] = s[right]; s[right] = s[left];
//       两边会变成同一个字符，前半截全丢。
//     - 循环条件是 left < right，不是 <=：== 时是中点自交换，白做功；
//       也不会死循环（left++ 和 right-- 每轮都在动，区间每轮缩 2）。
//     - 奇数长度不用特判：中点那格天然轮不到，left < right 自动停。
//     - 不用管大小写、不用管字符是什么：题目反转的是"位置"，不是"内容"，
//       ASCII 字符一律当普通值换位置就行。
//     - s.length 是 char 数组的属性（不是方法，别写 s.length()）；
//       这和 String 的 s.length() 不一样，两套语法别混。
//
//   六、复杂度
//     循环 n/2 轮，每轮 O(1)，时间 O(n)；只用 left、right、t 三个变量，
//     额外空间 O(1)，正好满足题面的硬性要求。
//
//   进阶：这题和 283 是姊妹篇
//     283 的双指针是"同向"的：i、j 都从头往尾走，快指针探路、慢指针收货；
//     这题的 双指针是"相向（对撞）"的：left、right 从两端往中间挤。
//     对撞双指针是后面一堆题的地基：125 验证回文串、167 两数之和 II、
//     11 盛最多水的容器、15 三数之和，全是这个 left/right 对撞的骨架。
//
//   其他能过的解法（了解即可）：
//     - 从后往前把字符拷到新数组再复制回去：结果对，但 O(n) 额外空间，
//       违反题面的 O(1) 要求，这题的核心考点就是不许这么做。
//     - 递归交换首尾：能写，但 n = 10^5 时递归深度 5 万层，
//       Java 默认栈大小（约 512KB~1MB）扛不住，会 StackOverflowError。
//     - 用 StringBuilder.reverse()：一行解决，但 String 是不可变的，
//       必须先 new String(s) 再转 char[] 拷回去，额外空间还是 O(n)，
//       而且完全没练到指针，不建议。
// ============================================================================

class Solution {
    public void reverseString(char[] s) {
        // 定义双指针，一个指向第一个字符，一个指向最后一个字符
        int left = 0;
        int right = s.length - 1;
        // 当左指针小于右指针时，交换两个指针指向的字符，并移动指针
        while(left < right){
            char temp = s[left];
            s[left] = s[right];
            s[right] = temp;
            // 移动指针
            left++;
            right--;
        }
        // 输出反转后的字符串
        for (char i : s) {
            System.out.print(i);
        }
    }
}
