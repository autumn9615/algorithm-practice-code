// ============================================================================
// 力扣 3. 无重复字符的最长子串
// ----------------------------------------------------------------------------
// 题目描述
// 给定一个字符串 s，请你找出其中不含有重复字符的最长子串的长度。
// 注意是"子串"不是"子序列"：子串必须连续，不能跳着挑字符。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int lengthOfLongestSubstring(String s)
//
// 输入 #1
//   s = "abcabcbb"
// 输出 #1
//   3
//   解释：最长的是 "abc"，长度 3。注意 "bca"、"cab" 也是答案，
//         题目只问长度，不问是哪一个。
//
// 输入 #2
//   s = "bbbbb"
// 输出 #2
//   1
//   解释：全是 b，最长只能取一个 b。
//
// 输入 #3
//   s = "pwwkew"
// 输出 #3
//   3
//   解释：最长的是 "wke"，长度 3。别选 "pwke"——它是子序列不是子串，
//         中间跳过了 w，不连续。
//
// 输入 #4
//   s = ""
// 输出 #4
//   0
//   补的边界样例：空串，没有任何子串，返回 0。题面允许 s.length = 0。
//
// 输入 #5
//   s = "abba"
// 输出 #5
//   2
//   补的陷阱样例：这是"last 数组"写法最容易翻车的一组。
//   走到最后一个 a 时，a 上次出现在下标 0，但左边界早就推到 2 了，
//   如果不加判断直接 left = last[a] + 1，left 会从 2 退回到 1，
//   答案就算成 3（错的）。正确写法必须保证 left 只进不退。
//
// 输入 #6
//   s = "tmmzuxt"
// 输出 #6
//   5
//   补的陷阱样例：最长是 "mzuxt"。结尾的 t 上次出现在下标 0，
//   同样比当前 left 小，直接跳会算成 6，正确答案是 5。
//
// 输入 #7
//   s = " "
// 输出 #7
//   1
//   补的边界样例：字符串是一个空格。题面说 s 可以包含空格，
//   所以别用 Scanner.next() 之类会跳过空白的读法（力扣用参数传，没事，
//   但自己本地测试时要注意）。
//
// 提示
//   1. 0 <= s.length <= 10^5
//   2. s 由英文字母、数字、符号和空格组成
//
// 说明/提示
// 【样例说明】样例 3 是这题的灵魂：它专门抓"把子序列当子串"的错。
//   样例 2 说明全相同字符时答案退化成 1。
// 【评测用例规模与约定】
//   n 最大 10^5。暴力枚举所有子串再查重是 O(n^2)（最坏 10^10 次），
//   肯定超时，需要 O(n) 的滑动窗口。字符集是 ASCII（字母、数字、符号、
//   空格），一共不超过 128 种，可以用 int[128] 数组当哈希表，
//   额外空间 O(1)。力扣难度：中等。
//
// 思路（滑动窗口 / 同向双指针，和 209 同一个骨架，但"求最长"和"求最短"
//       的两套条件正好相反）
//   一、窗口代表什么
//     维护窗口 [left, right]，要求：窗口内的字符互不相同。
//     对于每个 right，让 left 尽可能小——这样窗口就是以 right 结尾的、
//     不含重复字符的最长窗口。它的长度 right - left + 1 就是一个候选答案。
//
//   二、右指针扩张，遇到重复才收缩左指针
//     每轮把 s[right] 纳入窗口：
//       - 如果它没在窗口里出现过，直接纳入，窗口合法；
//       - 如果它已经在窗口里了，那就必须把 left 往右推，一直推到
//         窗口里不再有重复为止（把旧的那个字符挤出窗口）。
//     收缩完之后窗口一定合法，此时更新答案。
//
//   三、和 209 的对比（这是最关键的一节，两题连着做效果最好）
//     209 求"最短"，3 求"最长"，所以循环条件正好反着写：
//       ┌──────────┬────────────────────┬────────────────────┐
//       │          │ 209 长度最小的子数组 │ 3 无重复字符的最长子串│
//       ├──────────┼────────────────────┼────────────────────┤
//       │ 目标      │ 最短                │ 最长                │
//       │ 窗口属性  │ 和 >= target        │ 无重复字符          │
//       │ while     │ while (合法) 收缩    │ while (不合法) 收缩 │
//       │ 记答案    │ while 里面（缩之前） │ while 之后（缩完）  │
//       └──────────┴────────────────────┴────────────────────┘
//     道理很简单：
//       求最短 → 窗口一旦合法就想再短一点，所以"合法就缩"，边缩边记；
//       求最长 → 窗口一旦不合法就必须缩，缩到合法为止再记，
//                因为不合法的窗口没有意义。
//
//   四、写法 A：HashSet + while（好懂，和 209 写法最像）
//     int left = 0, ans = 0;
//     Set<Character> window = new HashSet<>();
//     for (int right = 0; right < s.length(); right++) {
//         char c = s.charAt(right);
//         while (window.contains(c)) {     // 有重复，缩小窗口直到不重复
//             window.remove(s.charAt(left));
//             left++;
//         }
//         window.add(c);                   // 现在窗口里没有 c 了，安全加入
//         ans = Math.max(ans, right - left + 1);   // 缩完再记答案
//     }
//     return ans;
//     注意：删的是 s.charAt(left)，不是 c。这一点最容易写错——
//     重复的可能是更早出现的那个字符，要按左端一个个挤出去。
//
//   五、写法 B：int[128] 记录每个字符上次出现的位置（更快，推荐）
//     字符集只有 ASCII 128 种，直接开数组当哈希表，省掉 HashSet 的开销。
//     int[] last = new int[128];       // last[字符] = 它上次出现的下标
//     Arrays.fill(last, -1);           // 用 -1 表示"没出现过"
//     int left = 0, ans = 0;
//     for (int right = 0; right < s.length(); right++) {
//         char c = s.charAt(right);
//         if (last[c] >= left) {       // ★ 上次出现在窗口内部，才算重复
//             left = last[c] + 1;      // 直接把 left 跳到它后面，不用一格格挪
//         }
//         last[c] = right;             // 刷新 c 的最新位置
//         ans = Math.max(ans, right - left + 1);
//     }
//     return ans;
//
//     为什么 "if (last[c] >= left)" 这个判断不能省？
//     因为 last[c] 可能指向窗口外面（更早的位置），那是"已经处理过、
//     不在窗口里的旧记录"，不能因为它把 left 往回拉。
//     反例 s = "abba"：
//       right=3 时 c='a'，last['a']=0，而当前 left=2。
//       如果直接 left = 0 + 1 = 1，left 退回去了，窗口 [1,3] = "bba"
//       有重复，长度算成 3，错。正确应该是 left 保持 2，答案 2。
//     再加一个反例 s = "tmmzuxt"：结尾 t 上次在下标 0，直接跳会得到 6，
//     正确答案是 5（"mzuxt"）。两个反例都是同一类错：left 只能进不能退。
//
//   六、拿样例 1 走一遍（s = "abcabcbb"，用写法 B）
//     right=0 'a'：last[a]=-1 < 0，不动；last[a]=0；ans=1
//     right=1 'b'：last[b]=-1 < 0，不动；last[b]=1；ans=2
//     right=2 'c'：last[c]=-1 < 0，不动；last[c]=2；ans=3
//     right=3 'a'：last[a]=0 >= left(0)，left=1；last[a]=3；ans=max(3,3)=3
//     right=4 'b'：last[b]=1 >= left(1)，left=2；last[b]=4；ans=3
//     right=5 'c'：last[c]=2 >= left(2)，left=3；last[c]=5；ans=3
//     right=6 'b'：last[b]=4 >= left(3)，left=5；last[b]=6；ans=3
//     right=7 'b'：last[b]=6 >= left(5)，left=7；last[b]=7；ans=3
//     结束，返回 3 ✓
//
//   七、坑和边界
//     - ★ 写法 B 里 "if (last[c] >= left)" 不能省，否则 left 会倒退，
//       答案偏大。反例就是样例 5 "abba" 和样例 6 "tmmzuxt"。
//     - 写法 A 里 remove 的是 s.charAt(left)，不是当前字符 c。
//     - 答案在 while 收缩"之后"更新，因为收缩前窗口可能还不合法。
//       这和 209 正好相反（209 是收缩前更新）。
//     - 空串返回 0：循环一次都不进，ans 初值 0 直接返回，天然正确。
//     - 别把"子串"当"子序列"：子串必须连续，所以窗口只能滑动，
//       不能跳着选字符。
//     - s.length() 是方法（带括号），数组才是 s.length 属性。
//     - 用 s.charAt(i) 取字符，别写成 s[i]——Java 的 String 不支持下标。
//
//   八、复杂度
//     右指针走 n 步；写法 A 里 left 总共也只走 n 步，while 累计 O(n)；
//     写法 B 里 left 直接跳，更是一次 O(1)。两种都是时间 O(n)。
//     写法 A 的空间是 O(字符集) = O(128) = O(1)；
//     写法 B 固定 int[128]，空间 O(1)。
//
//   其他能过的解法（了解即可）：
//     - 暴力枚举所有子串，每个子串再用集合查重：O(n^3) 或 O(n^2)，
//       10^5 规模必超时，只能用来对拍。
//     - 动态规划：dp[i] 表示以 i 结尾的最长无重复子串长度，也能做，
//       但状态转移要考虑"上次出现位置是否在当前区间内"，本质和写法 B
//       一样，还多开了一个数组，没必要。
// ============================================================================

class Solution {
    public int lengthOfLongestSubstring(String s) {
        // 左边从第一个开始，右边从第二个，往后面
        int left = 0;
        // 吧字符串转为字符数组
        char[] chars = s.toCharArray();
        // 记录最长子串的长度，设为暂时答案，求最长的话，初值应该是尽量短的，设为零
        int ans = 0;
        // 遍历字符数组
        for (int right = 0; right < chars.length; right++) {
            // 判断当前字符是否在子串中，一直缩小区间，缩到区间里面没有重复的字符为止
            while (isSame(chars, left, right)) {
                // 如果在子串中，左边往右移动一位
                left++;
            }
            // 更新最长子串的长度
            ans = Math.max(ans, right - left + 1);
        }
        // 返回最长子串的长度
        return ans;
    }
    // 判断当前字符是否在子串中
    private boolean isSame(char[] chars, int left, int right) {
        // 遍历子串
        for (int i = left; i < right; i++) {
            // 如果当前字符在子串中，返回true
            if(chars[i] == chars[right])
                return true;
        }
        // 如果当前字符不在子串中，返回false
        return false;
    }
}
