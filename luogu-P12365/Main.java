// ============================================================================
// 洛谷 P12365 [蓝桥杯 2022 省 Python B] 纸张尺寸
// ----------------------------------------------------------------------------
// 题目描述
// 在 ISO 国际标准中定义了 A0 纸张的大小为 1189 mm × 841 mm，将 A0 纸沿长边对折后为 A1 纸，
// 大小为 841 mm × 594 mm，在对折的过程中长度直接取下整（实际裁剪时可能有损耗）。
// 将 A1 纸沿长边对折后为 A2 纸，依此类推。
// 输入纸张的名称，请输出纸张的大小。
//
// 输入格式
// 输入一行包含一个字符串表示纸张的名称，该名称一定是 A0、A1、A2、A3、A4、A5、A6、A7、A8、A9 之一。
//
// 输出格式
// 输出两行，每行包含一个整数，依次表示长边和短边的长度。
//
// 输入 #1
//   A0
// 输出 #1
//   1189
//   841
//
// 输入 #2
//   A1
// 输出 #2
//   841
//   594
//
// 输入 #3（补的样例：A4，平时最常见的纸，用来对一下中间过程）
//   A4
// 输出 #3
//   297
//   210
//
// 输入 #4（补的边界样例：A9，折的次数最多、数字最小；1189→594、841→420、297→148、105→52 都是折出半个的地方）
//   A9
// 输出 #4
//   52
//   37
//
// 说明/提示
// 原题没有【说明/提示】内容。原题时限 1 秒，内存 512 MB。蓝桥杯 2022 年省赛 Python B 组。
//
// 思路（只用 for 循环 + 两个变量 + 字符运算，没有任何高级函数）
//   把纸张看成两个数：长边 a、短边 b，一开始 A0 就是 a = 1189、b = 841。
//   每沿长边对折一次，发生两件事：
//     ① 长边被对半裁开、长度取下整，这一半变成新的短边；
//     ② 原来的短边没被动过，它变成新的长边。
//   所以每折一次就是：
//       int t = a / 2;   // 先把半个长边算出来存好
//       a = b;           // 原来的短边，成为新的长边
//       b = t;           // 折出来的那一半，成为新的短边
//   输入的 A? 里的数字就是折的次数：A0 一次都不折，A1 折 1 次，……，A9 折 9 次。
//   读法：用 sc.next() 读入 "A4" 这样的字符串，再 charAt(1) 取出字符 '4'，减去 '0' 就是整数 4。
//   循环折 k 次之后，先输出长边 a，再输出短边 b。
//   三个容易踩的地方：
//     ① 更新顺序：别写成 a = b; b = a / 2; —— 那时 a 已经被覆盖成旧的 b 了，
//        分母被换掉，答案就错了；一定要先把 a / 2 存进临时变量再动 a。
//     ② 长边短边每折一次就换位：折一次之后，1189 那一路剩下的 594 反而成了短边。
//        所以不能只盯着一条边折，每折一次都要重新确定谁是长、谁是短。
//     ③ 题目要求"长度直接取下整"，Java 里两个 int 相除本来就是下整（1189 / 2 = 594），
//        直接用 / 就行，不要用 double，也不要自己加 0.5 去四舍五入。
//   折满 9 次的完整过程（写完了拿它对答案）：
//     A0 1189×841 → A1 841×594 → A2 594×420 → A3 420×297 → A4 297×210 →
//     A5 210×148 → A6 148×105 → A7 105×74 → A8 74×52 → A9 52×37
//   规模：最多折 9 次，最后才 52、37 这么小，int 绰绰有余，不用 long。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        String s = sc.nextLine();
        sc.close();
        // 拿到对折的次数
        int n = s.charAt(1) - '0';
        // 定义初始的长和宽两边
        int l = 1189;
        int w = 841;
        // 循环折 n 次
        for(int i = 0; i < n; i++){
            // 先算出长边的一半，变成下一次的宽边
            int temp = l / 2;
            // 原来的宽边变成下一次的长边
            l = w;
            // 折出来的那一半变成下一次的宽边
            w = temp;
        }
        // 输出最终的结果
        System.out.println(l);
        System.out.println(w);
    }
}
