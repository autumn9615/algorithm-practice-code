// ============================================================================
// 力扣 852. 山脉数组的峰顶索引
// ----------------------------------------------------------------------------
// 题目描述
// 符合下列属性的数组 arr 称为 山脉数组：
//   1. arr.length >= 3；
//   2. 存在 i（0 < i < arr.length - 1）使得
//        arr[0] < arr[1] < ... < arr[i-1] < arr[i]，
//        并且 arr[i] > arr[i+1] > ... > arr[arr.length-1]。
// 给你由整数组成的山脉数组 arr，返回峰顶元素的下标 i，也就是上面那个
// "先严格递增、再严格递减"的转折点。
// 你必须设计并实现时间复杂度为 O(log n) 的解决方案。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int peakIndexInMountainArray(int[] arr)
//
// 输入 #1
//   arr = [0,1,0]
// 输出 #1
//   1
//
// 输入 #2
//   arr = [0,2,1,0]
// 输出 #2
//   1
//
// 输入 #3
//   arr = [0,10,5,2]
// 输出 #3
//   1
//   解释：10 在下标 1，比左右邻居都大，所以峰顶索引是 1。
//
// 输入 #4
//   arr = [24,69,100,99,79,78,67,36,26,19]
// 输出 #4
//   2
//   补的样例：100 在下标 2，峰很靠左，考验"答案在 mid 左边"的那一半。
//
// 输入 #5
//   arr = [0,1,2,3,4,5,6,7,9,8]
// 输出 #5
//   8
//   补的边界样例：峰在下标 8，正好是 n-2（合法峰位的最右端），
//   考验二分里读 arr[mid+1] 时会不会越界。
//
// 提示
//   1. 3 <= arr.length <= 10^5
//   2. 0 <= arr[i] <= 10^6
//   3. 题目数据保证 arr 是一个山脉数组
//
// 说明/提示
// 【样例说明】三个官方样例的答案都是 1，看着像"蒙 1 就能过"，其实只是
//   巧合：它们的峰正好都落在下标 1。样例 1 的 n = 3，而下标 1 既是合法
//   峰位的最左端，又是 n-2 最右端（n = 3 时两端重合），所以答案只能是 1。
//   样例 2、3 的峰也在下标 1，就没有任何必然性了，必须靠算法算出来。
// 【评测用例规模与约定】
//   n 最大 10^5，题面明确要求 O(log n)。线性扫一遍是 O(n)，10^5 虽然
//   也能跑完，但不符合题目要求，面试时会被追问。力扣难度：中等。
//
// 思路（把"找峰顶"变成"找第一个 arr[i] > arr[i+1] 的下标"，就是 lowerBound）
//   一、山脉数组长什么样
//     题面说得很清楚：arr 先严格递增、再严格递减，相邻元素不可能相等。
//       上山段：arr[i] < arr[i+1]（i < peak）
//       下山段：arr[i] > arr[i+1]（i >= peak）
//     峰顶 peak 就是这两段的分界线，而且 1 <= peak <= n-2（n >= 3）。
//
//   二、关键一步：把"找峰顶"翻译成"找第一个满足条件的位置"
//     定义条件 P(i) = arr[i] > arr[i+1]，i 只取 0 到 n-2：
//       i <  peak 时，arr[i] < arr[i+1]，P(i) 为假；
//       i >= peak 时，arr[i] > arr[i+1]，P(i) 为真。
//     所以 P 的取值一定是"假假假…假真真真…真"：前半段全假、后半段全真。
//     第一个 P(i) 为真的下标，正好就是 peak。
//     这就是 34 题写的 lowerBound，只是把"nums[mid] 和 target 比"
//     换成了"arr[mid] 和 arr[mid+1] 比"，套路一模一样。
//
//   三、写法 A：左闭右开模板（和 34 题的 lowerBound 同款，推荐）
//     int left = 0, right = arr.length - 1;   // 搜索下标范围 [0, n-2]
//     while (left < right) {
//         int mid = left + (right - left) / 2;
//         if (arr[mid] > arr[mid + 1]) {
//             right = mid;        // mid 满足条件，答案在 mid 或更左
//         } else {
//             left = mid + 1;     // mid 不满足，答案一定在 mid 右边
//         }
//     }
//     return left;                // 结束时 left == right，就是第一个真
//     为什么 right 初值写 n-1 而不是 n-2？因为这是右开区间：答案的上界
//     是 n-2，右边界要开到 n-1（不含）才能把 n-2 包进来。同理，mid 最大
//     只能到 n-2，所以读 arr[mid+1] 永远不会越界。
//
//   四、写法 B：开区间模板（和 875 题的 left + 1 < right 同款）
//     int left = -1;                    // 哨兵：P(-1) 一定为假
//     int right = arr.length - 2;       // P(n-2) 一定为真（peak <= n-2）
//     while (left + 1 < right) {
//         int mid = left + (right - left) / 2;
//         if (arr[mid] > arr[mid + 1]) right = mid;
//         else left = mid;
//     }
//     return right;
//     含义和 875 完全一样：left 永远是"已知不满足"的下标，right 永远是
//     "已知满足"的下标，区间缩到相邻时，right 就是第一个满足的。
//     两种写法是同一个二分的两种外观，挑顺手的就行；建议先练熟写法 A，
//     因为它和刚做完的 34 题 lowerBound 一字不差，少记一套模板。
//
//   五、拿样例走一遍（写法 A）
//     样例 1：arr = [0,1,0]，left = 0，right = 2
//       mid = 1：arr[1] = 1 > arr[2] = 0 成立 → right = 1
//       left = 0，right = 1：mid = 0：arr[0] = 0 > arr[1] = 1 不成立
//         → left = 1
//       left = right = 1，返回 1 ✓
//     样例 4：arr = [24,69,100,99,79,78,67,36,26,19]，left = 0，right = 9
//       mid = 4：79 > 78 成立 → right = 4
//       left = 0，right = 4：mid = 2：100 > 99 成立 → right = 2
//       left = 0，right = 2：mid = 1：69 > 100 不成立 → left = 2
//       left = right = 2，返回 2 ✓
//     样例 5：arr = [0,1,2,3,4,5,6,7,9,8]，left = 0，right = 9
//       mid = 4：4 > 5 不成立 → left = 5
//       left = 5，right = 9：mid = 7：7 > 9 不成立 → left = 8
//       left = 8，right = 9：mid = 8：9 > 8 成立 → right = 8
//       left = right = 8，返回 8 ✓
//
//   六、坑和边界
//     - 判断方向别写反：arr[mid] > arr[mid+1] 说明 mid 已经在"下山段"，
//       峰在 mid 或者更左边，所以是 right = mid（mid 自己还要留着）；
//       反过来 arr[mid] < arr[mid+1] 说明还在"上山段"，峰一定在右边，
//       所以是 left = mid + 1。写反了答案会跑到数组两端去。
//     - 要读 arr[mid+1]，所以 mid 最多只能到 n-2。右边界必须设成
//       n-1（写法 A 的右开区间）或 n-2（写法 B 的右哨兵），
//       绝不能把 n-1 当"闭区间右端点"用，那样 mid 可能取到 n-1，
//       arr[mid+1] 直接数组越界。
//     - 不用管 arr[mid] == arr[mid+1]：山脉数组是严格递增再严格递减，
//       相邻元素一定不相等，只有"大于"和"小于"两种情况，不用写三分支。
//     - 不用处理"没有峰"：题目保证是山脉数组且 n >= 3，答案一定在
//       [1, n-2] 里，不会是 0 或 n-1，所以 left = -1 这种哨兵是安全的。
//     - 这不是"在有序数组里找 target"：山脉数组整体是无序的，704 那种
//       nums[mid] 和 target 直接比大小的二分套不进来。这里能二分的真正
//       原因是条件 P(i) 单调（前假后真），跟数组整体是否有序无关。
//
//   七、复杂度
//     每次循环区间减半，最多 log2(10^5) ≈ 17 次，时间 O(log n)；
//     只用了 left、right、mid 三个变量，额外空间 O(1)。
//
//   其他能过的解法（了解即可）：
//     - 线性扫一遍，第一个 arr[i] > arr[i+1] 的 i 就是答案：O(n)，
//       10^5 也跑得完，但不符合题面的 O(log n) 要求。
//     - 三分法求极值：能做出答案，但这题的条件比三分简单得多，
//       没必要为了统一而绕远路。
//     - 拿 arr[mid] 和 arr[0] 之类去比：比较对象选错了，条件不单调，
//       二分的前提不成立，越写越乱。
// ============================================================================

class Solution {
    // 思路：山脉数组一定是"先严格上升、后严格下降"，所以只看相邻两个元素
    // arr[i] 和 arr[i+1] 就能判断 i 在山的哪一边：
    //   arr[i] <= arr[i+1] → 还在上坡，峰一定在 i 的右边；
    //   arr[i] >  arr[i+1] → 已经在下坡，峰在 i 或者 i 的左边。
    // 这个判断随着 i 增大是"先真后假"的（前半段全是上坡、后半段全是下坡），
    // 是单调的，所以可以二分：找"第一个下坡的位置"，它就是峰顶。
    // 和 34 题的 lowerBound 是同一个模板，只是把"nums[mid] 和 target 比"
    // 换成了"arr[mid] 和 arr[mid+1] 比"。
    public int peakIndexInMountainArray(int[] arr) {
        // 取左右边界，用开区间模板（和 875 一样）：
        // left 永远是"已知在峰左边"的位置，right 永远是"已知在峰右边"的位置，
        // 答案一定落在 (left, right) 里面，等它俩相邻时 right 就是答案。
        //
        // left = -1 是哨兵：峰不可能在下标 0（n >= 3 时 arr[0] < arr[1]），
        //   所以"峰在 -1 右边"永远成立，循环里也不会真的去访问 arr[-1]。
        // right = arr.length 也是哨兵：峰最多到 n-2（峰必须满足
        //   arr[peak] > arr[peak+1]，所以 peak + 1 <= n-1），
        //   所以"峰在 n 左边"也永远成立，同样不会真的去访问 arr[n]。
        //   （写成 arr.length - 1 也行，区间紧一点，结果完全一样）
        int left = -1;
        int right = arr.length;
        // 题目保证 n >= 3，这个分支其实走不到，纯属保险：
        // n = 1 时唯一的下标 0 就是峰
        if(arr.length == 1){
            return 0;
        }
        // 模板二分：区间是开区间 (left, right)，left + 1 == right 时区间里
        // 只剩一个位置，循环结束
        while (left + 1 < right){
            // 取中点，left + (right - left) / 2 是防溢出的写法
            // （本题 n <= 10^5，其实不会溢出，养成习惯而已）
            //
            // 这里读 arr[mid+1] 不会越界，原因：
            //   mid < right <= n，所以 mid <= n-1。mid 真要取到 n-1，
            //   得先让 left = n-2，可 left 只在"上坡"时才会被更新成 mid，
            //   山脉数组里最后一个上坡下标是 n-3，所以 left <= n-3、
            //   mid <= n-2，arr[mid+1] 最远只读到 arr[n-1]，安全。
            int mid = left + (right - left) / 2;
            // arr[mid] <= arr[mid+1]：mid 还在上坡，峰一定在 mid 右边，
            // mid 自己肯定不是峰，可以放心排除掉，所以 left = mid
            // （山脉数组相邻元素不会相等，这里写 <= 还是 < 结果一样）
            if(arr[mid] <= arr[mid+1]){
                left = mid;
            }else{
                // arr[mid] > arr[mid+1]：mid 已经在下坡了，峰只可能在 mid
                // 或者 mid 的左边，mid 自己还要留着，所以是 right = mid
                // （不是 mid - 1，因为 mid 本身可能就是峰）
                right = mid;
            }
        }
        // 循环结束时 left + 1 == right：
        // left 是最后一个"上坡"的位置，right 就是第一个"下坡"的位置，
        // 也就是峰顶下标，直接返回 right
        return right;
    }
}
