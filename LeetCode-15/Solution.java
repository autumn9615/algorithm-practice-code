// ============================================================================
// 力扣 15. 三数之和
// ----------------------------------------------------------------------------
// 题目描述
// 给你一个整数数组 nums，判断是否存在三元组 [nums[i], nums[j], nums[k]]
// 满足 i != j、i != k 且 j != k，同时还满足
// nums[i] + nums[j] + nums[k] == 0。
// 请你返回所有和为 0 且不重复的三元组。
// 注意：答案中不可以包含重复的三元组。返回的顺序无所谓。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public List<List<Integer>> threeSum(int[] nums)
//   返回的是"列表的列表"，每一组答案都要 new 一个 ArrayList 装起来。
//   本地编译需要 import java.util.*;（骨架里已经补上了）。
//
// 输入 #1
//   nums = [-1,0,1,2,-1,-4]
// 输出 #1
//   [[-1,-1,2],[-1,0,1]]
//   解释：有三对下标能和成 0，但值相同的三元组只能算一次，
//         所以去重后只剩 [-1,-1,2] 和 [-1,0,1] 两组。
//
// 输入 #2
//   nums = [0,1,1]
// 输出 #2
//   []
//   解释：唯一的组合 0+1+1 = 2，不等于 0，没有答案。
//
// 输入 #3
//   nums = [0,0,0]
// 输出 #3
//   [[0,0,0]]
//   解释：三个 0 相加是 0，且只能算一组。
//
// 输入 #4
//   nums = [0,0,0,0]
// 输出 #4
//   [[0,0,0]]
//   补的样例：四个 0，但答案仍然只有一组 [0,0,0]。
//   这组专抓"去重没做干净"——不去重会输出 4 组一模一样的 [0,0,0]。
//
// 输入 #5
//   nums = [-2,0,1,1,2]
// 输出 #5
//   [[-2,0,2],[-2,1,1]]
//   补的样例：左边有重复的 1，右边有 2，同时考验两种去重。
//
// 输入 #6
//   nums = [1,2,3]
// 输出 #6
//   []
//   补的边界样例：全是正数，三数之和不可能为 0。这组能检验"排序后
//   第一个数就大于 0 时直接退出"这个剪枝有没有写。
//
// 提示
//   1. 3 <= nums.length <= 3000
//   2. -10^5 <= nums[i] <= 10^5
//
// 说明/提示
// 【样例说明】样例 1 的输入里 -1 出现了两次、下标不同，但值一样，
//   所以只能贡献一次 [-1,0,1]。这就是"下标不重复"和"三元组不重复"
//   两个要求的区别，也是本题最难的一点。
// 【评测用例规模与约定】
//   n 最大 3000。三重暴力循环是 O(n^3) = 2.7*10^10，必超时；
//   排序 + 固定一个数 + 双指针是 O(n^2) = 9*10^6，绰绰有余。
//   元素范围 ±10^5，三数之和最大 3*10^5，int 完全够用，不会溢出。
//   力扣难度：中等。
//
// 思路（排序 + 固定第一个数 + 对撞双指针 + 三处去重）
//   一、为什么先排序
//     排序解决两个问题：
//       1. 让"对撞双指针"能用：有序数组里，和太小就往右移，和太大就往
//          左移，方向是确定的；
//       2. 让"去重"变简单：相同的值一定挨在一起，只要判断相邻元素是否
//          相等，就知道是不是重复。
//     所以第一步一定是 Arrays.sort(nums)，这题不排序没法做。
//
//   二、把三数之和变成"两数之和"
//     固定第一个数 nums[i]，问题就变成：在 i 后面的区间 [i+1, n-1] 里
//     找两个数，使它们的和等于 -nums[i]。
//     这不就是 167 那道"两数之和 II"吗？那边是有序数组 + 对撞双指针，
//     这里排序之后同样有序，于是直接套 167 的骨架。
//
//   三、双指针怎么走（和 167 一样）
//     left = i + 1，right = n - 1：
//       sum < 0  → left++（和太小，换大一点的数）
//       sum > 0  → right--（和太大，换小一点的数）
//       sum == 0 → 收下这组答案，然后 left++、right-- 继续找
//
//   四、去重（本题真正的难点，一共三处）
//     ① 第一层循环的 i 去重：
//        if (i > 0 && nums[i] == nums[i - 1]) continue;
//        如果当前数和前一个数一样，那以它为第一个数的所有组合，上一轮
//        已经全部找过了，直接跳过。注意是 continue 不是 break——
//        后面还有别的数要试。
//     ② 找到答案后，left 跳过重复：
//        while (left < right && nums[left] == nums[left + 1]) left++;
//     ③ 找到答案后，right 跳过重复：
//        while (left < right && nums[right] == nums[right - 1]) right--;
//        然后别忘了再 left++、right--，跳过当前这一组本身。
//     为什么要跳过？因为 [-2,1,1] 这种答案，如果左边有多个 1，
//     不跳过就会重复输出同一组。
//
//   五、代码骨架
//     Arrays.sort(nums);
//     List<List<Integer>> ans = new ArrayList<>();
//     for (int i = 0; i < nums.length - 2; i++) {
//         if (nums[i] > 0) break;                    // 剪枝：后面全是正数
//         if (i > 0 && nums[i] == nums[i - 1]) continue;   // ① i 去重
//         int left = i + 1, right = nums.length - 1;
//         while (left < right) {
//             int sum = nums[i] + nums[left] + nums[right];
//             if (sum == 0) {
//                 ans.add(Arrays.asList(nums[i], nums[left], nums[right]));
//                 // ② left 跳过重复
//                 while (left < right && nums[left] == nums[left + 1]) left++;
//                 // ③ right 跳过重复
//                 while (left < right
//                        && nums[right] == nums[right - 1]) right--;
//                 left++;
//                 right--;
//             } else if (sum < 0) {
//                 left++;
//             } else {
//                 right--;
//             }
//         }
//     }
//     return ans;
//
//   六、拿样例 1 走一遍（nums = [-1,0,1,2,-1,-4]）
//     排序后：[-4,-1,-1,0,1,2]
//     i=0 (-4)，target=4：left=1(-1)、right=5(2)，和 -3 < 0 → left 一路
//       右移，始终找不到，left 走到 5 结束。
//     i=1 (-1)，target=1：left=2(-1)、right=5(2)，-1-1+2=0 → 收下
//       [-1,-1,2]；左边不重复、右边不重复；left=3、right=4
//       此时 -1+0+1=0 → 收下 [-1,0,1]；left=4、right=3，结束。
//     i=2 (-1)：和前一个 -1 相同 → continue 跳过（这就是 ① 的作用）。
//     i=3 (0)，target=0：left=4(1)、right=5(2)，1+2=3 > 0 → right 左移，
//       很快 left == right，没有答案。
//     i=4 (1) > 0 → break（剪枝）。
//     结果 [[-1,-1,2],[-1,0,1]] ✓
//
//   七、坑和边界
//     - ★ 必须先排序，否则双指针的移动方向和去重都不成立。
//     - ★ i 去重写 continue 不是 break：值相同只代表"以它为第一个数"
//       重复了，不代表后面的 i 也都不行。
//     - ★ 找到答案后，跳过 left/right 的重复之后，还要再各走一步
//       （left++、right--），否则会在同一组上原地打转，甚至死循环。
//     - ★ 跳过重复时循环条件要带 left < right，不然可能越界。
//     - 剪枝 if (nums[i] > 0) break：排序后 i 及其右边全是正数，
//       三个正数不可能和为 0。注意是 break 不是 continue。
//     - 答案要 new ArrayList 或者用 Arrays.asList，不能把同一个 List
//       引用反复 add。
//     - 结果里三元组的顺序无所谓，力扣判题会排序后比较。
//     - 三数之和最大 3 * 10^5，int 够用，不用 long。
//     - 数组长度至少 3，循环写 i < nums.length - 2，保证右边还留两个数。
//
//   八、复杂度
//     排序 O(n log n)；外层 i 走 n 次，内层双指针总共 O(n)，所以
//     主体是 O(n^2)。n = 3000 时约 9*10^6 次，很快。
//     额外空间 O(1)（不算返回结果和排序用的栈）。
//
//   其他能过的解法（了解即可）：
//     - 三重暴力循环 O(n^3)，3000 规模必超时，只能用来对拍。
//     - 固定 i 后把问题变成两数之和，用 HashMap 找 partner：O(n^2) 时间，
//       但 O(n) 额外空间，还要自己处理重复，比双指针麻烦。
//     - 先全部塞进 HashSet 再去重：输出顺序和去重逻辑都很容易写错。
//
//   和前几题的关系：
//     167 两数之和 II → 本题的内层双指针就是它，只是 target 变成了
//     -nums[i]；283 同向双指针、344 对撞双指针，这题是把"对撞"用在了
//     排序后的子区间上。这三题串起来，双指针这一块就齐了。
// ============================================================================

import java.util.*;

class Solution {
    public List<List<Integer>> threeSum(int[] nums) {
        // 排序
        Arrays.sort(nums);
        // 固定第一个数
        List<List<Integer>> ans = new ArrayList<>();
        for (int i = 0; i < nums.length - 2; i++) {
            // 剪枝：后面全是正数，不可能出现和为 0 的情况
            if(nums[i] > 0) {
                break;
            }
            // 重复的第一个数跳过
            if (i > 0 && nums[i] == nums[i - 1]) {
                continue;
            }
            // 初始化双指针
            int left = i + 1, right = nums.length - 1;
            // 双指针遍历，和为 0 收答案
            while (left < right) {
                // 计算和
                int sum = nums[i] + nums[left] + nums[right];
                if (sum == 0) {
                    // 收答案
                    ans.add(Arrays.asList(nums[i], nums[left], nums[right]));
                    // 跳过重复的 left
                    while (left < right && nums[left] == nums[left + 1]) {
                        left++;
                    }
                    // 跳过重复的 right
                    while (left < right && nums[right] == nums[right - 1]) {
                        right--;
                    }
                    // 移动指针
                    left++;
                    right--;
                } else if (sum < 0) {
                    // 和小于 0，left 右移
                    left++;
                } else {
                    // 和大于 0，right 左移
                    right--;
                }
            }
        }
        return ans;
    }
}