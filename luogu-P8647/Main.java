// ============================================================================
// 洛谷 P8647 [蓝桥杯 2017 省 AB] 分巧克力
// ----------------------------------------------------------------------------
// 题目描述
// 儿童节那天有 K 位小朋友到小明家做客。小明拿出了珍藏的巧克力招待小朋友们。
// 小明一共有 N 块巧克力，其中第 i 块是 Hi × Wi 的方格组成的长方形。
// 为了公平起见，小明需要从这 N 块巧克力中切出 K 块巧克力分给小朋友们。切出
// 的巧克力需要满足：
//   1. 形状是正方形，边长是整数；
//   2. 大小相同（K 块互相一样大）。
// 例如一块 6 × 5 的巧克力可以切出 6 块 2 × 2 的巧克力或者 2 块 3 × 3 的
// 巧克力。
// 当然小朋友们都希望得到的巧克力尽可能大，你能帮小明计算出最大的边长是多少
// 么？
//
// 输入格式
// 第一行包含两个整数 N 和 K。（1 <= N, K <= 10^5）
// 以下 N 行每行包含两个整数 Hi 和 Wi。（1 <= Hi, Wi <= 10^5）
// 输入保证每位小朋友至少能获得一块 1 × 1 的巧克力。
//
// 输出格式
// 输出切出的正方形巧克力最大可能的边长。
//
// 输入 #1
//   2 10
//   6 5
//   5 6
// 输出 #1
//   2
//
// 输入 #2（补的边界样例：专门卡"拿面积去除"的写法——5 × 5 按面积 ÷3÷3 像是
//   能切 2 块，实际上连一块 3 × 3 都切不出来）
//   1 2
//   5 5
// 输出 #2
//   2
//
// 输入 #3（补的边界样例：最大规模。100000 × 100000 的一块要切 100000 块，
//   答案不是直觉上的 316：边长 316 时只能切 316 × 316 = 99856 块，差一点，
//   要退到 315 才够；这里面块数还会上到 10^10 量级，顺便考验 long）
//   1 100000
//   100000 100000
// 输出 #3
//   315
//
// 输入 #4（补的边界样例：又细又长的长方形。两条 100000 × 1 的巧克力合起来
//   面积有 20 万，但边长 2 的正方形一块都切不出来，答案只能是 1）
//   3 3
//   100000 1
//   1 100000
//   1 1
// 输出 #4
//   1
//
// 说明/提示
// 【样例说明】官方样例只有 #1 一组，验算：6 × 5 切 2 × 2 能出
//   (6 / 2) × (5 / 2) = 3 × 2 = 6 块，5 × 6 切 2 × 2 能出
//   (5 / 2) × (6 / 2) = 2 × 3 = 6 块，一共 12 块 >= 10 块，够分；再拿
//   3 × 3 试：(6 / 3) × (5 / 3) = 2 × 1 = 2 块，(5 / 3) × (6 / 3) = 1 × 2
//   = 2 块，一共只有 4 块，不够分。所以 2 行、3 不行，最大边长就是 2。
// 【补充样例说明】（都是我手算并用小暴力程序跑过的，可用来对答案）
//   #2：边长 2 时 (5 / 2) × (5 / 2) = 2 × 2 = 4 块，够 2 块；边长 3 时
//     (5 / 3) × (5 / 3) = 1 × 1 = 1 块，不够，所以答案是 2；要小心按
//     面积 5 × 5 ÷ (3 × 3) = 2 块来算会误判成 3；
//   #3：边长 315 时 (100000 / 315) × (100000 / 315) = 317 × 317 = 100489
//     块，够 100000 块；边长 316 时 (100000 / 316) × (100000 / 316) =
//     316 × 316 = 99856 块，不够，所以答案是 315；
//   #4：边长 1 时 100000 + 100000 + 1 = 200001 块，够 3 块；边长 2 时
//     (100000 / 2) × (1 / 2) = 0 块、0 块、0 块，一共 0 块，不够，所以
//     答案是 1。
// 【评测用例规模与约定】
//   1 <= N, K <= 10^5；1 <= Hi, Wi <= 10^5；输入保证每位小朋友至少能获得
//   一块 1 × 1 的巧克力（等价于所有巧克力面积加起来 >= K，所以答案一定
//   存在，且至少是 1，不用特判无解）。
//   洛谷标注时限 1 秒，内存 256 MB。洛谷「说明/提示」原文：蓝桥杯 2022 省
//   赛 A 组 I 题。（原文如此，和标题写的 2017 省 AB 对不上，不影响做题。）
//
// 思路（只用数组、for / while 循环和 if，没有任何高级函数）
//   暴力想法是让边长 L 从 1 往上一个个试：L 最多到 100000，每试一次要
//   扫 N 块（最多 10^5 块），乘起来 10^10 太大了。注意到一个重要的单调
//   性：边长越大，同一批巧克力能切出的块数只会越少，绝不会变多。所以
//   "L 行不行"是干净的一刀切：小的 L 全都行、大的 L 全不行，我们要找的
//   就是最后一个行的 L——这正好是二分查找的拿手戏，最多只需要试
//   log2(100000) ≈ 17 次。
//
//   先想清楚"给定边长 L，一共能切出多少块正方形"：对第 i 块 Hi × Wi 的
//   巧克力，横着能排 Hi / L 个、竖着能排 Wi / L 个，整数除法正好就是
//   "向下取整"，这块贡献 (Hi / L) * (Wi / L) 块；把 N 块全部加起来就是
//   总块数，>= K 就说明 L 行。必须是两个方向各自取整再相乘，不能拿面积
//   Hi * Wi / (L * L) 来除（补充样例 #2 就是专门卡这个的）。
//
//   二分的写法（"找最后一个满足条件的值"，很经典的模板）：
//   ① 用 lo = 1、hi = 100000 圈定答案范围；
//   ② while (lo <= hi)：取中点 mid = (lo + hi) / 2，数一遍按 mid 能切
//      多少块；
//   ③ 够 K 块：mid 行，先记 ans = mid，再往大了试，lo = mid + 1；
//   ④ 不够：mid 太大，往小了试，hi = mid - 1；
//   ⑤ 循环结束，ans 就是最大边长。
//
//   几个要想清楚的点：
//   ① 总块数必须用 long，不能用 int！(Hi / L) 和 (Wi / L) 最大都是
//      10^5，相乘最大 10^10，早就超过 int 的范围了。建议写成
//      (long)(h / mid) * (w / mid)：先把一个因子转成 long，乘出来才是
//      long；如果两个 int 先乘完再赋给 long，那已经晚了（中间就爆了）。
//   ② 每次检查一旦块数 >= K 就可以直接收手（后面的块不用数了）。本题
//      不提前退出也完全够快（17 × 10^5 次运算），但顺手写上是个好习惯。
//   ③ 上界取 100000 就行（题面给的最大边长），哪块都不够这个尺寸也没
//      关系，检查一下自然就说不行。
//   ④ 输出的是边长这个整数，不是块数，别写错。
//   ⑤ 不同巧克力之间不能拼：每块自己管自己，切开不能跨块拼成正方形，
//      N 块的结果相加就完了。
//   ⑥ 二分最容易写错的是 lo、hi 的更新：能行就 lo = mid + 1，不行就
//      hi = mid - 1，配上 while (lo <= hi)，不会死循环；别图省事写成
//      lo = mid，容易原地打转。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        // 读入 N、K
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        int k = sc.nextInt();
        // 读入每块巧克力的高、宽
        int[] h = new int[n];
        int[] w = new int[n];
        for (int i = 0; i < n; i++) {
            h[i] = sc.nextInt();
            w[i] = sc.nextInt();
        }
        sc.close();
        // 二分查找最大边长
        int lo = 1, hi = 100000, ans = 1;
        while (lo <= hi) {
            int mid = (lo + hi) / 2;
            // 用 long 存总块数
            long count = 0; 
            for (int i = 0; i < n; i++) {
                // 计算第 i 块能切出的块数
                count += (long)(h[i] / mid) * (w[i] / mid); 
                if (count >= k){
                    // 一旦够了就可以提前退出
                    break; 
                } 
            }
            if (count >= k) {
                // mid 行，记下答案
                ans = mid; 
                // 往大了试
                lo = mid + 1; 
            } else {    
                // mid 不行，往小了试
                hi = mid - 1; 
            }
        }
        System.out.println(ans);
    }
}
