// ============================================================================
// 洛谷 P16302 [蓝桥杯 2026 省 Java C 组] 幸运约会日
// ----------------------------------------------------------------------------
// 题目描述
// 小明是个浪漫的程序员，他想要在一个特殊的日期向心仪的女孩表白。他认为如果
// 一个日期的年、月、日三个数字的数字和都相等，那这就是一个"幸运约会日"。
// 数字和是指一个数字各位数字之和。例如：
//   2026 的数字和为 2 + 0 + 2 + 6 = 10
//   12 的数字和为 1 + 2 = 3
//   25 的数字和为 2 + 5 = 7
// 给定一个日期，请你帮小明判断这是否是一个幸运约会日。
//
// 输入格式
// 第一行包含一个整数 T，表示测试用例的数量。
// 接下来 T 行，每行包含三个整数 Y、M、D，分别表示年、月、日。
//
// 输出格式
// 对于每个测试用例，如果是幸运约会日，输出 YES，否则输出 NO。
//
// 输入 #1
//   3
//   2026 12 7
//   2020 4 13
//   1111 1 3
// 输出 #1
//   NO
//   YES
//   NO
//
// 输入 #2（补的边界样例：月和日都是两位数，专门考"12 的数字和是 1 + 2 = 3"，
//   而不是拿 12 这个原数去比）
//   1
//   2001 12 12
// 输出 #2
//   YES
//
// 输入 #3（补的边界样例：Y 取最小值 1000，数字和是 1；M、D 取最小值 1，
//   数字和就是 1 本身，最"巧"的一天）
//   1
//   1000 1 1
// 输出 #3
//   YES
//
// 输入 #4（补的边界样例：Y 取最大值 9999，数字和高达 36，月、日再大也追
//   不上，不可能相等）
//   1
//   9999 12 31
// 输出 #4
//   NO
//
// 说明/提示
// 【样例说明】官方三组样例逐个验算：
//   #1 2026 年 12 月 7 日：2026 的数字和 2 + 0 + 2 + 6 = 10，12 的数字和
//     1 + 2 = 3，7 的数字和 7；10、3、7 互不相等，不是幸运约会日，输出 NO；
//   #2 2020 年 4 月 13 日：2020 的数字和 2 + 0 + 2 + 0 = 4，4 的数字和 4，
//     13 的数字和 1 + 3 = 4；4 = 4 = 4，是幸运约会日，输出 YES；
//   #3 1111 年 1 月 3 日：1111 的数字和 1 + 1 + 1 + 1 = 4，1 的数字和 1，
//     3 的数字和 3；4、1、3 互不相等，不是幸运约会日，输出 NO。
// 【补充样例说明】（都是我按数字和算好后写进去的，可用来对答案）
//   #2：2001 -> 2 + 0 + 0 + 1 = 3，12 -> 1 + 2 = 3，12 -> 1 + 2 = 3，
//     三边相等，输出 YES；
//   #3：1000 -> 1 + 0 + 0 + 0 = 1，1 -> 1，1 -> 1，三边相等，输出 YES；
//   #4：9999 -> 9 + 9 + 9 + 9 = 36，12 -> 1 + 2 = 3，31 -> 3 + 1 = 4，
//     36 既不等于 3 也不等于 4，输出 NO。
// 【评测用例规模与约定】
//   1 <= T <= 1000；1000 <= Y <= 9999（保证是有效的年份）；
//   1 <= M <= 12（保证是有效的月份）；1 <= D <= 31（保证是有效的日期）。
//   保证给定的日期都是实际存在的有效日期。
// 洛谷标注时限 3 秒，内存 512 MB。蓝桥杯 2026 年省赛，这道是 Java C 组。
//
// 思路（只用了 while 循环和 if，没有任何高级函数）
//   核心就一件事：求一个整数的数字和。写法是从个位开始一位一位地抠：每次
//   用 x % 10 取到当前个位上的数字，累加进总和，再 x /= 10 把这个个位去掉，
//   循环到 x 变成 0 为止，累加出来的就是数字和。比如 2026：依次抠出 6、2、
//   0、2，加起来是 10。一位数（M、D 经常是个位数）循环一次就结束，数字和
//   就是它本身，不用特判。
//   对每组数据：分别求出 Y、M、D 的数字和记成 sy、sm、sd，判断
//   sy == sm && sm == sd 是否成立：成立输出 YES，否则输出 NO。
//
//   几个要想清楚的点：
//   ① 三个和相等只要写 sy == sm && sm == sd 就够了（前两个相等且后两个
//      相等，三个自然全相等），不用再写 sy == sd。
//   ② 别写成"拿 Y、M、D 原数去比"：样例 #1 里 12 的数字和是 3，直接拿 12
//      去比就错了；这也是补充样例 #2 专门卡的。
//   ③ 题目保证给的日期都是真实存在的（M、D 的取值和日历都合法），所以
//      完全不用判闰年、大小月，别自己加戏。
//   ④ 输入量很小（最多 1000 组、3000 多个整数），Scanner 的 nextInt() 逐个
//      读完全够快，不用快读。
//   ⑤ 输出的是大写的 YES / NO，一组一行，注意别写错大小写或输出中文。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 读入 T，表示共有 T 组测试数据
        int T = sc.nextInt();
        // 循环处理每组数据
        for (int i = 0; i < T; i++) {
            // 读入 Y、M、D
            int Y = sc.nextInt();
            int M = sc.nextInt();
            int D = sc.nextInt();
            // 分别计算 Y、M、D 的数字和
            int sy = digitSum(Y);
            int sm = digitSum(M);
            int sd = digitSum(D);
            // 判断三个数字和是否相等
            if (sy == sm && sm == sd) {
                System.out.println("YES");
            } else {
                System.out.println("NO");   
            }
        }
        sc.close();
    }
    // 计算一个整数的数字和
    static int digitSum(int x){
        int sum = 0;
        while(x > 0){
            // 取出当前个位数字，累加到 sum
            sum = sum + (x % 10);
            // 去掉当前个位数字
            x = x /10;
        }
        return sum;
    }
}
