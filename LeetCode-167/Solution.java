// ============================================================================
// 力扣 167. 两数之和 II - 输入有序数组
// ----------------------------------------------------------------------------
// 题目描述
// 给你一个下标从 1 开始的整数数组 numbers，该数组已按非递减顺序排列
// （可能有重复元素），请你从数组中找出满足相加之和等于目标数 target 的
// 两个数。
// 设这两个数分别是 numbers[index1] 和 numbers[index2]，则
// 1 <= index1 < index2 <= numbers.length。
// 以长度为 2 的整数数组 [index1, index2] 的形式返回这两个整数的下标。
// 你可以假设每个输入只对应唯一的答案，而且你不可以重复使用相同的元素。
// 你所设计的解决方案必须只使用常量级的额外空间。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int[] twoSum(int[] numbers, int target)
//
// 输入 #1
//   numbers = [2,7,11,15], target = 9
// 输出 #1
//   [1,2]
//   解释：2 + 7 = 9，下标 1 和 2（注意是 1 开始计数）。
//
// 输入 #2
//   numbers = [2,3,4], target = 6
// 输出 #2
//   [1,3]
//   解释：2 + 4 = 6。
//
// 输入 #3
//   numbers = [-1,0], target = -1
// 输出 #3
//   [1,2]
//   解释：-1 + 0 = -1。最短的数组（n = 2），两个指针一开始就相邻。
//
// 输入 #4
//   numbers = [5,25,75], target = 100
// 输出 #4
//   [2,3]
//   补的样例：答案藏在数组尾部，left 要跨过 5 才能找到，考验
//   "sum 太小就 left++"这个方向会不会走。
//
// 输入 #5
//   numbers = [1,2,3,4,4,56,90], target = 8
// 输出 #5
//   [4,5]
//   补的样例：答案由两个相同的 4 组成，考验"不能重复用同一个元素"——
//   必须是 4(下标4) + 4(下标5) 两个不同位置的元素。
//
// 输入 #6
//   numbers = [0,0,3,4], target = 0
// 输出 #6
//   [1,2]
//   补的样例：target = 0，两个 0 相加。别因为"和为 0 好像不存在"就把
//   等号判断漏了。
//
// 提示
//   1. 2 <= numbers.length <= 3 * 10^4
//   2. -1000 <= numbers[i] <= 1000
//   3. numbers 按非递减排序
//   4. -1000 <= target <= 1000
//   5. 只存在一个有效答案
//
// 说明/提示
// 【样例说明】和第 1 题（两数之和）的三个区别：
//   1. 数组有序（1 题无序）→ 可以用双指针 / 二分，不用哈希表；
//   2. 下标从 1 开始（1 题从 0 开始）→ 返回时要 +1，最坑人的一条；
//   3. 必须常量额外空间（1 题没这要求）→ 哈希表解法直接被禁。
// 【评测用例规模与约定】
//   n 最大 3*10^4。O(n^2) 暴力双重循环最坏 9*10^8 次，会超时；
//   元素和 target 都在 [-1000, 1000]，两数之和最大 2000、最小 -2000，
//   int 完全够用，本题不涉及溢出问题。力扣难度：中等。
//
// 思路（对撞双指针：left、right 从两端往中间挤，344 题的骨架 + 新的判断逻辑）
//   一、为什么有序就能用对撞双指针
//     设当前看的是 numbers[left] 和 numbers[right]，记 sum = 两数之和：
//       sum <  target：left 太小了。right 已经是最大的那批，换 right 只会
//                      更小，所以只能 left++，用大一点的数试试。
//       sum >  target：right 太大了。left 已经是最小的那批，换 left 只会
//                      更大，所以只能 right--，用小一点的数试试。
//       sum == target：找到了，直接返回。
//     每一步都让 left 和 right 之间的距离缩小 1，所以最多 n-1 步就结束。
//
//   二、为什么不会漏掉正确答案（本题的核心证明）
//     关键在于"移动指针时，扔掉的那个数一定不是答案的一半"。
//     假设正确答案是 (i, j)，i < j。双指针从两端出发，先看 left 会不会
//     越过 i：
//       - 如果某一步 sum < target 导致 left++，把 left = i 扔掉了，那说明
//         numbers[i] + numbers[right] < target，而 right >= j 时
//         numbers[j] <= numbers[right]，所以 numbers[i] + numbers[j] 更小，
//         (i, j) 根本不是答案，矛盾。
//       - 同理 sum > target 时扔掉的 right 也证明不是答案的一半。
//     所以只要答案存在，两个指针一定会在 (i, j) 相遇，一个都不会漏。
//     直观理解：每次移动都排除掉一整行或一整列的候选，像在有序矩阵里
//     爬楼梯，答案所在的行和列永远不会被整体删掉。
//
//   三、代码骨架（left < right，不是 <=）
//     int left = 0, right = numbers.length - 1;
//     while (left < right) {
//         int sum = numbers[left] + numbers[right];
//         if (sum == target) {
//             return new int[]{left + 1, right + 1};   // ★ 下标 +1
//         } else if (sum < target) {
//             left++;      // 和太小，左指针右移
//         } else {
//             right--;     // 和太大，右指针左移
//         }
//     }
//     return new int[]{-1, -1};   // 题目保证有解，这行实际到不了，纯保险
//
//   四、拿样例 1 走一遍（numbers = [2,7,11,15], target = 9）
//     left=0, right=3：2 + 15 = 17 > 9 → right-- → right=2
//     left=0, right=2：2 + 11 = 13 > 9 → right-- → right=1
//     left=0, right=1：2 + 7 = 9 == 9 → 返回 [0+1, 1+1] = [1,2] ✓
//     样例 4（target = 100）：5+75=80 < 100 → left++；
//     25+75=100 → 返回 [2,3] ✓
//
//   五、坑和边界
//     - ★ 返回下标要 +1：题目是 1-indexed，numbers[0] 叫"第 1 个"。
//       直接 return {left, right} 就是这道题最常见的错。
//     - 循环条件是 left < right，不是 <=：left == right 意味着两个指针
//       指向同一个元素，等于"同一个元素用了两次"，题目明令禁止。
//     - 值可以是负数（-1000 起步），判断大小别写"和是正数就……"
//       这种想当然的假设；target 也可能是负数（样例 3）。
//     - 两个相同的数也能组答案（样例 5 的 4+4）：双指针天然处理得了，
//       因为它们是两个不同下标，不需要任何特判。
//     - 不要用 nums[i] == nums[j] 之类的条件去跳过重复元素：
//       本题答案唯一，指针移动规则本身就能保证不漏，画蛇添足容易跳过头。
//
//   六、复杂度
//     每轮 left 和 right 的距离至少缩 1，最多 n-1 轮，时间 O(n)；
//     只用 left、right 两个变量，额外空间 O(1)，正好满足题面的
//     "常量级额外空间"——这也是哈希表解法被禁的原因。
//
//   进阶：三种解法横向对比（和第 1 题对照着记）
//     1. 暴力双重循环：O(n^2) 时间，O(1) 空间，会超时；
//     2. 哈希表（第 1 题的解法）：O(n) 时间，O(n) 空间，答案对但
//        违反本题"常量空间"的要求；
//     3. 对撞双指针（本题）：O(n) 时间，O(1) 空间——它能把空间降到
//        O(1) 靠的就是"数组有序"这个额外信息，这是本题和第 1 题
//        唯一的本质区别。
//     还有个二分解法：固定一个数，在剩下的区间里二分找 target - x，
//     O(n log n)，能用但比双指针慢，且代码更长，知道即可。
//
//   其他能过的解法（了解即可）：
//     - 从 left 开始对每个数二分找 partner：O(n log n)，常数比双指针大。
//     - 先用哈希表存值再查：O(n) 空间，违反题面要求。
// ============================================================================

class Solution {
    public int[] twoSum(int[] numbers, int target) {
        // 定义双指针，初始时一个指向序列头部，一个指向序列尾部
        int left = 0;
        int right = numbers.length - 1;
        // 当左指针小于右指针时，进行循环
        while(left < right){
            // 计算当前左右指针之和
            int sum = numbers[left] + numbers[right];
            // 如果和等于目标值，返回左右指针的下标+1（因为数组是从1索引开始的，题目规定）
            if(sum == target){
                return new int[]{left + 1,right + 1};
            }else if(sum < target){
                // 如果和小于目标值，左指针右移，使得和变大
                left++;
            }else{
                // 如果和大于目标值，右指针左移，使得和变小
                right--;
            }
        }
        // 没找到，返回[-1,-1]
        return new int[]{-1,-1};
    }
}
