// ============================================================================
// 洛谷 P16284 [蓝桥杯 2026 省 Python A 组] 音乐节拍器
// ----------------------------------------------------------------------------
// 题目描述
// 小明在学习音乐，他发现不同乐器的演奏需要配合不同的节拍。现在有 N 种乐器，
// 每种乐器都有自己的"节拍周期"（以秒为单位）。
// 在音乐演奏中，如果某一时刻恰好是某个乐器节拍周期的整数倍，那么这个乐器就会
// 在这一时刻发声。例如，一个节拍周期为 3 秒的乐器会在第 3 秒、第 6 秒、第 9 秒
// 等时刻发声。
// 小明想知道：在前 T 秒内（即第 1 秒至第 T 秒，包含第 T 秒），恰好有 K 种乐器
// 同时发声的时刻有多少个？
//
// 输入格式
// 第一行包含三个整数 N、T、K，分别表示乐器数量、观察的时长、同时发声的乐器数量。
// 第二行包含 N 个整数 p1, p2, ..., pN，表示每种乐器的节拍周期（单位：秒）。
//
// 输出格式
// 一行，输出一个整数，表示恰好有 K 种乐器同时发声的时刻数量。
//
// 输入 #1
//   3 12 2
//   2 3 4
// 输出 #1
//   3
//
// 输入 #2
//   4 20 3
//   2 3 5 6
// 输出 #2
//   3
//
// 输入 #3
//   5 100 1
//   7 11 13 17 19
// 输出 #3
//   36
//
// 输入 #4（补的边界样例：两种乐器周期相同，要各算一种；第 0 秒不算）
//   2 10 2
//   3 3
// 输出 #4
//   3
//
// 输入 #5（补的边界样例：周期比 T 大的乐器一秒都不会响；第 T 秒本身包含在内）
//   3 42 3
//   2 3 7
// 输出 #5
//   1
//
// 说明/提示
// 【样例说明 1】周期为 2、3、4 的乐器：前 12 秒内恰好 2 种乐器发声的时刻是
//   t = 4、6、8，共 3 个（t = 12 时三种乐器都响，不算）。
// 【样例说明 2】周期为 2、3、5、6 的乐器：乐器 1、2、4 的最小公倍数是 6，
//   它们在时刻 6、12、18 同时发声；周期为 5 的乐器这三次都不发声，
//   所以恰好 3 种，共 3 个。
// 【样例说明 3】原题没有给逐时刻的表。答案是 36，已经用暴力算法验证：
//   7、11、13、17、19 在 1..100 内的倍数一共 14 + 9 + 7 + 5 + 5 = 40 个
//   "乐器-时刻"；其中 77 = 7 * 11 和 91 = 7 * 13 这两个时刻有两种乐器同时响
//   （所有两两乘积里只有这两个不超过 100，更不可能有三种叠加），
//   这两个时刻各占 2 个"乐器-时刻"，都不属于"恰好 1 种"，
//   所以恰好 1 种的时刻 = 40 - 4 = 36 个。
// 【评测用例规模与约定】
//   对于 30% 的评测用例：N <= 5，T <= 100；
//   对于 60% 的评测用例：N <= 10，T <= 1000；
//   对于所有评测用例：1 <= N <= 20，1 <= T <= 10000，1 <= K <= N，1 <= p_i <= 100。
// 洛谷标注时限 3 秒，内存 512 MB。蓝桥杯 2026 年省赛 Python A 组。
//
// 思路（只用最基础的数组 + for 循环 + if，不涉及任何高级函数）
//   直接一秒一秒地暴力数：
//     t 从 1 数到 T，对每一秒再从头看一遍 N 个乐器：
//     只要 t % p_i == 0，第 i 种乐器就在这一秒发声，计数器 cnt 加一；
//     这一秒数完后，如果 cnt 正好等于 K，答案 ans 加一，然后看下一秒。
//   O(T * N) = 10000 * 20 = 20 万次取余判断，3 秒时限、512 MB 内存绰绰有余，
//   不需要最小公倍数、容斥之类的高级做法。
//
//   几个要想清楚的点：
//   ① 周期可以重复。两种乐器周期相同（比如都是 3 秒）时，它们同一秒一起发声，
//      必须各算一种（cnt 要加两次），不能去重——题目数的是"乐器种数"。
//      把 N 个周期都存进数组、逐个判断，自然不会漏。
//   ② 周期比 T 大的乐器不用特判：t 在 1..T 里都小于 p_i 时 t % p_i = t != 0，
//      判断自然为假，它不会被算进去。
//   ③ 时刻从第 1 秒数到第 T 秒（包含第 T 秒），千万别从第 0 秒开始数——
//      0 是任何周期 p_i 的倍数，t = 0 会把全部 N 种乐器都算成发声，多算一个时刻。
//   ④ 数据都很小：答案最多是 T（每一秒最多贡献一个时刻），T <= 10000，
//      int 完全够用，输入也全用 nextInt() 读即可。
//   ⑤ 注意本题的 T 是"观察的时长"，不是测试组数：本题只有一组数据，
//      读完 N、T、K 和 N 个周期就算这一组，不要写读多组的循环。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 读入 N、T、K
        int N = sc.nextInt();
        int T = sc.nextInt();
        int K = sc.nextInt();
        // 读入 N 个乐器的节拍周期
        int[] p = new int[N];
        for (int i = 0; i < N; i++) {
            p[i] = sc.nextInt();    
        }
        sc.close();
        // 循环判断答案
        int ans = 0;
        // 外循环表示每一秒
        for(int i = 0; i <= T; i++){
            // 记录这一秒有多少种乐器发声
            int cut = 0;
            if(i == 0){
                // 第 0 秒不算
                continue;
            }
            // 内循环表示每一种乐器
            for(int j = 0; j < N; j++){
                // 如果这一秒是第 j 种乐器的节拍周期的整数倍
                if(i % p[j] == 0){
                    cut++;
                }
            }
            // 如果这一秒恰好有 K 种乐器发声
            if(cut == K){
                ans++;
            }
        }
        // 输出答案
        System.out.println(ans);
    }
}
