// ============================================================================
// 洛谷 P8665 [蓝桥杯 2018 省 A] 航班时间
// ----------------------------------------------------------------------------
// 题目描述
// 小 h 前往美国参加了蓝桥杯国际赛。小 h 的女朋友发现小 h 上午十点出发，上午
// 十二点到达美国，于是感叹到“现在飞机飞得真快，两小时就能到美国了”。
// 小 h 对超音速飞行感到十分恐惧。仔细观察后发现飞机的起降时间都是当地时间。
// 由于北京和美国东部有 12 小时时差，故飞机总共需要 14 小时的飞行时间。
// 不久后小 h 的女朋友去中东交换。小 h 并不知道中东与北京的时差。但是小 h 得到
// 了女朋友来回航班的起降时间。小 h 想知道女朋友的航班飞行时间是多少。
// 对于一个可能跨时区的航班，给定来回程的起降时间。假设飞机来回飞行时间相同，
// 求飞机的飞行时间。
//
// 输入格式
// 从标准输入读入数据。一个输入包含多组数据。
// 第一行为一个正整数 T，表示输入数据组数。
// 每组数据包含两行，第一行为去程的起降时间，第二行为回程的起降时间。
// 起降时间的格式如下
//   h1:m1:s1 h2:m2:s2
// 或
//   h1:m1:s1 h3:m3:s3 (+1)
// 或
//   h1:m1:s1 h4:m4:s4 (+2)
// 表示该航班在当地时间 h1 时 m1 分 s1 秒起飞：
//   第一种格式表示在当地时间 当日 h2 时 m2 分 s2 秒降落；
//   第二种格式表示在当地时间 次日 h3 时 m3 分 s3 秒降落；
//   第三种格式表示在当地时间 第三天 h4 时 m4 分 s4 秒降落。
// 对于此题目中的所有以 h:m:s 形式给出的时间，保证 0 <= h <= 23、
// 0 <= m, s <= 59。
//
// 输出格式
// 输出到标准输出。对于每一组数据输出一行一个时间 hh:mm:ss，表示飞行时间为
// hh 小时 mm 分 ss 秒。
// 注意，当时间为一位数时，要补齐前导零。如三小时四分五秒应写为 03:04:05。
//
// 输入 #1（官方样例，3 组数据）
//   3
//   17:48:19 21:57:24
//   11:05:18 15:14:23
//   17:21:07 00:31:46 (+1)
//   23:02:41 16:13:20 (+1)
//   10:19:19 20:41:24
//   22:19:04 16:41:09 (+1)
// 输出 #1
//   04:09:05
//   12:10:39
//   14:22:05
//
// 输入 #2（补的最简样例：没有时差（两行时长完全一样），平均下来还是它自己；
//   先拿它把"读入 + 平均 + 补零输出"这条链路跑通）
//   1
//   12:00:00 14:00:00
//   06:00:00 08:00:00
// 输出 #2
//   02:00:00
//
// 输入 #3（补的边界样例：只有去程带跨天标记，回程不跨天；两行时长一个 27 小时
//   一个 1 小时，差得越夸张，"平均"这一步写错越容易露馅）
//   1
//   00:00:00 03:00:00 (+1)
//   00:00:00 01:00:00
// 输出 #3
//   14:00:00
//
// 输入 #4（补的边界样例：(+2) 标记。顺带证明：想合法地出现 (+2)，只能飞满
//   24 小时且时差刚好 24 小时，去程时长正好 48 小时、回程 0 秒——理由是
//   "回程时长 = 飞行时间 - 时差"不能为负，见下面坑 ③。答案是 24:00:00，
//   专门测解析器认不认 (+2) 里那个数字，别只写死 +1）
//   1
//   00:00:00 00:00:00 (+2)
//   10:00:00 10:00:00
// 输出 #4
//   24:00:00
//
// 说明/提示
// 【样例说明】官方样例 3 组，逐个验（下面 h:m:s 都换算成秒再减）：
//   组 1：去程 21:57:24 - 17:48:19 = 14945 秒；回程 15:14:23 - 11:05:18 =
//     14945 秒；平均仍是 14945 秒 = 4 小时 9 分 5 秒 → 04:09:05，与样例一致。
//   组 2：去程 17:21:07 → 次日 00:31:46，按 24:31:46 算，减掉 17:21:07 得
//     25839 秒；回程 23:02:41 → 次日 16:13:20，按 40:13:20 算，减掉 23:02:41
//     得 61839 秒；(25839 + 61839) / 2 = 43839 秒 = 12 小时 10 分 39 秒 →
//     12:10:39，与样例一致。
//   组 3：去程 20:41:24 - 10:19:19 = 37325 秒；回程 40:41:09 - 22:19:04 =
//     66125 秒；平均 51725 秒 = 14 小时 22 分 5 秒 → 14:22:05，与样例一致。
// 【补充样例说明】#2 到 #4 都是用参考程序实际跑过的，可以直接拿去对答案：
//   #2：两行时长都是 7200 秒（2 小时），平均 7200 秒 = 02:00:00；
//   #3：去程 27 小时（97200 秒）、回程 1 小时（3600 秒），平均 50400 秒 =
//     14:00:00（就是"时差 13 小时、飞行 14 小时"那个航班）；
//   #4：去程 48 小时（172800 秒）、回程 0 秒，平均 86400 秒 = 24:00:00。
// 【评测用例规模与约定】
//   题面没有给 T 的上限（洛谷原题 T 很小，几十组）；提示里保证输入时间合法，
//   且飞行时间不超过 24 小时。
//   洛谷标注时限 1 秒、内存 128 MB；洛谷难度：普及-。
//   蓝桥杯 2018 年（第九届）省赛 A 组。
//
// 思路（split 拆串 + 把时间化成秒 + 两个方向的时长取平均，都是 Java 算法题
//   常见写法）
//   整题拆成四步：① 一行拆成"起飞 / 降落 / 可能的 (+k) 标记" → ② 各段化成
//   秒、带跨天标记的把降落时间加上 86400 的整数倍 → ③ 两个方向的时长相加
//   除以 2 → ④ 按 hh:mm:ss 补零输出。
//
//   第一步：核心公式——为什么"不知道时差"也能算
//   设飞行时间 F（去程回程一样），设 Δ = 目的地当地时间 - 出发地当地时间。
//   去程那一行算出来的"降落 - 起飞"，钟表上走过的时间既包含飞行、又包含时差：
//     去程钟表差 = F + Δ
//   回程是反着飞的，时差的方向也跟着反过来：
//     回程钟表差 = F - Δ
//   两式一加，Δ 正好抵消，结果等于 2F，于是
//     F = (去程钟表差 + 回程钟表差) / 2
//   拿题面开头那个故事对一遍：北京上午 10:00 起飞、美国当地时间 12:00 落地，
//   钟表差 2 小时；美国东部比北京晚 12 小时（Δ = -12），所以 F = 2 - (-12)
//   = 14 小时，和题面"总共需要 14 小时的飞行时间"对得上。这就是全题的钥匙，
//   题目也正是靠"来回各给一行、时差一正一负互相抵消"才让你不必知道 Δ。
//
//   第二步：把一行拆开，时间化成秒
//   一行最多三段，段与段之间是空格：
//     17:48:19 21:57:24
//     17:21:07 00:31:46 (+1)
//   用 sc.nextLine() 整行读成一个 String，再按空白切成数组：
//     String[] s = line.trim().split("\\s+");
//     int up = toSec(s[0]);       // 起飞，"17:21:07"
//     int down = toSec(s[1]);     // 降落，"00:31:46"
//     if (s.length == 3) {        // 第三段是跨天标记，如 "(+1)"
//       down += (s[2].charAt(2) - '0') * 86400;   // 字符 '1' -> 数字 1 天
//     }
//   toSec 是 main 外面的 static 小方法，再按 ":" split 成三段 parseInt：
//     return h * 3600 + m * 60 + sec;
//   （"(+1)" 里括号是第 0 个、加号是第 1 个、数字是第 2 个，所以
//   charAt(2) - '0' 就把字符 '1' 变成整数 1；换成
//   Integer.parseInt(s[2].substring(2, 3)) 也一样。）
//   这一行算出来的时长 d = down - up 一定 >= 0：不跨天时降落本来就晚于起飞，
//   跨天时已经补过 86400 了。
//
//   ⚠ 坑 ①：不能用 nextInt() 读 "17:48:19"。Scanner 是先按空白切出一整段、
//   再回头解析数字，段里夹着冒号，nextInt() 会直接抛 InputMismatchException。
//   整段读成 String 再 split 才稳。
//   ⚠ 坑 ②：读 T 的时候别把 sc.nextInt() 和 sc.nextLine() 混着用——nextInt()
//   只吃掉数字，行尾那个换行还留在缓冲区，紧跟着的第一个 nextLine() 会读到
//   空串，之后所有行全部错位。要么 T 也用 nextLine() 读再 Integer.parseInt，
//   要么在 nextInt() 后面补一句 sc.nextLine() 把行尾吃掉。
//   ⚠ 坑 ③：split("\\s+") 之前要先 trim()。字符串行首若有空格，split 会切出
//   一个空串当第 0 段（"\\s+" 是分隔符，行首的空格照样算一个分隔），后面
//   下标全串位。行尾的空格倒是不影响。
//   ⚠ 坑 ④：也可以一个 token 一个 token 用 sc.next() 读，但第三段"到底是
//   (+1) 还是下一行的起飞时间"必须看一眼才知道，而 Scanner 没有 peek（只看
//   不取），判断起来别扭；整行读的写法不用纠结这个。
//
//   第三步：两个方向的时长取平均
//   每组数据读两行，各算出一个时长 d1（去程）、d2（回程）：
//     int fly = (d1 + d2) / 2;
//   为什么敢用整数除法：d1 + d2 = 2F，一定是偶数，不会丢掉 1 秒。
//   规模很小：单行时长最多 48 小时 = 172800 秒，两行加起来 345600，int 都
//   装得下（想用 long 也行，图个心安）。
//
//   第四步：把秒数按 hh:mm:ss 补零输出
//     int h = fly / 3600, m = fly / 60 % 60, sec = fly % 60;
//     System.out.printf("%02d:%02d:%02d%n", h, m, sec);
//   %02d = 至少两位、不足补 0；%n 是换行。别用字符串拼接（h + ":" + m + ":" +
//   sec）——样例 #1 的答案 04:09:05 会立刻暴露成 "4:9:5"。题目原话："当时间
//   为一位数时，要补齐前导零"。
//
//   几个要想清楚的点：
//   ① 跨天标记是加在【降落】时间上的——"今日 / 次日 / 第三天"说的是降落那天。
//      加到起飞上去的话，样例 #1 第 2 组（17:21:07 00:31:46 (+1)）立刻会算出
//      负数。
//   ② "(+1)" 里那个数字要真读出来，别写死一个 86400 蒙过去，格式里写了
//      (+2) 就得认（虽然它只在一种极端情形下合法，见下条）。
//   ③ 关于 (+2) 的冷知识：回程时长 = F - Δ 必须 >= 0，所以 Δ <= F；题面又
//      保证 F <= 24 小时，于是去程时长 = F + Δ <= 48 小时，刚好卡在"两天"的
//      门槛上。也就是说 (+2) 唯一合法的样子是 F = Δ = 24 小时、去程正好 48
//      小时、回程 0 秒，答案 24:00:00（就是补充样例 #4）。看着怪，但它是真
//      存在的边界，也说明答案的 hh 有可能是 24。
//   ④ Δ 可以是负的（回程时长比去程长，样例 #1 第 2 组就是这样），公式对它
//      照样成立——"取平均"正是把方向相反的时差抵消掉，别去假设哪个方向更长。
//   ⑤ 题面保证输入时间合法，所以不用做任何校验，也不用担心降落早于起飞，
//      精力全放在公式和解析上就行。
//   ⑥ 复杂度：每组数据都是常数次字符串处理加加法，总体 O(T)，1 秒时限远远
//      够用，不需要任何优化。
//   别忘了文件开头 import java.util.Scanner;（或者直接 import java.util.*;）。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        int T = Integer.parseInt(sc.nextLine().trim());
        for (int i = 0; i < T; i++) {
            int d1 = getDuration(sc.nextLine());
            int d2 = getDuration(sc.nextLine());
            int fly = (d1 + d2) / 2;
            int h = fly / 3600, m = fly / 60 % 60, sec = fly % 60;
            System.out.printf("%02d:%02d:%02d%n", h, m, sec);
        }
        sc.close();
    }
    static int getDuration(String line) {
        String[] s = line.trim().split("\\s+");
        int up = toSec(s[0]);
        int down = toSec(s[1]);
        if (s.length == 3) {
            down += (s[2].charAt(2) - '0') * 86400;
        }
        return down - up;
    }
    static int toSec(String time) {
        String[] t = time.split(":");
        int h = Integer.parseInt(t[0]);
        int m = Integer.parseInt(t[1]); 
        int sec = Integer.parseInt(t[2]);
        return h * 3600 + m * 60 + sec;
    }
}
