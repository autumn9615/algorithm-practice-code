// 题目描述
// 小蓝要画一个 2025 图形。图形的形状为一个 h × w 的矩形，h 表示图形的高，
// w 表示图形的宽。当 h = 5, w = 10 时，图形如下所示：
//
//   2025202520
//   0252025202
//   2520252025
//   5202520252
//   2025202520
//
// 图形的规律是：第一行用 2025 重复填入，第二行开始，每行向左移动一个字符，
// 用 2025 重复填入。给定 h, w，请输出对应的图形。
//
// 输入格式
// 输入的第一行包含两个正整数 h, w，用一个空格分隔。
//
// 输出格式
// 输出若干行，表示对应的图形（一共 h 行，每行 w 个字符）。
//
// 输入 #1
//   4 5
// 输出 #1
//   20252
//   02520
//   25202
//   52025
//
// 输入 #2（补的边界样例：w = 1，每行只有一个字符，专门盯取模下标对不对）
//   4 1
// 输出 #2
//   2
//   0
//   2
//   5
//
// 输入 #3（补的边界样例：h = 1 只有一行，正是 30% 那档数据的形状）
//   1 5
// 输出 #3
//   20252
//
// 说明/提示
// 对于 30% 的评测用例，h = 1，1 ≤ w ≤ 20；
// 对于 60% 的评测用例，1 ≤ h, w ≤ 20；
// 对于所有评测用例，1 ≤ h, w ≤ 100。
// 原题时限 1 秒，内存 256M。蓝桥杯 2025 年省赛 C/Python A 组，洛谷自造数据。
//
// 思路（只用字符数组 + 双重 for 循环，没有任何高级函数）
//   别去想"字符串怎么平移"，直接盯一个位置该填什么字符：
//   设行号 i 从 0 数、列号 j 从 0 数，第 i 行第 j 列填的是 2025 里的
//   第 (i + j) % 4 个字符（0 号是 '2'，1 号是 '0'，2 号是 '2'，3 号是 '5'）。
//   为什么是 i + j：每往下一行，整行往左挪一格，同一个位置上轮到的字符就往后
//   退一位；每往右一列也一样，所以行号加列号再对 4 取余。
//   做法：
//     ① 先把规律存进一个长度为 4 的字符数组，比如 char[] p = {'2','0','2','5'}；
//     ② 外层 for 让 i 从 0 走到 h - 1（第几行），内层 for 让 j 从 0 走到 w - 1（第几列）；
//     ③ 每个位置用 System.out.print(p[(i + j) % 4]) 打印，注意 print 不换行；
//     ④ 内层循环一结束，用 System.out.println() 补一个换行，换到下一行。
//   易错点：w 不一定是 4 的倍数（样例 1 的 w = 5 就是），不能"先打整数遍
//         2025 再截断"；老老实实一列一列算下标，取模会自动绕回开头。
//   规模：h、w 最大 100，总共才 100 × 100 = 10000 个字符，1 秒时限随手就过。
// ============================================================================

import java.util.*;
import java.io.*;

public class Main {
    public static void main(String[] args){
        //定义一个字符数组存放规律
        char[] arr = {'2', '0', '2', '5'};
        Scanner sc = new Scanner(System.in);
        //定义行h
        int h = sc.nextInt();
        //定义列w
        int w = sc.nextInt();
        sc.close();
        for(int i = 0; i < h; i++){
            //打印每一行的字符
            for(int j = 0; j < w; j++){
                //打印第i行上的每一个字符
                System.out.print(arr[(i + j) % 4]);
            }
            //打印完了一行之后换行
            System.out.println();
        }
    }
}