// ============================================================================
// 力扣 283. 移动零
// ----------------------------------------------------------------------------
// 题目描述
// 给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持
// 非零元素的相对顺序。
// 请注意，必须在不复制数组的情况下原地对数组进行操作。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public void moveZeroes(int[] nums)
//   注意返回类型是 void：答案直接写在传进来的 nums 里，不用 return
//
// 输入 #1
//   nums = [0,1,0,3,12]
// 输出 #1
//   [1,3,12,0,0]
//   解释：非零元素 1、3、12 的先后顺序不变，两个 0 被挪到末尾。
//
// 输入 #2
//   nums = [0]
// 输出 #2
//   [0]
//   只有一个元素，本身就是 0，不用动。
//
// 输入 #3
//   nums = [1,2,3]
// 输出 #3
//   [1,2,3]
//   补的边界样例：一个 0 都没有，数组应该原封不动。
//
// 输入 #4
//   nums = [0,0,0]
// 输出 #4
//   [0,0,0]
//   补的边界样例：全是 0，也不用动，考验"一次交换都不该发生"。
//
// 输入 #5
//   nums = [0,0,1]
// 输出 #5
//   [1,0,0]
//   补的样例：唯一的非零元素在最后面，要跨过两个 0 挪到最前面。
//
// 提示
//   1. 1 <= nums.length <= 10^4
//   2. -2^31 <= nums[i] <= 2^31 - 1
//   3. 进阶：你能尽量减少完成的操作次数吗？
//
// 说明/提示
// 【样例说明】样例 1 是标准情况，样例 2 只有一个元素。这题真正的考点
//   不是"把 0 找出来扔到后面"，而是"保持非零元素的相对顺序"——顺序乱了
//   就算错。
// 【评测用例规模与约定】
//   n 最大 10^4，O(n^2) 的写法（遇到 0 就往后冒泡 / 找后面第一个非零来换）
//   最坏要 10^8 次操作，会超时；O(n) 的双指针扫一遍就够。力扣难度：简单。
//
// 思路（双指针：慢指针 j 记"下一个非零元素该放哪"，快指针 i 负责扫描）
//   一、先想清楚答案数组长什么样
//     把所有 0 挪到后面之后，数组一定是这个样子：
//       前面一段全是非零元素（保持原来的先后顺序），后面一段全是 0。
//     所以问题等价于：把原数组里的非零元素，按原顺序依次"挤"到数组开头，
//     剩下的位置全部填 0。
//
//   二、双指针的分工
//     j（慢指针）：下一个非零元素应该放的位置。
//     i（快指针）：当前正在检查的位置，从 0 走到 n-1。
//     循环里始终维持这个不变量：
//       [0, j)   已经放好的非零元素（顺序和原数组一致）
//       [j, i)   全是 0（这些位置迟早被后面的非零元素占掉）
//       [i, n)   还没看过
//
//   三、每一步做什么
//     nums[i] == 0：它是 0，本来就该待在后半段，跳过，i 自己往前走。
//     nums[i] != 0：它得挪到前面去，和 nums[j] 交换，然后 j++。
//       为什么交换是对的？因为 [j, i) 里全是 0，所以 nums[j] 一定是 0。
//       交换等于"把非零元素搬到 j，把 0 换到 i"，一举两得。
//       换完之后 [0, j+1) 还是非零段、[j+1, i] 还是 0 段，不变量保持。
//
//     int j = 0;                          // 慢指针：下一个非零该放的位置
//     for (int i = 0; i < nums.length; i++) {
//         if (nums[i] != 0) {
//             int t = nums[i];            // 交换 nums[i] 和 nums[j]
//             nums[i] = nums[j];
//             nums[j] = t;
//             j++;                        // 非零段变长一格
//         }
//     }
//
//   四、为什么非零元素的相对顺序不会乱
//     非零元素是按 i 从小到大的顺序被处理的，每次都被放到 j 这个"下一个
//     空位"，而 j 只增不减。所以先遇到的非零元素一定排在前面，顺序天然
//     就保持住了。
//
//   五、拿样例 1 走一遍（nums = [0,1,0,3,12]）
//     i=0：nums[0]=0，跳过
//     i=1：nums[1]=1 ≠ 0，交换 nums[1] 和 nums[0] → [1,0,0,3,12]，j=1
//     i=2：nums[2]=0，跳过
//     i=3：nums[3]=3 ≠ 0，交换 nums[3] 和 nums[1] → [1,3,0,0,12]，j=2
//     i=4：nums[4]=12 ≠ 0，交换 nums[4] 和 nums[2] → [1,3,12,0,0]，j=3
//     结束，结果 [1,3,12,0,0] ✓
//
//   六、坑和边界
//     - 题目要求原地修改，不能 new 一个新数组再复制回去。
//     - 慢指针 j 只在"遇到非零"时前进；遇到 0 时只有 i 前进、j 不动，
//       两者的差值就是"已经跨过去的 0 的个数"。
//     - 全是 0 时 j 一直是 0，一次交换都不会发生，数组原样不动。
//     - 一个 0 都没有时 i 和 j 同步前进，每次都是自己和自己交换，
//       结果不变（想省操作可以加 if (i != j) 再换，见下面的进阶）。
//     - 交换一定要用临时变量。别写成 nums[i] = nums[j]; nums[j] = nums[i];
//       那样两个位置会变成同一个值，非零元素就丢了。
//
//   七、复杂度
//     只扫一遍，时间 O(n)；只用了 i、j、t 三个变量，额外空间 O(1)。
//
//   进阶：怎么让操作次数最少（题目最后问的）
//     上面的交换版，每个非零元素都要交换一次（3 次赋值），哪怕它本来就在
//     正确的位置上。更省的做法是"覆盖法"，分两趟：
//       第一趟：把非零元素依次写到 nums[j++]，j 从 0 开始；
//       第二趟：把 nums[j] 到数组末尾全部填 0。
//     这样每个位置正好写一次，总共 n 次赋值，是最少的。
//     第一趟不会覆盖还没读的数据：因为 j <= i 永远成立（只有遇到非零时
//     j 才加一，而 i 每轮都加一），写的位置要么已经读过、要么就是自己。
//
//   其他能过的解法（了解即可）：
//     - 用一个新数组存非零元素再拷回来：结果对，但违反"原地"的要求。
//     - 遇到 0 就去找后面第一个非零元素交换：最坏 O(n^2)，会超时。
//     - 直接排序：非零元素之间的先后顺序会被打乱（比如 [2,1,0] 会变成
//       [0,1,2]），除非专门写稳定排序，完全没必要。
// ============================================================================

class Solution {
    public void moveZeroes(int[] nums) {
        // 慢指针：下一个非零元素应该放的位置
        int j = 0;
        // 快指针：当前正在检查的位置，从 0 走到 n-1
        int i = 0;
        // 循环里始终维持这个不变量：
        //   [0, j)   已经放好的非零元素（顺序和原数组一致）
        //   [j, i)   全是 0（这些位置迟早被后面的非零元素占掉）
        //   [i, n)   还没看过
        for(i = 0; i < nums.length; i++){
            if(nums[i] != 0){
                // nums[i] ≠ 0，它得挪到前面去，和 nums[j] 交换，然后 j++
                int temp = nums[i];
                nums[i] = nums[j];
                nums[j] = temp;
                // 非零段变长一格,j指向下一个非零元素应该放的位置
                j++;
            }
        }
    }
}
