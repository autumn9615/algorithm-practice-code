// ============================================================================
// 洛谷 P16274 [蓝桥杯 2026 省 C] 二维码存储
// ----------------------------------------------------------------------------
// 题目描述
// 打印机吐出了一张二维码，小蓝准备把它存进嵌入式设备的内存。
// 这张二维码是一个 n 行 m 列的矩阵，由 n × m 个黑白模块组成，
// 每个模块用 1 个二进制位（bit）记录：0 代表白色，1 代表黑色。
//
// 数据在内存中以“行优先”的方式紧挨着存储：先存第一行，再存第二行，以此类推。
// 但这台设备的硬件限制很严格——内存中每一行数据占用的空间大小必须是 32 的整数倍（bit），
// 所以要按行做 32 bit 对齐：
//   若 m 不是 32 的倍数，就在该行末尾补若干个 0，使该行占用的位数
//   变成不小于 m 的最小的 32 的倍数；
//   若 m 恰好是 32 的倍数，则不需要补位。
// 补上的 0 只作为本行的填充位、计入本行占用空间，下一行不能使用这些填充位。
//
// 问：要想存下这张完整的二维码，至少需要向系统申请多少个字节（Byte）的内存空间？
// （注：1 Byte = 8 bit）
//
// 输入格式
// 输入共一行，包含两个整数 n 和 m，分别表示二维码的行数和每行的模块数。
//
// 输出格式
// 输出一个整数，表示存储该二维码所需的最少字节数。
//
// 输入 #1
//   2 10
// 输出 #1
//   8
//
// 输入 #2
//   2 40
// 输出 #2
//   16
//
// 输入 #3（补的边界样例：每行只有 1 个模块也得单独对齐到 32 位，两行共 64 位 = 8 字节；
//             不能把 n × m 个有效位一起凑整，那样会错算成 1 字节）
//   2 1
// 输出 #3
//   8
//
// 输入 #4（补的边界样例：m 恰好是 32 的倍数，不补位）
//   1 32
// 输出 #4
//   4
//
// 输入 #5（补的边界样例：n、m 都取最大 10^9，答案大到超过 int 范围，必须用 long）
//   1000000000 1000000000
// 输出 #5
//   125000000000000000
//
// 说明/提示
// 【样例说明】
//   样例 1：每行 10 个模块，10 不是 32 的倍数，补 22 个 0 凑成 32 位，两行共 64 位，即 8 字节。
//   样例 2：每行 40 个模块，40 不是 32 的倍数，最近的倍数是 64，补 24 个 0，两行共 128 位，即 16 字节。
//
// 【评测用例规模与约定】
//   对于 40% 的评测用例：1 <= n, m <= 1000；
//   对于所有评测用例：1 <= n, m <= 10^9。
// 原题时限 1 秒，内存 512 MB。蓝桥杯 2026 年省赛 C 组。
//
// 思路（只用了 Scanner + long 变量 + 四则运算，没有任何高级函数）
//   关键是“按行各自对齐”：每一行单独补 0 补到 32 的整数倍，行与行之间的填充位互不共用，
//   所以只要先算清楚“一行占多少位”，再乘上行数 n 就行。
//
//   第一步，一行需要多少个 32 位的块：把 m 向上取整到 32 的倍数，
//       块数 = (m + 31) / 32。
//       为什么要加 31：整数除法是向下取整的。m 不是 32 的倍数时，加 31 能把商顶到下一个整数，
//       正好多补一块；m 恰好是 32 的倍数时，(m + 31) / 32 还是等于 m / 32，不会多补，
//       这正对应题目“m 是 32 的倍数就不补位”的规则。
//       千万别写成 m / 32，那样 m 不是 32 的倍数时会少算一块。
//
//   第二步，一行占 块数 × 32 位；因为 32 bit = 4 Byte，换算成字节就是 块数 × 4。
//
//   第三步，总字节数 = n × 块数 × 4，直接输出。
//
//   坑：
//     ① 内存里不按连续位存：n 行一共只有 n × m 个有效位，但每行末尾的填充位下一行用不了，
//        所以绝不能算成 (n × m + 7) / 8。比如 n = 2、m = 1：每行都要占满 32 位，
//        两行共 64 位 = 8 字节；而按整体凑整只要 1 字节，差得很远。
//     ② n、m 都能到 10^9，答案最大约 1.25 × 10^17，远超 int 上限（21 亿多），
//        所以 n、m 用 nextLong() 读，块数和答案也全放在 long 里算，不让 int 参与乘法。
//
//   规模：输入只有一行，读入后一次除法、两次乘法就出结果，1 秒时限远远用不完。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        long n = sc.nextLong();
        long m = sc.nextLong();
        long blocks = (m + 31) / 32; // 每行需要多少个 32 位块
        long bytesPerRow = blocks * 4; // 每行占用的字节数
        long totalBytes = n * bytesPerRow; // 总字节数
        System.out.println(totalBytes);
    }
}
