// ============================================================================
// 力扣 69. x 的平方根
// ----------------------------------------------------------------------------
// 题目描述
// 给你一个非负整数 x，计算并返回 x 的算术平方根。
// 由于返回类型是整数，结果只保留整数部分，小数部分将被舍去。
// 注意：不允许使用任何内置指数函数和算符，例如 pow(x, 0.5) 或者 x ** 0.5。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int mySqrt(int x)
//
// 输入 #1
//   x = 4
// 输出 #1
//   2
//
// 输入 #2
//   x = 8
// 输出 #2
//   2
//   解释：8 的算术平方根是 2.82842...，由于返回类型是整数，小数部分将被舍去。
//
// 提示
//   1. 0 <= x <= 2^31 - 1
//
// 说明/提示
// 【样例说明】样例 1 里 4 是完全平方数，2 * 2 = 4，直接返回 2；
//   样例 2 里 2 * 2 = 4 <= 8 < 9 = 3 * 3，所以取地板值 2，
//   即"最大的满足 mid * mid <= x 的整数 mid"。
// 【评测用例规模与约定】
//   x 最大到 2^31 - 1（约 21 亿），从 0 到 46340 逐个试也能过，但
//   更好的是用二分：平方根随 x 单调不减，可以在 [0, x] 上二分找答案。
//
// 思路（二分找"最后一个满足 mid * mid <= x 的下标"，闭区间写法）
//   把问题翻译成二分能回答的形式：
//     答案 ans = 最大的整数 mid，使得 mid * mid <= x。
//   因为 mid 越大 mid * mid 越大，所以"mid * mid <= x"这个条件
//   前一半全真、后一半全假，正好可以用二分找"最后一个真的位置"。
//
//   闭区间二分（和 LeetCode-704 一个框架），区间 [left, right] 初始为 [0, x]：
//     int left = 0, right = x, ans = 0;
//     while (left <= right) {
//         int mid = left + (right - left) / 2;
//         if ((long) mid * mid <= x) {
//             ans = mid;      // mid 满足条件，先记下来
//             left = mid + 1; // 再试试更大的
//         } else {
//             right = mid - 1;// mid 太大了，往小的那边收
//         }
//     }
//     return ans;
//
//   关键坑：mid * mid 会溢出。mid 最大约 46340 时 mid * mid 约 21 亿，
//   刚好在 int 上限附近；二分过程中 mid 可能取到 2^30 这种值，
//   mid * mid 直接超出 int（约 10^18），会变成负数导致判断错误。
//   所以先转成 long：写成 (long) mid * mid 或 (long) mid * mid <= x。
//
//   边界：x = 0 时区间是 [0, 0]，mid = 0，0 <= 0 成立，ans = 0，返回 0；
//   x = 1 时返回 1；x = 2^31 - 1 时返回 46340（因为 46340^2 = 2147395600，
//   46341^2 = 2147488281 > 2^31 - 1）。
//
//   用样例 2 走一遍（x = 8）：区间 [0,8] → mid=4, 16>8 → right=3；
//   mid=1, 1<=8 → ans=1, left=2；mid=2, 4<=8 → ans=2, left=3；
//   mid=3, 9>8 → right=2，left=3 > right=2 结束，返回 ans=2。
//   循环结束时 left 和 right 交叉，right 就是答案，也可以直接 return right，
//   用 ans 记录只是为了更好读。
// ============================================================================

class Solution {
    public int mySqrt(int x) {
        long left = -1;
        long right = x;
        int ans = 0;
        if(x == 1){
            return 1;
        }
        while(left + 1 < right){
            long mid = left + (right - left) / 2;
            if(mid * mid <= x){
                ans = (int)mid;
                left = mid;
            }else{
                right = mid;
            }
        }
        return ans;
    }
}