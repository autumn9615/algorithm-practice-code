// ============================================================================
// 力扣 977. 有序数组的平方
// ----------------------------------------------------------------------------
// 题目描述
// 给你一个按非递减顺序排序的整数数组 nums，返回每个数字的平方组成的
// 新数组，要求也按非递减顺序排序。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int[] sortedSquares(int[] nums)
//   注意这次要 return 一个新数组，不是原地修改。
//
// 输入 #1
//   nums = [-4,-1,0,3,10]
// 输出 #1
//   [0,1,9,16,100]
//   解释：平方后变成 [16,1,0,9,100]，排序后变为 [0,1,9,16,100]。
//
// 输入 #2
//   nums = [-7,-3,2,3,11]
// 输出 #2
//   [4,9,9,49,121]
//   解释：平方后 [49,9,4,9,121]，注意 -3 和 2 平方后都是 9，
//   原数组两个不同位置（下标 1、2）的数在结果里挨在一起。
//
// 输入 #3
//   nums = [-5]
// 输出 #3
//   [25]
//   补的边界样例：单个负数，平方后 25。
//
// 输入 #4
//   nums = [0]
// 输出 #4
//   [0]
//   补的边界样例：单个 0。
//
// 输入 #5
//   nums = [-3,-2,-1]
// 输出 #5
//   [1,4,9]
//   补的样例：全是负数。平方后大小关系整个反过来（-3 最大变最大，
//   -1 最小变最小），是本题最特殊的一种分布。
//
// 输入 #6
//   nums = [0,1,2]
// 输出 #6
//   [0,1,4]
//   补的样例：全是非负数。平方不改变大小关系，结果就是原数组逐个平方。
//
// 输入 #7
//   nums = [-10000,10000]
// 输出 #7
//   [100000000,100000000]
//   补的样例：10^4 的平方是 10^8，两个挨在一起放，验证不会溢出
//   （int 上限约 2.1*10^9，10^8 离得很远）。
//
// 提示
//   1. 1 <= nums.length <= 10^4
//   2. -10^4 <= nums[i] <= 10^4
//   3. nums 已按非递减顺序排序
//   4. 进阶：请设计时间复杂度为 O(n) 的算法解决本问题
//
// 说明/提示
// 【样例说明】这题的核心观察是：原数组有序，但平方之后就不一定有序了
//   ——负数的部分平方后会"倒过来"（-7 < -3 平方后 49 > 9）。
//   真正有序的是"绝对值"：原数组里绝对值最大的数，一定在两端
//   （要么是最左边的最小负数，要么是最右边的最大正数），中间的绝对值
//   反而小。
// 【评测用例规模与约定】
//   n 最大 10^4，逐个平方再 Arrays.sort 是 O(n log n)，能过；
//   但题目进阶问的就是 O(n) 怎么做。10^4 的平方是 10^8，
//   int 最大约 2.1*10^9，不会溢出，不用 long。力扣难度：简单。
//
// 思路（对撞双指针 + 从后往前填：谁绝对值大谁的平方就放结果末尾）
//   一、为什么不能"顺着"填
//     平方后的最小值在原数组"绝对值最小"的地方——通常在正负交界处
//     （0 附近），这个位置从两端是看不出在哪的。
//     但平方后的最大值很好找：一定在原数组的两端！
//       最左端 nums[0] 是最小的数（可能是绝对值很大的负数），
//       最右端 nums[n-1] 是最大的数（可能是很大的正数）。
//       中间任何一个数的绝对值都不可能同时超过这两个。
//     所以正着找"下一个最小"很难，倒着找"下一个最大"很简单——
//     结果数组从后往前填，每次挑两端中平方更大的那个。
//
//   二、双指针的分工（和 167 相反的填法）
//     left：从 0 开始，指还没处理的左端。
//     right：从 n-1 开始，指还没处理的右端。
//     pos：结果数组的写入位置，从 n-1 往前走。
//     每轮比较 nums[left]² 和 nums[right]²：
//       左边大 → res[pos] = 左边平方，left++（用掉左边的数）；
//       否则   → res[pos] = 右边平方，right--（用掉右边的数）。
//       无论哪种，pos-- 往前挪一格。
//     循环条件是 left <= right（注意带等号！）：两个指针指向同一个
//     元素时它还没被处理，也要写进结果；这也是唯一一个 pos 和
//     left/right 能同时"会合"的地方。
//
//   三、代码骨架
//     int n = nums.length;
//     int[] res = new int[n];
//     int left = 0, right = n - 1, pos = n - 1;
//     while (left <= right) {
//         int x = nums[left] * nums[left];    // 左端平方
//         int y = nums[right] * nums[right];  // 右端平方
//         if (x > y) {
//             res[pos--] = x;
//             left++;          // 左边的数用掉了
//         } else {
//             res[pos--] = y;
//             right--;         // 右边的数用掉了
//         }
//     }
//     return res;
//
//   四、拿样例 1 走一遍（nums = [-4,-1,0,3,10]）
//     left=0, right=4, pos=4：16 vs 100 → 右大，res[4]=100，right=3
//     left=0, right=3, pos=3：16 vs 9   → 左大，res[3]=16，left=1
//     left=1, right=3, pos=2：1  vs 9   → 右大，res[2]=9，right=2
//     left=1, right=2, pos=1：1  vs 0   → 左大，res[1]=1，left=2
//     left=2, right=2, pos=0：0  vs 0   → 相等走 else，res[0]=0，right=1
//     left > right，结束。结果 [0,1,9,16,100] ✓
//     注意最后一步：left == right 时也要处理（条件是 <=），
//     0 就是那个"绝对值最小"的数，正好填在结果开头。
//
//   五、坑和边界
//     - 循环条件是 left <= right，不是 <：写 < 会漏掉正负交界处那个
//       绝对值最小的数，结果数组开头是 0（new int 默认值）。
//       这是本题最常见的一个错。
//     - 填的位置从后往前：res 的下标是 pos 从 n-1 减到 0，别顺手写成
//       从 0 开始填——那得反过来比"谁的平方小"，逻辑就拧了。
//     - 比较的是平方值不是绝对值：直接比 x > y 两个平方数就行，
//       不要先 Math.abs 再比再平方，白算一遍。
//     - 全是负数 / 全是正数都不用特判：全负时每次都是左端平方大，
//       left 一路推到底；全正时每次都是右端平方大，right 一路退到底，
//       同一套代码自然处理。
//     - 10^4 * 10^4 = 10^8，int 装得下（上限约 2.1*10^9），不用 long；
//       但要是题目改成 -10^9 <= nums[i]，就得考虑溢出了。
//
//   六、复杂度
//     每轮恰好用掉一个数，n 个数走 n 轮，时间 O(n)；
//     结果数组是题目要求必须返回的，不算额外空间，
//     额外只用了 left、right、pos 三个变量，O(1)。
//
//   进阶：两种解法对比
//     1. 逐个平方 + 排序：O(n log n)，代码最短，面试说得出但答不出
//        "进阶"的要求；
//     2. 对撞双指针从后往前填：O(n)，靠的是"最大值必在两端"这个观察。
//     这题的套路叫"从两端往中间归并"，是双指针家族的另一种用法：
//     167 是"从两端往中间收缩找答案"，本题是"从两端往中间收缩
//     生成答案"。
//
//   其他能过的解法（了解即可）：
//     - 逐个平方再 Arrays.sort：O(n log n)，能过但没答到进阶点；
//     - 找到正负分界点后做归并：也是 O(n)，但要处理分界点的各种
//       边界情况，代码比双指针长一倍，没必要。
// ============================================================================

class Solution {
    public int[] sortedSquares(int[] nums) {
        // 先把这个数组原地全部平方
        for(int i = 0; i < nums.length;i++){
            nums[i] = nums[i] * nums[i];
        }
        // 然后再按照从小到大排序，使用Array里面的sort方法
        Arrays.sort(nums);
        return nums;
    }
}

