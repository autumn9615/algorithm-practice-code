// ============================================================================
// 力扣 209. 长度最小的子数组
// ----------------------------------------------------------------------------
// 题目描述
// 给定一个含有 n 个正整数的数组和一个正整数 target，找出该数组中满足其
// 总和大于等于 target 的长度最小的连续子数组，并返回其长度。
// 如果不存在符合条件的子数组，返回 0。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int minSubArrayLen(int target, int[] nums)
//
// 输入 #1
//   target = 7, nums = [2,3,1,2,4,3]
// 输出 #1
//   2
//   解释：子数组 [4,3] 的和是 7，长度 2，是满足条件的最短子数组。
//
// 输入 #2
//   target = 4, nums = [1,4,4]
// 输出 #2
//   1
//   解释：单个元素 4 就够，长度 1。
//
// 输入 #3
//   target = 11, nums = [1,1,1,1,1,1,1,1]
// 输出 #3
//   0
//   解释：整个数组加起来才 8，不到 11，找不到，返回 0。
//
// 输入 #4
//   target = 1, nums = [2]
// 输出 #4
//   1
//   补的边界样例：只有一个元素且它自己就达标，答案 1。
//
// 输入 #5
//   target = 6, nums = [1,2,3]
// 输出 #5
//   3
//   补的边界样例：必须取满整个数组才够，答案等于 n。
//   考验"窗口一直缩不到"的情况会不会正确返回全长。
//
// 输入 #6
//   target = 6, nums = [1,2,3,3]
// 输出 #6
//   2
//   补的样例：答案 [3,3] 在数组末尾，前面的 1,2 都是干扰项。
//   考验右指针要一路扫到最后才能找到解。
//
// 提示
//   1. 1 <= target <= 10^9
//   2. 1 <= nums.length <= 10^5
//   3. 1 <= nums[i] <= 10^4
//   4. 进阶：如果你已经实现 O(n) 的解法，请尝试设计一个 O(n log n) 的解法
//
// 说明/提示
// 【样例说明】这题的关键前提是"元素全是正整数"。正因为没有负数和 0，
//   窗口里的和才会随着右指针右移单调增大、随着左指针右移单调减小，
//   "滑动窗口"才能成立。如果数组里有负数，窗口一缩和反而可能变大，
//   这套方法就直接失效了。
// 【评测用例规模与约定】
//   n 最大 10^5。O(n^2) 的双重循环（枚举起点、累加到够为止）最坏
//   10^10 次，肯定超时。元素和最大 10^5 * 10^4 = 10^9，正好是 int 上限
//   21 亿的一半，int 装得下，不用 long。力扣难度：中等。
//
// 思路（滑动窗口 / 同向双指针：右指针负责扩大、左指针负责收缩）
//   一、暴力为什么慢
//     枚举所有起点 i，再从 i 往后累加，直到和 >= target 就记下长度。
//     每个起点都要扫一遍后面，最坏 O(n^2)。
//     慢在"重复计算"：以 i 为起点的窗口和，和以 i+1 为起点的窗口和，
//     大部分内容是重叠的，白白重算。
//
//   二、滑动窗口怎么避免重复
//     维护一个窗口 [left, right] 和它的和 sum。让 right 一路往右走，
//     每走一步就把 nums[right] 加进来；只要 sum >= target 了，就说明
//     "以当前 right 结尾的、最短的达标窗口"就是现在这个，记下长度
//     right - left + 1，然后试着把 left 往右推（把 nums[left] 减出去），
//     看看缩一格之后还达不达标——达标就继续缩，直到不达标为止。
//     整个过程 right 只往右走 n 步，left 也只往右走 n 步，总共 O(n)。
//
//   三、为什么这样不会漏掉最优解（本题核心）
//     任何一个最优子数组 [i, j]，在 right 走到 j 的那一刻，left 一定
//     已经推到了 i 或更左的位置（因为 left 只会在"缩了仍然达标"时才
//     前进，而 [i, j] 是最短的，缩到 i+1 就不达标了，所以 left 最多
//     停在 i）。此时窗口正好是 [i, j]，长度被记录。
//     所以每个右端点都会检查到"以它为结尾的最短达标窗口"，一个不漏。
//
//   四、代码骨架
//     int n = nums.length;
//     int left = 0;
//     int sum = 0;
//     int ans = n + 1;              // 用 n+1 表示"还没找到"，别用 0 或 -1
//     for (int right = 0; right < n; right++) {
//         sum += nums[right];       // 右指针扩张，把新元素纳入窗口
//         while (sum >= target) {   // 达标了，就试着收缩
//             ans = Math.min(ans, right - left + 1);
//             sum -= nums[left];    // 左指针收缩，把最左边的元素移出
//             left++;
//         }
//     }
//     return ans == n + 1 ? 0 : ans;
//
//   五、拿样例 1 走一遍（target = 7, nums = [2,3,1,2,4,3]）
//     right=0：sum=2，不达标
//     right=1：sum=5，不达标
//     right=2：sum=6，不达标
//     right=3：sum=8 >= 7 → ans=4（窗口 2,3,1,2），减掉 2 → sum=6，left=1
//              6 < 7，停止收缩
//     right=4：sum=10 >= 7 → ans=min(4,4)=4（窗口 3,1,2,4），减 3 → sum=7，left=2
//              7 >= 7 → ans=min(4,3)=3（窗口 1,2,4），减 1 → sum=6，left=3
//              6 < 7，停止
//     right=5：sum=9 >= 7 → ans=min(3,3)=3（窗口 2,4,3），减 2 → sum=7，left=4
//              7 >= 7 → ans=min(3,2)=2（窗口 4,3），减 4 → sum=3，left=5
//              3 < 7，停止
//     结束，返回 2 ✓
//
//   六、坑和边界
//     - ★ ans 的初值要用 n+1（或 Integer.MAX_VALUE），不能用 0。
//       如果用 0，Math.min(0, 任何长度) 永远是 0，答案永远是 0。
//       也不能用 -1，因为要取最小值。
//     - while 循环里要先更新 ans 再减 nums[left]：顺序反了会算错长度
//       （先减的话窗口已经变了，但 right - left + 1 还没跟着变）。
//     - 内层是 while 不是 if：一个 right 可能要连续缩好几次才不达标
//       （样例 1 的 right=4 就缩了两次）。写成 if 会漏掉更短的答案。
//     - 收缩完要真的把 nums[left] 从 sum 里减掉，同时 left++，
//       两者必须配套，只做一半会导致 sum 和窗口对不上。
//     - 找不到时返回 0，不是返回 n：题目明确要求"不存在返回 0"。
//       用 ans == n+1 来判断，别用 ans > n 之类的模糊写法。
//     - 元素全为正整数是滑动窗口成立的前提（见"说明/提示"），
//       不要想当然地认为所有数组都能这么做。
//
//   七、复杂度
//     right 走 n 步，left 最多也走 n 步，内层 while 总共执行不超过 n 次，
//     所以时间 O(n)；只用了 left、right、sum、ans 四个变量，空间 O(1)。
//
//   进阶：O(n log n) 的解法（题目最后问的）
//     思路是"前缀和 + 二分"。因为元素全正，前缀和 pre 是严格递增的，
//     所以对每个起点 i，可以用二分找出"最小的 j 使
//     pre[j+1] - pre[i] >= target"，也就是 pre[j+1] >= pre[i] + target。
//     前缀和严格递增 → 可以二分 → 每个起点 O(log n)，总共 O(n log n)。
//       int n = nums.length;
//       int[] pre = new int[n + 1];
//       for (int i = 0; i < n; i++) pre[i + 1] = pre[i] + nums[i];
//       int ans = n + 1;
//       for (int i = 0; i < n; i++) {
//           int need = pre[i] + target;
//           int lo = i + 1, hi = n + 1;      // 找第一个 pre[x] >= need 的 x
//           while (lo < hi) {
//               int mid = lo + (hi - lo) / 2;
//               if (pre[mid] >= need) hi = mid;
//               else lo = mid + 1;
//           }
//           if (lo <= n) ans = Math.min(ans, lo - i);
//       }
//       return ans == n + 1 ? 0 : ans;
//     这个写法比滑动窗口长得多、常数也大，实际跑起来更慢，
//     但它是"进阶"要求的那一档，面试官问"还有别的做法吗"时能答上来。
//
//   其他能过的解法（了解即可）：
//     - 暴力双重循环：O(n^2)，10^10 次操作，超时。
//     - 滑动窗口（本题主解）：O(n)，最优。
//     - 前缀和 + 二分：O(n log n)，就是上面"进阶"那段。
// ============================================================================

class Solution {
    public int minSubArrayLen(int target, int[] nums) {
        // 设置左边界，初始和为0
        // n为数组长度
        int left = 0;
        int n = nums.length;
        int sum = 0;
        // 设置初始答案为n+1，即不存在
        int ans = n + 1;
        // 遍历数组，右边界从0开始，每次向右移动一位
        for (int right = 0; right < nums.length; right++) {
            // 右边界右移，将新元素加入窗口
            sum += nums[right];
            // 当窗口内的和大于等于目标值时，开始收缩左边界
            // 更新答案，取最小值
            while(sum >= target){
                // 更新答案，取最小值
                // right - left + 1 为当前窗口长度
                ans = Math.min(ans, (right - left) + 1);
                // 左边界右移，将最左边的元素移出窗口
                sum -= nums[left];
                // 左边界右移++
                left++;
            }
        }
        // 返回答案，如果答案为n+1，则表示不存在，返回0
        return ans == n + 1 ? 0 : ans;
    }
}
