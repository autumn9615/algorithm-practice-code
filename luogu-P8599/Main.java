// ============================================================================
// 洛谷 P8599 [蓝桥杯 2013 省 B] 带分数
// ----------------------------------------------------------------------------
// 题目描述
// 100 可以表示为带分数的形式：100 = 3 + 69258/714。
// 还可以表示为：100 = 82 + 3546/197。
// 注意特征：带分数中，数字 1~9 分别出现且只出现一次（不包含 0）。
// 类似这样的带分数，100 有 11 种表示法。
//
// 输入格式
// 从标准输入读入一个正整数 N（N < 1000*1000 = 1000000）。
//
// 输出格式
// 程序输出数字 N 用数码 1~9 不重复不遗漏地组成带分数表示的全部种数。
// 注意：不要求输出每个表示，只统计有多少表示法！
//
// 输入 #1
//   100
// 输出 #1
//   11
//
// 输入 #2（补的边界样例：一种表示法都没有时，输出 0）
//   1
// 输出 #2
//   0
//
// 说明/提示
// 原题时限 3 秒，内存 64M。蓝桥杯 2013 年第四届省赛 B 组。
//
// 思路（只用数组 + 递归 + for 循环，没有任何高级函数）
//   目标：把 N 写成 a + b/c，让 a、b、c 三段正好把数字 1~9 各用一次，不重复、不遗漏。
//   写一个递归函数 dfs(part, cur, a, b, cnt)，五个参数各管一件事：
//     part —— 现在在拼第几段：1 表示 a，2 表示 b，3 表示 c
//     cur  —— 这一小段目前拼出来的数（每接一位就是 cur * 10 + d）
//     a、b —— 前面几段已经定下来的值
//     cnt  —— 已经用掉几个数字（9 个数字必须正好用完）
//   每一层递归从 1 到 9 试一个还没用过的数字 d，接到 cur 末尾，然后有两种走法：
//     ① 这一位继续留在本段里，本段还没结束；
//     ② 本段到此为止，把这一位当作下一段的开头。
//   走到 c 的最后一位、9 个数字刚好用完时，检查：b % c == 0 并且 a + b/c == N，
//   成立就把答案 ans 加 1。
//   剪枝：a 一旦拼得比 N 大了，这条分支直接放弃——后面再加分数也回不到 N。
//   边界：三段都不能是空的（9 个数字必须一个不多、一个不少地用完），
//         所以只有"后面还有数字可接"的时候才允许结束本段。
//   特别提醒：题目没有要求分数部分 b/c 是真分数，千万别多加 "b < c" 这个条件——
//         100 的那 11 种表示每一个都是 b > c（比如题目给的 69258/714）。
// ============================================================================
import java.util.*;

public class Main {
    static int N;                              // 要表示的那个数
    static int ans;                            // 表示法种数
    static boolean[] used = new boolean[10];   // used[d] = 数字 d 是否已经被用过（下标只用到 1~9）

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        N = sc.nextInt();
        sc.close();
        dfs(1, 0, 0, 0, 0);
        System.out.println(ans);
    }

    // part：正在拼第几段（1 = 整数部分 a，2 = 分子 b，3 = 分母 c）
    // cur ：当前这一段已经拼出来的数
    // a、b：前面几段已经定下来的值
    // cnt ：已经用掉几个数字（1~9 一共 9 个，全用上才算一个完整的带分数）
    static void dfs(int part, int cur, int a, int b, int cnt) {
        for (int d = 1; d <= 9; d++) {
            if (used[d]) {
                continue;
            }
            used[d] = true;
            int next = cur * 10 + d;              // 把数字 d 接到当前这一段的末尾

            if (part == 1) {
                if (next <= N) {                  // 剪枝：a 已经比 N 大了，后面再加正分数也回不来
                    dfs(1, next, 0, 0, cnt + 1);  // 这一位留在 a 里，a 接着拼
                    dfs(2, 0, next, 0, cnt + 1);  // a 到此为止，这一位当作 b 的开头
                }
            } else if (part == 2) {
                dfs(2, next, a, 0, cnt + 1);      // 这一位留在 b 里，b 接着拼
                dfs(3, 0, a, next, cnt + 1);      // b 到此为止，这一位当作 c 的开头
            } else {
                if (cnt + 1 == 9) {               // 最后一位接到 c 上，9 个数字正好用完
                    int c = next;
                    if (b % c == 0 && a + b / c == N) {
                        ans++;                    // 能整除，而且 a + b/c 正好等于 N
                    }
                } else {
                    dfs(3, next, a, b, cnt + 1);  // 这一位留在 c 里，c 接着拼
                }
            }

            used[d] = false;
        }
    }
}
