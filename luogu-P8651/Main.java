// ============================================================================
// 洛谷 P8651 [蓝桥杯 2017 省 B] 日期问题
// ----------------------------------------------------------------------------
// 题目描述
// 小明正在整理一批历史文献。这些历史文献中出现了很多日期。小明知道这些日期
// 都在 1960 年 1 月 1 日至 2059 年 12 月 31 日。令小明头疼的是，这些日期采用
// 的格式非常不统一，有采用 年/月/日 的，有采用 月/日/年 的，还有采用
// 日/月/年 的。更加麻烦的是，年份也都省略了前两位，使得文献上的一个日期，
// 存在很多可能的日期与其对应。
// 比如 02/03/04，可能是 2002 年 03 月 04 日、2004 年 02 月 03 日或 2004 年
// 03 月 02 日。
// 给出一个文献上的日期，你能帮助小明判断有哪些可能的日期与其对应吗？
//
// 输入格式
// 一个日期，格式是 AA/BB/CC。(0 <= A, B, C <= 9)
// （题面这行说的是三段各自都是两位数字，读的时候把每段两位拼成一个数就行：
//   样例 02/03/04 拆出来就是 2、3、4。）
//
// 输出格式
// 输出若干个不相同的日期，每个日期一行，格式是 yyyy-MM-dd。多个日期按从早
// 到晚排列。
//
// 输入 #1（官方样例）
//   02/03/04
// 输出 #1
//   2002-03-04
//   2004-02-03
//   2004-03-02
//
// 输入 #2（补的边界样例：三段的数字相同，三种解释都落在 2002-02-02 这一个
//   日期上，专门卡"忘了去重"——不去重会输出三行一样的）
//   02/02/02
// 输出 #2
//   2002-02-02
//
// 输入 #3（补的边界样例：60 恰好是两位年份的分界线，60 开头要补成 19XX；
//   1960-01-01 正是题目允许的最早日期，年份补全规则写错就露馅）
//   60/01/01
// 输出 #3
//   1960-01-01
//
// 输入 #4（补的边界样例：59 开头要补成 20XX，2059-12-31 正是题目允许的最晚
//   日期；和样例 #3 一头一尾夹住年份补全规则）
//   59/12/31
// 输出 #4
//   2059-12-31
//
// 输入 #5（补的边界样例：2004 年是闰年，2004-02-29 必须算合法；把闰年当平年
//   过的写法会漏掉第一行。另外注意三个日期的输出顺序是解释 ①③②，不是按
//   ①②③ 算出来的顺序，必须排过序才对）
//   04/02/29
// 输出 #5
//   2004-02-29
//   2029-02-04
//   2029-04-02
//
// 输入 #6（补的边界样例：2001 年是平年，2001-02-29 非法必须剔除；把 2 月
//   一律放 29 天过的写法会多输出一行 2001-02-29）
//   01/02/29
// 输出 #6
//   2029-01-02
//   2029-02-01
//
// 输入 #7（补的边界样例：2000 年能被 400 整除，是世纪闰年，2000-02-29 合法；
//   闰年公式只写"能被 4 整除且不能被 100 整除"、漏掉 400 那一条的写法，会把
//   它误判成平年而剔除，正确输出就一行都剩不下）
//   02/29/00
// 输出 #7
//   2000-02-29
//
// 说明/提示
// 【样例说明】官方样例只有 #1 一组，三种解释逐个验：
//   ① 年/月/日：02 → 2002 年，03 月，04 日 → 2002-03-04，月日都合法；
//   ② 月/日/年：02 月，03 日，04 → 2004 年 → 2004-02-03，合法；
//   ③ 日/月/年：02 日，03 月，04 → 2004 年 → 2004-03-02，合法。
//   三个日期互不相同，按从早到晚（先比年 2002 < 2004，同年再比月日）排好，
//   逐行输出，与样例一致。
// 【补充样例说明】#2 到 #7 都是用参考程序实际跑过的，可以拿来对答案：
//   #2：三种解释全是 2002-02-02，去重后只剩一行；
//   #3：① 解释得 1960-01-01（60 补成 19XX）；② 的月是 60、③ 的日是 60，
//     都非法被剔除；
//   #4：① 解释得 2059-12-31（59 补成 20XX）；② 的月是 59、③ 的日是 59，
//     都非法被剔除；
//   #5：2004-02-29（2004 是闰年）、2029-04-02（② 解释）、2029-02-04
//     （③ 解释）三个全合法，从小到大排好输出；
//   #6：① 解释得 2001-02-29，平年 2 月没有 29 日、被剔除；② 解释得
//     2029-01-02、③ 解释得 2029-02-01，都合法；
//   #7：① 的月是 29 非法、③ 的月是 29 非法，只有 ② 解释（月=02、日=29、
//     年=00 → 2000）合法，且必须认得出 2000 年是闰年。
// 【评测用例规模与约定】
//   输入只有一行 "AA/BB/CC"，三段都是 00-99 的两位数字。
//   洛谷标注时限 1 秒，内存 256 MB；数据规模极小，怎么算都够。
//   洛谷难度：普及-；蓝桥杯 2017 年第八届省赛 B 组。
//
// 思路（split 拆串 + parseInt、静态小方法 add 把三种解释合成一套代码、
//   TreeSet 自动排序 + 去重，都是 Java 算法题常见写法）
//   整题拆成五步：① 读入拆数 → ② 三种解释各调一次 add → ③ add 里补全年份
//   → ④ add 里检查合法性、合法就存成整数 → ⑤ TreeSet 排好序去完重，逐行输出。
//
//   第一步：读入，把 "AA/BB/CC" 拆出三个数
//   这一行里有斜杠，用 nextInt() 会直接报错（原因见下面坑 ①）。先用 sc.next()
//   把整行读成一个字符串，再用 split("/") 按斜杠切成三段字符串，每段交给
//   Integer.parseInt 转成数字——"02" 会正常转成 2，前导零不用自己处理：
//     String[] p = sc.next().split("/");   // "02/03/04" → ["02","03","04"]
//     int aa = Integer.parseInt(p[0]);     // 2
//     int bb = Integer.parseInt(p[1]);     // 3
//     int cc = Integer.parseInt(p[2]);     // 4
//
//   第二步：三种解释，各调用一次 add
//   同一串 aa/bb/cc 按题目三种格式读，得到三个 (年, 月, 日) 组合：
//     ① 年/月/日：年 = aa、月 = bb、日 = cc；
//     ② 月/日/年：年 = cc、月 = aa、日 = bb；
//     ③ 日/月/年：年 = cc、月 = bb、日 = aa。
//   注意 ②③ 的年份都是 cc（原文写在最后那一段的那个数）。
//   三种解释的处理逻辑一模一样（补年份、查合法性、存日期），所以把这套逻辑
//   写成 main 外面的静态小方法 add(int y2, int m, int d)（前面加 static 才能
//   在 main 里直接调），三种解释各调一次、换一下参数就行——不合法的组合在
//   add 里直接 return 丢掉：
//     add(aa, bb, cc);   // ① 年/月/日
//     add(cc, aa, bb);   // ② 月/日/年
//     add(cc, bb, aa);   // ③ 日/月/年
//
//   第三步：add 里先把两位年份补成四位
//   日期范围 1960-01-01 至 2059-12-31 正好是一百年，两位年份就是这 100 年
//   的后两位：
//     两位年份 >= 60 → 前面补 19（60 → 1960，……，99 → 1999）；
//     两位年份 <= 59 → 前面补 20（00 → 2000，……，59 → 2059）。
//   写成一行就是：int y = y2 >= 60 ? 1900 + y2 : 2000 + y2;
//   这是本题第一号易错点，样例 #3、#4 专门卡两头。
//
//   第四步：add 里检查 (年, 月, 日) 合不合法，合法就存成整数
//   下面几条全过才存，不合法直接 return：
//     a. 月份在 1 到 12 之间；
//     b. 日在 1 到"当月天数"之间。每月天数用数组对号入座，下标直接就是月份，
//        最前面白占一个 0：
//          static int[] days = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
//        这样 m 月的天数就是 days[m]，不用写 days[m - 1]，少一个容易错的
//        减法。2 月先按 28 天；
//     c. 2 月特殊处理：闰年 29 天，平年 28 天。闰年公式：
//          y % 400 == 0 || (y % 4 == 0 && y % 100 != 0)
//        即"能被 4 整除，但末两位是 00 的年份必须能被 400 整除才算"。
//        本题年份范围内会碰到的整百年只有 2000（恰好是闰年），但完整公式
//        背下来，别的题也用得着。
//   合法就把日期存成一个整数：
//     num = 年 * 10000 + 月 * 100 + 日      // 2002-03-04 存成 20020304
//   位数固定（年 4 位、月 2 位、日 2 位），所以数值大小顺序就是日期先后顺序。
//   集合声明成静态字段，三种解释共用，add 里最后一句 set.add(num) 就存好：
//     static TreeSet<Integer> set = new TreeSet<>();
//   （备选：判合法性也可以偷懒用 JDK 自带的 LocalDate.of(y, m, d)——合法就
//     返回日期，非法就抛 DateTimeException，try-catch 包住、合法时才 set.add
//     即可（实测：2001-02-29、月 13、月 0、日 0 都会抛，2000-02-29 正常）。
//     这是日期题的 Java 常见套路；但闰年公式是算法题常客，建议自己会写。）
//
//   第五步：TreeSet 一步完成排序 + 去重，然后逐行输出
//   TreeSet 正好白送本题最费劲的两件事：
//     · 自动排序：往里存一堆数，遍历出来就是从小到大——不用自己写冒泡；
//     · 自动去重：同一个日期存第二遍直接不生效（集合不允许重复元素）——
//       不用自己写"和上一个比"。
//   所以 add 之后直接遍历就完事，for-each 一行搞定：
//     for (int num : set) {
//       // 从 num 拆回：y = num / 10000，m = num / 100 % 100，d = num % 100
//       System.out.printf("%04d-%02d-%02d%n", y, m, d);
//     }
//   %04d 表示至少 4 位、不足补 0；%02d 同理 2 位；%n 是换行。printf 属于
//   基础语法，格式化输出最省事，放心用。
//   别忘了文件开头 import java.util.Scanner; 和 import java.util.TreeSet;。
//
//   几个要想清楚的点：
//   ① 读入必须用 sc.next() 读成字符串再 split！"02/03/04" 不是纯数字，
//      nextInt() 会直接抛 InputMismatchException（实测：Scanner 是按空白切出
//      一整段再来解析的，段里混了斜杠就报错，不是"读走数字就停"）。
//   ② 年份分界是 60：60 → 1960、59 → 2059，别写成 50 或者不补全。
//   ③ 排序、去重都被 TreeSet 兜住了，不用自己写；但要知道它为什么成立：
//      num 的数值大小顺序 = 日期先后顺序（位数固定，先比年、再比月、再比日），
//      集合又不允许重复元素。三种解释撞同一个日期时只留一份——02/02/02 是
//      三种解释全撞（样例 #2）；再比如 01/12/01，① 和 ③ 都得 2001-12-01。
//   ④ 不要以为 ①②③ 的调用顺序就是输出顺序！样例 #1 碰巧 ①②③ 就是时间顺序，
//      但样例 #5 的实际顺序是 ①③②（2029-02-04 在 2029-04-02 前面）。用
//      TreeSet 它会自动排好；要是哪天换成数组自己写，这里必踩，别把这个
//      教训丢了。
//   ⑤ 月、日的下界也要查：每段数字范围是 00-99，月=00、日=00 都可能出现，
//      不检查 1 <= m、1 <= d 会把乱七八糟的"日期"放出去。
//   ⑥ 复杂度是常数级（最多 3 次 add、TreeSet 里最多 3 个数），1 秒时限富富
//      有余，不需要任何优化。
// ============================================================================

import java.util.*;

public class Main {
    static TreeSet<Integer> set = new TreeSet<>();
    public static void main(String[] args){
        // 读入被拆数
        Scanner sc = new Scanner(System.in);
        // 读成字符串再 split，三段各自转成数字
        String[] s = sc.next().split("/");
        // 三段数字分别是年、月、日
        int YY = Integer.parseInt(s[0]);
        int MM = Integer.parseInt(s[1]);
        int DD = Integer.parseInt(s[2]);
        // 三种解释各调一次 add
        add(YY, MM, DD);   // 年/月/日
        add(DD, YY, MM);   // 月/日/年
        add(DD, MM, YY);   // 日/月/年
        // 遍历 TreeSet，逐行输出
        for (Integer i : set) {
            // 从整数拆回年月日
            int yyyy = i / 10000;
            int mm = i / 100 % 100;
            int dd = i % 100;
            // 格式化输出

            // 错误例子：没有做到月份“06”或者日期“09”，前面的那个 0 被丢掉了
            // System.out.println(yyyy + "-" + mm + "-" + dd);

            System.out.println(String.format("%04d-%02d-%02d", yyyy, mm, dd));
        }
        sc.close();
    }
    static void add(int YY, int MM, int DD){
        // 补全年份
        int YYYY = YY >= 60 ? 1900 + YY : 2000 + YY;
        // 检查月份是否合法
        if(MM < 1 || MM > 12){
            return;
        }
        // 检查日是否合法（每个月的天数做成数组）
        int[] days = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
        int maxDay = days[MM];
        // 闰年特殊处理（2月29日）
        if(MM == 2 && (YYYY % 400 == 0 || (YYYY % 4 == 0 && YYYY % 100 != 0))){
            maxDay = 29;
        }
        // 检查日是否合法
        if(DD < 1 || DD > maxDay){
            return;
        }
        // 合法就存成整数
        int num = YYYY * 10000 + MM * 100 + DD;
        set.add(num);
    }
}
