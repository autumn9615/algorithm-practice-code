// ============================================================================
// 力扣 88. 合并两个有序数组
// ----------------------------------------------------------------------------
// 题目描述
// 给你两个按非递减顺序排列的整数数组 nums1 和 nums2，另有两个整数 m 和 n，
// 分别表示 nums1 和 nums2 中的元素数目。
// 请你合并 nums2 到 nums1 中，使合并后的数组同样按非递减顺序排列。
//
// 注意：最终合并后的数组不应由函数返回，而是存储在数组 nums1 中。
// 为了应对这种情况，nums1 的初始长度为 m + n，其中前 m 个元素表示应合并
// 的元素，后 n 个元素为 0，应忽略。nums2 的长度为 n。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public void merge(int[] nums1, int m, int[] nums2, int n)
//   返回类型是 void：答案直接写在 nums1 里，不用 return。
//   注意 nums1 的长度是 m + n，不是 m，后面 n 个 0 是"占位符"，不是数据。
//
// 输入 #1
//   nums1 = [1,2,3,0,0,0], m = 3
//   nums2 = [2,5,6],       n = 3
// 输出 #1
//   [1,2,2,3,5,6]
//   解释：真正参与合并的是 [1,2,3] 和 [2,5,6]，末尾三个 0 是空位，
//         合并结果 1,2,2,3,5,6 正好填满 nums1 的 6 个位置。
//
// 输入 #2
//   nums1 = [1], m = 1
//   nums2 = [],  n = 0
// 输出 #2
//   [1]
//   解释：nums2 是空的，nums1 原样不动。
//
// 输入 #3
//   nums1 = [0], m = 0
//   nums2 = [1], n = 1
// 输出 #3
//   [1]
//   解释：m = 0 表示 nums1 里没有真实数据，那个 0 只是占位符，
//         合并结果完全来自 nums2。这是最容易理解错样例。
//
// 输入 #4
//   nums1 = [4,5,6,0,0,0], m = 3
//   nums2 = [1,2,3],       n = 3
// 输出 #4
//   [1,2,3,4,5,6]
//   补的样例：nums2 的所有元素都比 nums1 小，答案全在左边。
//   如果从前往后合并，第一步就会把 nums1[0] 的 4 覆盖掉，这组能直接抓出来。
//
// 输入 #5
//   nums1 = [-5,-3,0,0], m = 2
//   nums2 = [-4,-1],     n = 2
// 输出 #5
//   [-5,-4,-3,-1]
//   补的样例：全是负数，考验"0 是占位符不是数据"——别把 nums1 后两个 0
//   当成真实元素参与比较。
//
// 提示
//   1. nums1.length == m + n
//   2. nums2.length == n
//   3. 0 <= m, n <= 200
//   4. 1 <= m + n <= 200
//   5. -10^9 <= nums1[i], nums2[j] <= 10^9
//   6. 进阶：你可以设计实现一个时间复杂度为 O(m + n) 的算法吗
//
// 说明/提示
// 【样例说明】样例 3 的 m = 0 是理解本题的关键：nums1 里那个 0 是占位符，
//   不是数据。很多人在 m = 0 时把 0 也拿去比较，结果答案里凭空多出一个 0。
// 【评测用例规模与约定】
//   m + n 最大 400，规模很小，随便怎么写都能过。但这题真正的考点不是
//   "能不能做出来"，而是"能不能原地合并"——题目只给了 nums1 这一块
//   长度为 m + n 的空间，没有额外空间可用。力扣难度：简单。
//
// 思路（三指针 + 从后往前填：i 指 nums1 有效段的末尾，j 指 nums2 的末尾，
//       k 指 nums1 真正的末尾，谁大就把谁放到 k）
//   一、先想为什么不能从前往后
//     从前往后合并很自然：比较 nums1[i] 和 nums2[j]，小的放进 nums1 的开头。
//     但问题是——nums1 的开头正是你还没读完的数据！
//     例子 nums1 = [4,5,6,0,0,0]，nums2 = [1,2,3]：
//       第一步 1 < 4，把 1 写到 nums1[0]，4 当场被覆盖，永久丢失。
//     想从前往后做，就必须先把 nums1 的前 m 个复制到临时数组，多花 O(m) 空间。
//
//   二、从后往前就不会覆盖
//     关键观察：nums1 的**尾部** n 个位置是空的（全是占位 0），
//     而合并结果里**最大的元素**一定来自 nums1 或 nums2 的**末尾**。
//     所以从最后一位往前填：
//       比较 nums1[i] 和 nums2[j]，大的那个放到 nums1[k]，然后对应的
//       指针左移，k 也左移一格。
//     放进去的位置 k 永远在 i 的右边（后面证明），所以**绝不会覆盖还没读的
//     nums1 元素**。这就是"不用额外空间"的全部秘密。
//
//   三、指针定义和循环
//     int i = m - 1;        // nums1 有效段的最后一个元素
//     int j = n - 1;        // nums2 的最后一个元素
//     int k = m + n - 1;    // 结果要填的位置，从 nums1 的最后一格开始往前
//     while (j >= 0) {              // 只要 nums2 还有没放完的
//         if (i >= 0 && nums1[i] > nums2[j]) {
//             nums1[k--] = nums1[i--];   // 取 nums1 的大
//         } else {
//             nums1[k--] = nums2[j--];   // 取 nums2 的大（或相等时取 nums2）
//         }
//     }
//     注意：循环条件只看 j，不看 i。原因见下面"六、坑和边界"第 3 条。
//
//   四、为什么 k 永远在 i 右边（不覆盖的严格证明）
//     每轮开始时始终满足 k = i + j + 1：
//       初始 i = m-1, j = n-1, k = m+n-1 = (m-1) + (n-1) + 1 ✓
//       从 nums1 取：i 和 k 同时减 1，等式左边右边各减 1，仍成立 ✓
//       从 nums2 取：j 和 k 同时减 1，同理仍成立 ✓
//     因为 j >= 0（循环条件），所以 k = i + j + 1 >= i + 1 > i，
//     写入位置永远严格在 nums1 待读位置的右边，覆盖不到。
//
//   五、拿样例 1 走一遍（nums1 = [1,2,3,0,0,0], nums2 = [2,5,6]）
//     i=2(3), j=2(6), k=5：3 < 6  → nums1[5]=6，j=1, k=4
//     i=2(3), j=1(5), k=4：3 < 5  → nums1[4]=5，j=0, k=3
//     i=2(3), j=0(2), k=3：3 > 2  → nums1[3]=3，i=1, k=2
//     i=1(2), j=0(2), k=2：2 > 2 不成立 → nums1[2]=2，j=-1, k=1
//     j < 0，循环结束。nums1 = [1,2,2,3,5,6] ✓
//     左边剩下的 [1,2] 本来就在正确位置，不用动。
//
//   六、坑和边界
//     - ★ 取 nums1[i] 之前必须判断 i >= 0。nums1 的有效段可能先用完
//       （比如样例 3 的 m = 0），此时 i = -1，直接读 nums1[-1] 会
//       数组越界。所以条件写 `i >= 0 && nums1[i] > nums2[j]`，
//       短路求值保证 i < 0 时不会去读数组。
//     - ★ 循环条件只看 j >= 0，不看 i。因为 j < 0 表示 nums2 全部放完了，
//       此时 nums1 剩下的前缀 [0, i] 本来就待在正确位置，不用搬。
//       反过来如果写成 while (i >= 0 && j >= 0)，nums2 剩下的元素
//       就永远填不进去，答案会缺东西。
//     - nums1 的长度是 m + n，别拿 m 当长度用；同理 i 的初值是 m - 1，
//       不是 nums1.length - 1（那是 k 的初值）。
//     - m = 0 时 nums1 只有一个 0，它是占位符不是数据，别参与比较。
//     - n = 0 时循环一次都不进，nums1 原样保留，天然正确。
//     - 相等时取哪个都行（代码里走 else 取 nums2）。这题只要求值有序，
//       不要求"两个数组元素的相对次序"，所以不用纠结稳定性。
//     - 返回类型是 void：结果必须原地写进 nums1，return 新数组是错的。
//
//   七、复杂度
//     每轮恰好放好一个元素，最多 m + n 轮，时间 O(m + n)；
//     只用了 i、j、k 三个下标变量，额外空间 O(1)，正好满足题目
//     "不返回新数组、原地合并"的要求，也就是进阶要的那一档。
//
//   其他能过的解法（了解即可）：
//     - 前 m 个复制到临时数组，再从前往后归并：时间 O(m + n)，
//       但额外空间 O(m)，不是原地，进阶那一问就答不上来。
//     - System.arraycopy 拼起来再 Arrays.sort：O((m+n) log(m+n))，
//       能过（400 太小了），但完全没利用"两个数组已经有序"这个条件，
//       面试会被追问。
//     - 开一个新数组存结果再整体拷回 nums1：O(m + n) 时间、O(m + n)
//       空间，思路最直白，但同样不是原地。
// ============================================================================

import java.util.Arrays;

class Solution {
    public void merge(int[] nums1, int m, int[] nums2, int n) {
        // 先判定特殊情况
        // 下面个数组nums2是空的
        if(n == 0){
            return;
        }
        // 上面个数组nums1是空的
        if(m == 0){
            for(int i = 0;i < n;i++){
                nums1[i] = nums2[i];
            }
            return;
        }
        // 两个数组都不为空，考虑正常情况
        // 设置一个索引标识数组2的下标
        int index = 0;
        for(int j = m;j < nums1.length;j++){
            // 将数组二全部赋值到数组一里面
            nums1[j] = nums2[index];
            //数组二下标加一
            index++;
        }
        // 对数组一进行排序
        Arrays.sort(nums1);
        return;
    }
}

