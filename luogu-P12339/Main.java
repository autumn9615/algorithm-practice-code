// ============================================================================
// 洛谷 P12339 [蓝桥杯 2025 省 B/Python B 第二场] 25 之和
// ----------------------------------------------------------------------------
// 题目描述
// 小蓝最近对求和很着迷。给定一个正整数 n，他想求从 n 开始的连续 25 个整数的和，
// 即 n + (n + 1) + (n + 2) + …… + (n + 24)，请帮帮他吧。
//
// 输入格式
// 输入一行包含一个正整数 n。
//
// 输出格式
// 输出一行包含一个整数表示答案。
//
// 输入 #1
//   1
// 输出 #1
//   325
//
// 输入 #2
//   100
// 输出 #2
//   2800
//
// 输入 #3（补的边界样例：n 取到题目上限 10000，答案最大，顺便验一下会不会溢出）
//   10000
// 输出 #3
//   250300
//
// 说明/提示
// 对于 40% 的评测用例，1 ≤ n ≤ 100；
// 对于所有评测用例，1 ≤ n ≤ 10000。
// 原题时限 1 秒，内存 512M。蓝桥杯 2025 年省赛 B/Python B 组第二场。
//
// 思路（只用 for 循环 + 一个累加变量，没有任何高级函数）
//   题意就是把 n、n+1、……、n+24 这 25 个数加起来，一个不多一个不少。
//   最直白的做法：
//     ① 读入 n；
//     ② 开 sum = 0，用 for 让 i 从 0 数到 24，每次 sum += n + i；
//     ③ 循环结束后输出 sum。
//   为什么是加 n + i：i = 0 时加的就是 n 本身，i = 24 时加的是 n + 24，
//   正好凑齐 25 个数。边界就在这儿——24 是最后一个下标，别顺手写成 i <= 25，
//   那会多加一个 n + 25，样例 1 就会输出 351 而不是 325。
//   备选：这 25 个数是等差数列，和 = 25 * n + (0 + 1 + …… + 24) = 25 * n + 300，
//         一行就能算出答案；不过上面那个循环更不容易写错，先拿循环过。
//   规模：n 最小 1，最大 10000，最大答案是 25 * 10000 + 300 = 250300，
//         int 完全装得下，不用 long。
// ============================================================================

import java.util.*;
import java.io.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 定义一个数拿来存输入的n
        int n = sc.nextInt();
        // 定义一个数拿来存和
        long sum = 0;
        for(int i = 0; i < 25; i++){
            sum = sum + (n + i);
        }
        System.out.println(sum);
    }
}
