// ============================================================================
// 洛谷 P12172 [蓝桥杯 2025 省 Python B] LQ 图形
// ----------------------------------------------------------------------------
// 题目描述
// 小蓝要为蓝桥画一个图形。由于小蓝的画图能力有限，他准备用大写字母 Q 画一个
// L 形状的字符画。他希望 L 的粗细正好是 w 个字符宽，竖的笔划伸出 h 高（因此
// 图形总共 h + w 高），横的笔划伸出 v 宽（因此图形总共 v + w 宽），要求每个
// 笔划方方正正不能有多余内容。
//
// 例如，当 w = 2, h = 3, v = 4 时，图形如下所示：
//
//   QQ
//   QQ
//   QQ
//   QQQQQQ
//   QQQQQQ
//
// 给定 w, h, v，请帮助小蓝画出这个图形。
//
// 输入格式
// 输入的第一行包含三个正整数 w, h, v，相邻整数之间使用一个空格分隔。
//
// 输出格式
// 输出若干行，表示对应的图形。
//
// 输入 #1
//   3 4 5
// 输出 #1
//   QQQ
//   QQQ
//   QQQ
//   QQQ
//   QQQQQQQQ
//   QQQQQQQQ
//   QQQQQQQQ
//
// 输入 #2（补的边界样例：w = h = v = 1，图形最小，两个笔划都只伸出 1 格）
//   1 1 1
// 输出 #2
//   Q
//   QQ
//
// 输入 #3（补的边界样例：粗细 w = 3 比 h、v 都大，专门盯"下面要打 w 行"这个数）
//   3 1 1
// 输出 #3
//   QQQ
//   QQQQ
//   QQQQ
//   QQQQ
//
// 说明/提示
// 对于 30% 的评测用例，w = 1，1 ≤ h, v ≤ 20；
// 对于 60% 的评测用例，1 ≤ w, h, v ≤ 20；
// 对于所有评测用例，1 ≤ w, h, v ≤ 100。
// 原题时限 5 秒，内存 512M。蓝桥杯 2025 年省赛 Python B 组。
//
// 思路（只用双重 for 循环 + System.out.print，没有任何高级函数）
//   不用想"怎么画 L"，把它当成上下两块长方形拼起来就行：
//     上半块——竖笔划露在横笔划上面的那截：h 行，每行 w 个 Q；
//     下半块——横笔划本身（连着竖笔划的脚一起）：w 行，每行 v + w 个 Q。
//   三个数各管一件事：w 管粗细（上半块每行几个、下半块总共几行），
//   h 管上半块的行数，v 管横笔划往右多伸出几个字符——所以下半块宽 v + w
//   （竖笔划自己还占着 w 宽，横笔划是从最左边一直铺到最右边的）。
//   做法：
//     ① 外层 for 让 i 从 0 到 h - 1，内层 for 让 j 从 0 到 w - 1，
//        每个格子 System.out.print('Q')；内层一结束就 System.out.println()，
//        补一个换行，这样打出来就是上面那 h 行；
//     ② 再来一个双层 for：i 从 0 到 w - 1，j 从 0 到 v + w - 1，
//        一样 print('Q') 加换行，这就是下面那 w 行。
//   易错点：
//     - 下半块是 w 行，不是 h 行也不是 v 行：样例 1 输入 3 4 5，下面正好 3 行；
//     - 下半块宽度是 v + w，别只打 v 个：竖笔划本身还占着 w 宽；
//     - 不能有多余内容：别打空格占位，每行打满就直接换行。
//   规模：w、h、v 最大 100，最多 200 行 × 200 个字符 = 4 万个字符，随手就过。
// ============================================================================

import java.util.*;
import java.io.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 输入三个数
        int w = sc.nextInt();
        int h = sc.nextInt();
        int v = sc.nextInt();
        // 打印出上半块，竖笔画
        for(int i = 0; i < h; i++){
            // 打印行
            for(int j = 0; j < w; j++){
                // 打印每行的每个Q
                System.out.print('Q');
            }
            // 打印完一行就换行
            System.out.println();
        }
        // 打印出下半块，横笔画
        for(int i = 0; i < w; i++){
            // 打印行
            for(int j = 0; j < (v + w); j++){
                // 打印每行的每个Q
                System.out.print('Q');
            }
            // 打印完一行就换行
            System.out.println();
        }
    }
}
