// ============================================================================
// 洛谷 P16298 [蓝桥杯 2026 省 Python C 组] 解题速度对决
// ----------------------------------------------------------------------------
// 题目描述
// 机房的白炽灯下，键盘的敲击声此起彼伏。
// 小蓝和小红约定进行一场解题速度的对决。比赛共有 n 道题目，两人同时开始，
// 谁先完成所有题目，谁即获胜。虽然题目是一样的，但两人的解题节奏截然不同：
//    小蓝：解决每道题耗时固定为 t1 分钟。但他有个特殊的习惯，在完成第 i 道
//      题后，他需要休息 i * d1 分钟来平复心情，然后才能开始下一题。
//    小红：解决每道题耗时固定为 t2 分钟。同样地，她在完成第 i 道题后，需要
//      休息 i * d2 分钟。
// 你是这场对决的裁判。已知题目总数以及两人的各项耗时参数，现在请你计算出
// 最终的获胜者：如果是小蓝获胜，请输出 BLUE；如果是小红获胜，请输出 RED；
// 如果两人在同一时刻完成，则判定为平局，输出 DRAW。
//
// 输入格式
// 第一行输入一个整数 T，表示共有 T 组测试数据。
// 接下来 T 行，每行包含五个整数 n, t1, d1, t2, d2，其含义如题所述。
//
// 输出格式
// 对于每组测试数据，输出一行结果：
//   如果小蓝先完成，输出 BLUE。
//   如果小红先完成，输出 RED。
//   如果两人同时完成，输出 DRAW。
//
// 输入 #1
//   3
//   3 5 2 4 3
//   3 5 2 4 2
//   3 5 2 4 4
// 输出 #1
//   DRAW
//   RED
//   BLUE
//
// 输入 #2（补的边界样例：n = 1 时没有"下一题"，两边的休息一律不算，
//   即使 d1 = 100 很大也只是白给；若谁错算了最后一次休息，会输出 RED）
//   1
//   1 3 100 4 1
// 输出 #2
//   BLUE
//
// 输入 #3（补的边界样例：n = 2，每人只休息一次且 i = 1，一次休息就能翻盘）
//   1
//   2 3 1 3 3
// 输出 #3
//   BLUE
//
// 输入 #4（补的边界样例：n 取满 10^5，两人的总时间都约 5 * 10^14 分钟，远超
//   int 范围，必须用 long；两人解题时间完全相同，胜负只由 d 差 1 决定）
//   1
//   100000 100000 100000 100000 99999
// 输出 #4
//   RED
//
// 说明/提示
// 【样例说明 1】小蓝：解 3 题用 3 * 5 = 15 分钟，中途休息在完成第 1、2 道题
//   之后，共 1 * 2 + 2 * 2 = 6 分钟，合计 21 分钟；小红：解 3 题用 3 * 4 = 12
//   分钟，休息 1 * 3 + 2 * 3 = 9 分钟，合计 21 分钟，同时完成，输出 DRAW。
//   第二组只有 d2 从 3 变成 2：小红 12 + 6 = 18 < 21，输出 RED；
//   第三组只有 d2 从 3 变成 4：小红 12 + 12 = 24 > 21，输出 BLUE。
//   注意：做完第 3 题（最后一题）后的那次休息不算——如果算进去，
//   小蓝 15 + (1 + 2 + 3) * 2 = 27，小红 12 + (1 + 2 + 3) * 3 = 30，
//   输出会变成 BLUE，与样例第一组的 DRAW 矛盾。样例第一组就是专门卡这一点
//   设计的，写代码前务必确认这条已经想对。
// 【补充样例说明】（都是我按公式算好后写进去的，可用来对答案）
//   #2：蓝 1 * 3 = 3 分钟（n = 1 时 n * (n - 1) / 2 = 0，一次也不休息），
//     红 1 * 4 = 4 分钟，3 < 4，输出 BLUE；
//   #3：蓝 2 * 3 + 1 * 1 = 7 分钟，红 2 * 3 + 1 * 3 = 9 分钟，输出 BLUE；
//   #4：蓝 100000 * 100000 + 100000 * 4999950000 = 500005000000000 分钟，
//     红 100000 * 100000 + 99999 * 4999950000 = 500000000050000 分钟，
//     蓝的总时间比红多 4999950000 分钟，输出 RED。
// 【评测用例规模与约定】
//   对于 30% 的评测用例，1 <= T <= 100，1 <= n, t1, d1, t2, d2 <= 10^3；
//   对于所有评测用例，1 <= T <= 10^3，1 <= n, t1, d1, t2, d2 <= 10^5。
// 洛谷标注时限 3 秒，内存 512 MB。蓝桥杯 2026 年省赛 Python C 组。
//
// 思路（只用最基础的公式 + for 循环 + if，不涉及任何高级函数）
//   两人同时开始，所以不用模拟过程，分别算出每人完成全部 n 道题的总时间，
//   再比大小就行。每人的总时间 = 解题时间 + 中途休息时间：
//     解题时间 = n * t（每道题都耗时 t，一共 n 道）；
//     休息时间 = d * (1 + 2 + ... + (n - 1)) = d * n * (n - 1) / 2。
//   为什么休息只加到 n - 1：第 i 次休息是"完成第 i 道题后、开始第 i + 1 道题
//   之前"的那一段，做完最后一题比赛就结束了，第 n 次休息根本没有发生
//   （样例 1 第一组已经证实了这一点，见上面的说明）。
//   最后比较：blue < red 输出 BLUE，blue > red 输出 RED，相等输出 DRAW；
//   每组数据算完立刻输出一行，读 T 次算 T 次。
//
//   几个要想清楚的点：
//   ① 休息的下标 i 从 1 开始：完成第 1 道题后休息 1 * d，完成第 2 道题后休息
//      2 * d……所以休息总和是 1 + 2 + ... + (n - 1)，直接用等差数列公式
//      n * (n - 1) / 2 一次算出，不用写循环累加。
//   ② 算 n * (n - 1) / 2 时小心 int 溢出：n 最大 10^5，n * (n - 1) 是 10^10，
//      已经超过 int 上限（约 2.1 * 10^9）。所以表达式里要先转 long，比如
//      写成 (long) n * (n - 1) / 2，或者干脆把 n、t、d 都用 long 存。
//   ③ 总时间的量级：n * t 最大 10^10，休息部分最大约 10^5 * 5 * 10^9 = 5 * 10^14，
//      相加约 5 * 10^14，int 绝对装不下，蓝、红两人的总时间都要用 long。
//   ④ 输入：T <= 1000，每组 5 个整数，一共 5000 多个数，Scanner 的 nextInt()
//      逐个读完全够快，不需要快读，也不用自己写字符串解析。
//   ⑤ 输出的是字符串 BLUE / RED / DRAW，注意拼写和大小写，别输出中文。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        // 读入 T，表示共有 T 组测试数据
        Scanner sc = new Scanner(System.in);
        int T = sc.nextInt();
        // 循环处理每组测试数据
        for(int i = 0; i < T; i++){
            // 读入五个整数 n, t1, d1, t2, d2
            long n = sc.nextLong();
            long t1 = sc.nextLong();
            long d1 = sc.nextLong();
            long t2 = sc.nextLong();
            long d2 = sc.nextLong();
            // 计算小蓝的总时间
            long blueTime = n * t1 + d1 * (n * (n - 1) / 2);
            // 计算小红的总时间
            long redTime = n * t2 + d2 * (n * (n - 1) / 2);
            // 比较总时间，输出结果
            if(blueTime < redTime){
                System.out.println("BLUE");
            } else if(blueTime > redTime){
                System.out.println("RED");
            } else {
                System.out.println("DRAW");
            }
        }
    }
}
