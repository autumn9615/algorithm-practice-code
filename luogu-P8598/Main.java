// ============================================================================
// 洛谷 P8598 错误票据
// ----------------------------------------------------------------------------
// 题目描述
// 每张票据有唯一的 ID 号，全年所有票据的 ID 号是连续的，但 ID 的开始数码是随机选定的。
// 因为工作人员疏忽，在录入 ID 号的时候发生了一处错误，造成了某个 ID 断号，另外一个 ID 重号。
// 你的任务是通过编程，找出断号的 ID 和重号的 ID。
// 数据保证断号不可能发生在最大和最小号。
//
// 输入格式
// 一个整数 N（N < 100）表示后面数据行数，接着读入 N 行数据，每行数据长度不等，
// 是用空格分开的若干个（不大于 100 个）正整数（不大于 10^5），每个整数代表一个 ID 号。
//
// 输出格式
// 输出 1 行，含两个整数 m，n，用空格分隔，其中 m 表示断号 ID，n 表示重号 ID。
//
// 输入 #1
//   2
//   5 6 8 11 9
//   10 12 9
// 输出 #1
//   7 9
//
// 输入 #2（100 ~ 199 共 100 个号，105 断号、120 重号）
//   6
//   100 101 102 103 104 106 107 108 109 110 111 112 113 114 115 116 117
//   118 119 120 121 122 123 124 125 126 127 128 129 130 131 132 133 134
//   135 136 137 138 139 140 141 142 143 144 145 146 147 148 149 150 151
//   152 153 154 155 156 157 158 159 160 161 162 163 164 165 166 167 168
//   169 170 171 172 173 174 175 176 177 178 179 180 181 182 183 184
//   185 186 187 188 189 190 191 192 193 194 195 196 197 198 199 120
// 输出 #2
//   105 120
//
// 思路（只用了数组和循环，没有任何高级函数）
//   用一个数组 count[id] 记录每个 ID 号出现了几次。
//   最后只检查真正出现过号码的那一段 [min, max]：
//     count[id] == 0  -> 这个号一次都没出现，它就是断号
//     count[id] == 2  -> 这个号出现了两次，它就是重号
// ============================================================================
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        // 1. 创建 Scanner 对象，用于从标准输入（键盘或评测文件）读取数据
        Scanner sc = new Scanner(System.in);

        // 2. 创建一个巨大的数组，用来充当"计数器"
        // 题目限制 ID 最大是 100000，数组下标从 0 开始，所以长度必须开到 100001
        // 比如：count[5] = 2 代表 ID 为 5 的号码出现了 2 次
        int[] count = new int[100001];

        // 3. 初始化最大值和最小值
        // 用 Integer.MAX_VALUE 初始化 min，保证读入的第一个数一定能比它小
        int min = Integer.MAX_VALUE; 
        // 用 Integer.MIN_VALUE 初始化 max，保证读入的第一个数一定能比它大
        int max = Integer.MIN_VALUE;

        // 4. 循环读取所有剩余的 ID 号码
        // sc.hasNextInt() 会持续判断输入流中是否还有下一个整数，如果有就返回 true
        while (sc.hasNextInt()) {
            // 读取下一个整数，即当前的 ID 号
            int id = sc.nextInt();

            // 如果当前 ID 比记录的最小值还要小，就更新最小值
            if (id < min) {
                min = id;
            }
            // 如果当前 ID 比记录的最大值还要大，就更新最大值
            if (id > max) {
                max = id;
            }

            // 核心操作：在计数器数组中，将对应 ID 的下标位置加 1
            count[id]++; 
        }

        // 读取完毕，关闭 Scanner，释放系统资源
        sc.close();

        // 5. 定义变量，用来存储最终的断号 ID 和重号 ID，初始化为 0
        int duanhao = 0;
        int chonghao = 0;

        // 6. 遍历从最小 ID 到最大 ID 的完整区间
        // 因为题目保证断号不在最开头和最结尾，所以断号一定存在于 min 和 max 之间
        for (int id = min; id <= max; id++) {
            // 如果 count[id] 等于 0，说明这个号码在输入数据里根本没出现过，它就是断号
            if (count[id] == 0) {
                duanhao = id;
            }
            // 如果 count[id] 等于 2，说明这个号码被重复录入了，它就是重号
            else if (count[id] == 2) {
                chonghao = id;
            }
        }

        // 7. 按照题目要求的格式输出结果：先输出断号，空格隔开，再输出重号
        System.out.println(duanhao + " " + chonghao);
    }
}
