// ============================================================================
// 力扣 438. 找到字符串中所有字母异位词
// ----------------------------------------------------------------------------
// 题目描述
// 给定两个字符串 s 和 p，找到 s 中所有 p 的字母异位词的子串，返回这些
// 子串的起始索引。不考虑答案输出的顺序。
//
// 字母异位词：由相同字母重新排列形成的字符串。比如 "abc" 的异位词有
// "abc"、"acb"、"bac"、"bca"、"cab"、"cba"——字母和出现次数完全一样，
// 只是顺序不同。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public List<Integer> findAnagrams(String s, String p)
//   返回的是下标列表，顺序无所谓。本地编译需要 import java.util.*;。
//
// 输入 #1
//   s = "cbaebabacd", p = "abc"
// 输出 #1
//   [0,6]
//   解释：下标 0 开始的 "cba" 是 "abc" 的异位词；
//         下标 6 开始的 "bac" 也是；中间的 "eba"、"aba" 等都不是。
//
// 输入 #2
//   s = "abab", p = "ab"
// 输出 #2
//   [0,1,2]
//   解释：长度 2 的窗口一共三个：下标 0 的 "ab"、1 的 "ba"、2 的 "ab"，
//         三个都是 "ab" 的异位词，所以全部收下。
//
// 输入 #3
//   s = "a", p = "ab"
// 输出 #3
//   []
//   补的边界样例：s 比 p 还短，根本放不下一个窗口，直接返回空列表。
//   这组考验"循环开始前先判断 n < m"这个前置检查。
//
// 输入 #4
//   s = "aa", p = "aa"
// 输出 #4
//   [0]
//   补的样例：完全相同的两个字符串，答案就是 [0]。
//
// 输入 #5
//   s = "baa", p = "aa"
// 输出 #5
//   [1]
//   补的样例：窗口里字母数量必须完全匹配。"aa" 只有下标 1 开始的 "aa"，
//   下标 0 的 "ba" 差一个 a 多一个 b，不算。
//
// 输入 #6
//   s = "abacbabc", p = "abc"
// 输出 #6
//   [1,2,3,5]
//   补的样例：答案是分散的多段，考验窗口滑动时"进出各一个字符"的
//   计数维护有没有算对。
//
// 提示
//   1. 1 <= s.length, p.length <= 3 * 10^4
//   2. s 和 p 只包含小写英文字母
//
// 说明/提示
// 【样例说明】样例 2 的 "abab" 里窗口互相重叠，答案可以连续出现，
//   所以不能用"找到一个就跳 m 位"的写法，必须一格一格滑。
// 【评测用例规模与约定】
//   n 最大 3*10^4。暴力做法是"枚举每个起点，把长度 m 的子串排序后
//   和 p 比较"，O(n * m log m)，最坏约 3*10^4 * 3*10^4 * 15，必超时。
//   滑动窗口把每次比较降到 O(26) 甚至 O(1)，总共 O(n)。
//   字符集只有 26 个小写字母，int[26] 就够，额外空间 O(1)。力扣难度：中等。
//
// 思路（定长滑动窗口 + 字符计数数组）
//   一、先想清楚"异位词"怎么判断
//     两个字符串是异位词，等价于：26 个字母各自出现的次数完全相同。
//     所以不用管顺序，只统计每个字母的个数就行。
//     用一个 int[26] 数组 need 存 p 的字母计数，作为"标准答案"。
//
//   二、窗口固定长度为 m
//     这题和 209（长度最小）、3（最长无重复）不一样：**窗口长度是固定的**
//     ——必须是 p.length()。所以不需要 while 收缩，窗口每次都正好是 m 个字符。
//     做法：
//       1. 先把 s 的前 m 个字符放进窗口计数 win；
//       2. 从下标 m 开始，每轮"右边进一个、左边出一个"，窗口始终长 m；
//       3. 每轮比较 win 和 need 是否完全相同，相同就把窗口起点记下来。
//
//   三、代码骨架（写法 A：每轮比 26 次，好懂）
//     int n = s.length(), m = p.length();
//     List<Integer> ans = new ArrayList<>();
//     if (n < m) return ans;                  // s 太短，不可能有答案
//     int[] need = new int[26];
//     int[] win  = new int[26];
//     for (int i = 0; i < m; i++) need[p.charAt(i) - 'a']++;
//     for (int i = 0; i < n; i++) {
//         win[s.charAt(i) - 'a']++;           // 右边进来一个
//         if (i >= m) {                       // 窗口超过 m 了，左边出去一个
//             win[s.charAt(i - m) - 'a']--;
//         }
//         if (i >= m - 1) {                   // 窗口已经攒够 m 个
//             if (Arrays.equals(win, need)) {
//                 ans.add(i - m + 1);         // 起点 = 右端 - m + 1
//             }
//         }
//     }
//     return ans;
//
//     这个写法的妙处：**一个循环同时处理"攒窗口"和"滑动"两件事**。
//       i < m-1 时窗口还没攒满，只加不减；
//       i >= m 时窗口已经超了，加一个的同时减掉 i-m 那个。
//
//   四、写法 B：用 diff 记录"有几个字母的计数不一样"，O(1) 判断
//     写法 A 每轮要比较 26 个格子，虽然 26 是常数，但可以做到更快。
//     维护 diff = 计数不同的字母种类数，diff == 0 就说明完全匹配：
//
//     int[] cnt = new int[26];
//     for (int i = 0; i < m; i++) {
//         cnt[p.charAt(i) - 'a']++;           // p 里有的加一
//         cnt[s.charAt(i) - 'a']--;           // s 里有的减一
//     }
//     int diff = 0;
//     for (int k = 0; k < 26; k++) if (cnt[k] != 0) diff++;
//     if (diff == 0) ans.add(0);
//     for (int i = m; i < n; i++) {
//         int in  = s.charAt(i) - 'a';        // 新进来的字母
//         int out = s.charAt(i - m) - 'a';    // 要出去的字母
//         // 处理"进来"：先看变之前是不是 0
//         if (cnt[in] == 0) diff++;
//         cnt[in]--;
//         if (cnt[in] == 0) diff--;
//         // 处理"出去"：先看变之前是不是 0
//         if (cnt[out] == 0) diff++;
//         cnt[out]++;
//         if (cnt[out] == 0) diff--;
//         if (diff == 0) ans.add(i - m + 1);
//     }
//     注意 cnt 的含义是"p 的计数 - s 窗口的计数"：某个字母在 p 里多就
//     是正数，在 s 里多就是负数，等于 0 表示这个字母已经对齐。
//
//   五、拿样例 1 走一遍（s = "cbaebabacd", p = "abc"）
//     need: a=1, b=1, c=1
//     i=0 'c'：win[c]=1
//     i=1 'b'：win[b]=1
//     i=2 'a'：win[a]=1，窗口攒满 → win == need → 收下 0
//     i=3 'e'：win[e]=1，i>=3 减掉 s[0]='c' → win[c]=0
//              窗口 "bae" 不是 → 跳过
//     i=4 'b'：win[b]=2，减掉 s[1]='b' → win[b]=1
//              窗口 "aeb" 不是 → 跳过
//     i=5 'a'：win[a]=2，减掉 s[2]='a' → win[a]=1
//              窗口 "eba" 不是 → 跳过
//     i=6 'b'：win[b]=2，减掉 s[3]='e' → win[e]=0
//              窗口 "bab" 不是（a=0）→ 跳过
//     i=7 'a'：win[a]=2，减掉 s[4]='b' → win[b]=1
//              窗口 "aba" 不是（b=1 但 a=2）→ 跳过
//     i=8 'c'：win[c]=1，减掉 s[5]='a' → win[a]=1
//              窗口 "bac" → win == need → 收下 6 ✓
//     i=9 'd'：win[d]=1，减掉 s[6]='b' → win[b]=0
//              窗口 "acd" 不是 → 跳过
//     结果 [0,6] ✓
//
//   六、坑和边界
//     - ★ 窗口长度是固定的 p.length()，不要照搬 209/3 的 while 收缩模板。
//       这题窗口大小不变，只需要"进一个、出一个"。
//     - ★ 起点是 i - m + 1，不是 i。i 是窗口右端，减 m 再加 1 才是左端。
//     - ★ 先判断 n < m 直接返回空，否则下面的下标会算错。
//     - ★ 攒窗口的阶段（i < m-1）不能减左边，否则会减到负数下标。
//       写法 A 里靠 if (i >= m) 挡住，写法 B 里靠循环从 m 开始天然避开。
//     - 必须用 Arrays.equals 比较数组，不能用 == （== 比的是引用）。
//       Java 的 Arrays.equals 对 int[] 是逐元素比较。
//     - 大小写不敏感？不，题目只含小写字母，直接 - 'a' 就行，
//       不用 Character.toLowerCase。
//     - 答案顺序无所谓，所以按从左到右的顺序收就行，不用排序。
//     - 字符集只有 26 个小写字母，int[26] 就够；如果题目改成含大写/数字，
//       要开 int[128]。
//
//   七、复杂度
//     写法 A：循环 n 次，每次比较 26 个格子，O(26n) = O(n)；
//     写法 B：每轮 O(1) 更新 diff，O(n)。
//     两种都是 O(n)，n = 3*10^4 时毫秒级。
//     额外空间 int[26] = O(1)。
//
//   其他能过的解法（了解即可）：
//     - 枚举每个起点，截取长度 m 的子串排序后和排序后的 p 比较：
//       O(n * m log m)，会超时。
//     - 枚举每个起点，用 int[26] 重新统计一遍：O(26nm)，也会超时，
//       慢在"每个起点都从头数"。
//     - 滑动窗口 + HashMap 计数：能过，但 26 个字母用数组更快更省。
//
//   和前几题的关系：
//     209 是"变长窗口，求最短"；3 是"变长窗口，求最长"；这题是
//     "定长窗口，找全部"。三种滑动窗口的形态凑齐了。判断条件也各不相同：
//       209 比"和"，3 比"有没有重复"，438 比"26 个字母计数是否全等"。
// ============================================================================

import java.util.*;

class Solution {
    public List<Integer> findAnagrams(String s, String p) {
        // 先建一个答案集合
        List<Integer> ans = new ArrayList<>();
        // 先判断特殊情况
        // 如果 s 短于 p，不可能有答案，直接返回空集合
        if(s.length() < p.length()){
            return ans;
        }
        // 如果 s 和 p 相等（拿方法比的，不是说的长度），直接返回 0
        if(s.equals(p)){
            ans.add(0);
            return ans;
        }
        // 建立两个数组，一个存 p 的字母计数，一个存 s 的字母计数
        int[] need = new int[26];
        int[] win = new int[26];
        // 遍历 p，把 p 的字母计数存进 need 数组
        for (int i = 0; i < p.length(); i++) {
            need[p.charAt(i) - 'a']++;
        }
        // 遍历 s，把 s 的字母计数存进 win 数组
        for (int i = 0; i < s.length(); i++) {
            // 先判断 i >= p.length()，如果大于等于 p 的长度
            // 就要开始减去最左边的字母
            if (i >= p.length()) {
                win[s.charAt(i - p.length()) - 'a']--;
            }
            // 把当前字母的计数加一
            win[s.charAt(i) - 'a']++;
            // 判断 win 和 need 是否相等
            if (Arrays.equals(win, need)) {
                // 如果相等，就把 i - p.length() + 1 加到答案里
                ans.add(i - p.length() + 1);
            }
        }
        return ans;
    }
}