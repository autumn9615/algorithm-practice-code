// ============================================================================
// 洛谷 P8662 [蓝桥杯 2018 省 AB] 全球变暖
// ----------------------------------------------------------------------------
// 题目描述
// 你有一张 N×N 像素的照片，"." 表示海洋、"#" 表示陆地。例如：
//   .......
//   .##....
//   .##....
//   ....##.
//   ..####.
//   ...###.
//   .......
// 其中"上下左右"四个方向上连在一起的一片陆地组成一座岛屿，上图有 2 座岛屿。
// 由于全球变暖导致海面上升，科学家预测未来几十年，岛屿边缘一个像素的范围
// 会被海水淹没。具体来说，如果一块陆地像素与海洋相邻（上下左右四个相邻
// 像素中有海洋），它就会被淹没。上面那张照片未来会变成：
//   .......
//   .......
//   .......
//   .......
//   ....#..
//   .......
//   .......
// 请你计算：依照科学家的预测，照片中有多少岛屿会被完全淹没。
//
// 输入格式
// 第一行包含一个整数 N（1 <= N <= 1000）。
// 以下 N 行 N 列代表一张海域照片。
// 照片保证第 1 行、第 1 列、第 N 行、第 N 列的像素都是海洋。
//
// 输出格式
// 一个整数表示答案。
//
// 输入 #1
//   7
//   .......
//   .##....
//   .##....
//   ....##.
//   ..####.
//   ...###.
//   .......
// 输出 #1
//   1
//
// 输入 #2（补的样例：一整块 3×3 实心岛，最中间那个像素四面都是陆地、
//   淹不掉，所以答案是 0——专门测"岛没有被完全淹没"这条分支）
//   5
//   .....
//   .###.
//   .###.
//   .###.
//   .....
// 输出 #2
//   0
//
// 输入 #3（补的样例：两座各 2 个像素的小岛，每个像素都挨着海，两座全淹，
//   答案是 2——测"多座岛分别计数"和"小岛必淹"）
//   5
//   .....
//   .##..
//   .....
//   ..##.
//   .....
// 输出 #3
//   2
//
// 说明/提示
// 时限 1 秒，内存 256M。蓝桥杯 2018 年（第九届）省赛 AB 组。洛谷难度：普及-。
// 【样例 #1 说明】照片里一共 2 座岛：
//   左上角那座：占第 2~3 行、第 2~3 列，共 4 个像素，每个像素的上下左右都
//     至少挨着一格海（.），4 个全被淹没 → 这座岛完全淹没，答案 +1。
//   右下角那座：共 9 个像素。其中第 5 行第 5 列那个像素的上下左右四格
//     （第 4 行第 5 列、第 6 行第 5 列、第 5 行第 4 列、第 5 行第 6 列）都是
//     陆地，它不会被淹，所以这座岛还剩一块 → 不算完全淹没。
//   所以答案是 1，和题面给出的"未来照片"里仅剩的那个 # 恰好对得上。
// 【补充样例说明】#2、#3 都用参考程序实际跑过，可以直接拿去对答案。
//
// 思路（把"会被淹"翻译成"四面有没有海" + BFS 找连通块数岛屿）
//   整个题眼只有一句话：一个陆地像素会不会被淹，只看它在【原图】里上下
//   左右是不是至少有一个 '.'。四个方向全是 '#' 的像素是岛的内部，一定
//   淹不掉；只要一座岛里有任何一个这样的内部像素，这座岛就没被完全淹没。
//   于是问题变成：找出所有陆地连通块，逐块统计"有没有内部像素"，没有的
//   就 ans++。
//
//   第一步：读图
//   读 N 之后，一行一行读成字符串再转字符数组：
//     int n = sc.nextInt();
//     char[][] g = new char[n][];
//     for (int i = 0; i < n; i++) g[i] = sc.next().toCharArray();
//   用 sc.next() 而不是 nextLine() 最省事——next() 会自动跳过空白（包括
//   换行），不会踩"nextInt() 留下行尾换行"的坑。
//
//   第二步：怎么判断一个像素"淹不掉"
//   对像素 (r, c)，看它上下左右四个邻居：
//     boolean allLand = true;
//     for (每个方向 d) {
//         int nr = r + dr[d], nc = c + dc[d];
//         if (nr < 0 || nr >= n || nc < 0 || nc >= n || g[nr][nc] != '#')
//             allLand = false;
//     }
//   allLand 为 true 就是内部像素，这座岛有救了。边界判断不能省：虽然题目
//   保证最外一圈全是海，但遍历到边上时 nr/nc 仍会越界，先短路判掉就行。
//
//   第三步：BFS 找连通块（一定要用 BFS 或自己开栈，不能递归）
//   从左上往右下扫，遇到没访问过的 '#' 就开一个新连通块，把它丢进队列，
//   标记已访问，然后当队列不空时：
//     取出队首 (r, c)；
//     用第二步判断它是不是内部像素，是就把 survives 置 true；
//     枚举四个方向，邻居越界 / 是 '.' / 已经访问过就跳过；否则标记访问并
//     入队。
//   队列出完，若 survives 还是 false，说明整座岛的像素全都挨着海，ans++。
//
//   队列用数组自己写：开两个 int[] 当队列（长度 n*n 足够），配 head、tail
//   两个下标就够了，比 ArrayDeque 快，也不用装箱：
//     int[] qr = new int[n * n], qc = new int[n * n];
//     int head = 0, tail = 0;
//     qr[tail] = r; qc[tail] = c; tail++;
//     ...
//     int cr = qr[head], cc = qc[head]; head++;
//   visited 用 boolean[n][n] 单独开一张表；别直接改 g 里的 '#'（原因见坑①）。
//
//   几个要想清楚的点：
//   ① 【最关键的坑】判断"会不会被淹"必须始终基于原图。如果一边遍历一边把
//      淹掉的格子改成 '.'，再去判断别的格子，就会出现连锁反应：本来四面临
//      陆的内部格子，因为旁边的格子先被改了，被误判成挨着海，跟着一起"淹"。
//      题目说的是所有边缘像素【同时】被淹。所以要么像上面这样把判断和修改
//      分开（我们干脆不修改原图），要么单独开一张"新图"重新算。
//   ② 不能写递归 DFS。N 最大 1000，内部最多约 10^6 个陆地像素，最坏情况
//      一整座岛连成一条长蛇，递归深度到 10^6，Java 直接 StackOverflowError。
//      用 BFS + 数组队列，或者显式开一个栈，都能做到 O(N²) 且不会爆栈。
//   ③ 统计单位是"岛"，不是"像素"：ans 要在每座岛的 BFS 结束后按整座岛
//      判断一次，不能在遍历像素时一遇到边缘像素就 ans++。
//   ④ 岛被淹后即使裂成好几块也无所谓，题目问的是"原来的岛有没有被完全
//      淹没"，只要原岛还有任意一个像素活着，就不算。按连通块判断正好符合
//      这个定义。
//   ⑤ 单像素岛（比如 N=3 时中间那个 '#'）四面都是海，必淹；题面保证
//      最外圈是海，所以真正的陆地只可能出现在内部。
//   ⑥ 规模：N <= 1000，格子数 10^6。每个格子至多进队一次、四个方向各看
//      一次，时间 O(N²)；char[][] 约 2 MB、visited 约 1 MB、两个队列数组
//      约 8 MB，256 MB 绰绰有余，1 秒时限也没问题。
//   别忘了文件开头 import java.util.Scanner;（或直接 import java.util.*;）。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 读取要输入的行数和列数（相等的）
        int N = sc.nextInt();
        // 读取输入的字符数组
        char[][] g = new char[N][];
        // 读取每一行
        for (int i = 0; i < N; i++) {
            // g[i]的意思是第i行的字符数组，这时候读到的所有字符都存到g[i]中，自动成了一个字符数组
            g[i] = sc.next().toCharArray();
        }
        // 定义方向数组
        int[] dr = {-1, 0, 1, 0}, dc = {0, 1, 0, -1};
        // 定义访问数组
        boolean[][] visited = new boolean[N][N];
        // 定义答案
        int ans = 0;
        // 从左上角开始遍历
        for (int r = 0; r < N; r++) {
            for (int c = 0; c < N; c++) {
                // 如果是陆地且没有被访问过
                if (g[r][c] == '#' && !visited[r][c]) {
                    // 初始化 survives 为 false
                    boolean survives = false;
                    // 开队列
                    int[] qr = new int[N * N], qc = new int[N * N];
                    int head = 0, tail = 0;
                    // 把当前陆地入队
                    qr[tail] = r; qc[tail] = c; tail++;
                    // 标记已访问
                    visited[r][c] = true;
                    // 当队列不为空时
                    while (head < tail) {
                        // 取出队首
                        int cr = qr[head], cc = qc[head]; head++;
                        // 判断是否是内部像素
                        if (allLand(g, N, cr, cc, dr, dc)) {
                            survives = true;
                        }
                        // 枚举四个方向
                        for (int d = 0; d < 4; d++) {
                            // 计算邻居的坐标
                            int nr = cr + dr[d], nc = cc + dc[d];
                            // 如果邻居越界、是海或者已经访问过，跳过
                            if (nr < 0 || nr >= N || nc < 0 || nc >= N || g[nr][nc] == '.' || visited[nr][nc]) {
                                continue;
                            }
                                                        // 标记已访问并入队
                            visited[nr][nc] = true;
                            qr[tail] = nr; qc[tail] = nc; tail++;

                        }
                    }
                    // 如果整座岛都被淹了，答案加一
                    if (!survives) {
                        ans++;
                    } 
                }
            }
        }
        sc.close();
        System.out.println(ans);
    }

    // 判断一个像素是否是内部像素
    static boolean allLand(char[][] g, int N, int r, int c, int[] dr, int[] dc) {
        // 枚举四个方向
        for (int d = 0; d < 4; d++) {
            // 计算邻居的坐标
            int nr = r + dr[d], nc = c + dc[d];
            // 如果邻居越界、是海或者已经访问过，返回 false
            if (nr < 0 || nr >= N || nc < 0 || nc >= N || g[nr][nc] != '#') {
                return false;
            }
        }
        // 否则返回 true
        return true;
    }
}
