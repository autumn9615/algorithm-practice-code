// ============================================================================
// 力扣 875. 爱吃香蕉的珂珂
// ----------------------------------------------------------------------------
// 题目描述
// 珂珂喜欢吃香蕉。这里有 n 堆香蕉，第 i 堆中有 piles[i] 根香蕉。警卫已经
// 离开了，将在 h 小时后回来。
// 珂珂可以决定她吃香蕉的速度 k（单位：根/小时）。每个小时，她将会选择一堆
// 香蕉，从中吃掉 k 根。如果这堆香蕉少于 k 根，她将吃掉这堆的所有香蕉，
// 然后这一小时内不会再吃更多的香蕉。
// 珂珂喜欢慢慢吃，但仍然想在警卫回来前吃掉所有的香蕉。
// 返回她可以在 h 小时内吃掉所有香蕉的最小速度 k（k 为整数）。
//
// 函数签名（力扣已经给出，不用自己读输入，把方法补全提交即可）
//   public int minEatingSpeed(int[] piles, int h)
//
// 输入 #1
//   piles = [3,6,7,11], h = 8
// 输出 #1
//   4
//   解释：k = 4 时，各堆分别要 1、2、2、3 小时，共 8 小时正好赶上；
//         再慢一点（k = 3）就要 1 + 2 + 3 + 4 = 10 小时，来不及。
//
// 输入 #2
//   piles = [30,11,23,4,20], h = 5
// 输出 #2
//   30
//   解释：5 堆香蕉每堆至少要花 1 小时，h = 5 正好等于堆数，所以每堆都得
//         1 小时吃完，k 不能小于最大的那堆 30。
//
// 输入 #3
//   piles = [30,11,23,4,20], h = 6
// 输出 #3
//   23
//   解释：k = 23 时，30 那堆要 2 小时、其余各 1 小时，共 6 小时；
//         k = 22 时，30 和 23 两堆都要 2 小时，共 7 小时，超了。
//
// 输入 #4
//   piles = [1], h = 1
// 输出 #4
//   1
//   补的边界样例：只有一堆 1 根，二分区间 [0, 1] 一次都不循环，直接返回 1。
//
// 提示
//   1. 1 <= piles.length <= 10^4
//   2. piles.length <= h <= 10^9
//   3. 1 <= piles[i] <= 10^9
//
// 说明/提示
// 【样例说明】三个官方样例分别对应"中间有可行/不可行"、"h 等于堆数"、
//   "h 比堆数多 1" 三种情况，答案依次是 4、30、23。
//   样例 2、3 只差 h 的取值（5 和 6），答案就从 30 掉到 23，说明 h 对答案
//   影响很大，这正是"在速度上二分"的切入点。
// 【评测用例规模与约定】
//   h 保证 >= piles.length，所以最慢也能每堆一小时吃完，答案一定存在且
//   不超过 max(piles)。piles[i] 最大 10^9，线性枚举 k 最坏要走 10^9 次，
//   会超时；但"k 越大总时间越少"是有序的，所以可以二分。力扣难度：中等。
//
// 思路（二分答案 + 开区间模板法：在速度 k 上二分"能不能 h 小时吃完"）
//   一、先把问题翻译成"判定"问题
//     给定速度 k，吃完所有香蕉要多少小时？
//       第 i 堆要 ceil(piles[i] / k) 小时。因为每小时只能选一堆，
//       吃不满 k 根的那个小时也照样占掉一小时（剩余不足 k 时一次吃完，
//       这个小时不会再去吃别的堆）。
//     总时间 t(k) = 各堆 ceil(piles[i] / k) 之和。
//     若 t(k) <= h，就说 k 是"可行速度"。
//
//   二、为什么能二分
//     k 越大，每一堆花的时间越少，t(k) 单调不增：
//       k 可行 → 所有比它大的速度都可行；
//       k 不可行 → 所有比它小的速度都不可行。
//     所以可行速度构成一个后缀 [ans, +∞)，题目要的就是这个后缀的起点，
//     正是"二分答案"里最经典的最小可行值模型。
//
//   三、二分区间怎么定（沿用 34、367 的开区间模板）
//     下界 left = 0，只当"一定不可行"的哨兵（速度 0 等于永远吃不完）。
//       循环里只会检查 mid，而 mid 一定落在 (left, right) 之间，
//       所以永远不会真的去算 t(0)，不会除零。
//       注意不能写 left = 1：h 很大时速度 1 也可能可行，那就不是哨兵了。
//     上界 right = max(piles)，一定可行。因为每堆至少要 1 小时，
//       k = max(piles) 时每堆正好 1 小时，总共 n 小时，而题面保证 h >= n。
//       比 max(piles) 更快没有任何意义，再大也不会减少小时数。
//
//     int left = 0, right = 0;
//     for (int p : piles) {
//         right = Math.max(right, p);          // 上界取最大的那堆
//     }
//     while (left + 1 < right) {
//         int mid = left + (right - left) / 2; // 防溢出写法
//         if (canFinish(piles, mid, h)) {
//             right = mid;                     // mid 可行，答案 <= mid
//         } else {
//             left = mid;                      // mid 不可行，答案 > mid
//         }
//     }
//     return right;   // 结束时 left 不可行、right 可行且相邻，right 就是最小可行速度
//
//     模板的含义：left 永远是"已知不可行"的速度，right 永远是"已知可行"的
//     速度，区间不断缩小，最后剩下的 right 就是第一个可行值。
//
//   四、判定函数 canFinish（两个坑都在这里）
//     boolean canFinish(int[] piles, int k, int h) {
//         long hours = 0;                      // 坑 1：总小时数必须用 long
//         for (int p : piles) {
//             hours += (p + k - 1) / k;        // 坑 2：向上取整的整数写法
//             if (hours > h) return false;     // 剪枝：超了立刻停，不继续累加
//         }
//         return hours <= h;
//     }
//     坑 1：k = 1 时总小时数 = 各堆之和，最大 10^4 * 10^9 = 10^13，
//           int 装不下，会变成负数，早退判断跟着全错。用 long。
//     坑 2：整数除法 a / b 是向下取整，ceil(a / b) 要写成 (a + b - 1) / b。
//           直接写 p / k 会把时间算少，答案偏小。
//           p 最大 10^9、k 最大 10^9，p + k - 1 最多约 2*10^9，还在 int
//           范围内（int 上限 2147483647）；更保险的写法是 (p - 1) / k + 1，
//           这个写法永远不会溢出，效果完全一样。
//
//   五、拿样例 1 走一遍（piles = [3,6,7,11], h = 8，right 初值 11）
//     left=0, right=11 → mid=5：t = 1+2+2+3 = 8 <= 8，可行 → right=5
//     left=0, right=5  → mid=2：t = 2+3+4+6 = 15 > 8，不可行 → left=2
//     left=2, right=5  → mid=3：t = 1+2+3+4 = 10 > 8，不可行 → left=3
//     left=3, right=5  → mid=4：t = 1+2+2+3 = 8 <= 8，可行 → right=4
//     left=3, right=4  → 3 + 1 < 4 不成立，结束，返回 right = 4，和样例一致。
//   样例 3（h = 6）最后两步：mid=24 可行 → right=24；mid=23 可行 → right=23，
//   区间缩成 [22, 23] 结束，返回 23，也一致。
//
//   六、边界与复杂度
//     - piles = [1], h = 1：left=0, right=1，循环一次都不进，直接返回 1。
//     - h 正好等于 n：答案是 max(piles)，因为每堆都只能花 1 小时。
//     - 时间复杂度 O(n * log M)，M = max(piles) <= 10^9，log M 约 30，
//       10^4 * 30 = 3*10^5 次判定，很快；额外空间 O(1)。
//
//   其他能过的解法（了解即可）：
//     - 从 k = 1 开始线性试，第一个可行的就是答案：最坏 10^13 次，超时。
//     - 用 Math.ceil((double) p / k) 求小时数：也能过，但浮点数没必要，
//       整数除法既精确又快。
//     - 上界可以从 max(piles) 收紧到某个更小的值（比如 ceil(总数/ h)），
//       但 log 级别差别不大，没必要为这题增加出错面。
// ============================================================================

class Solution {
    public int minEatingSpeed(int[] piles, int h) {
        // 定义左右边界
        long left = 0;
        long right = 0;
        // 算最大的一堆香蕉，定义为右边界
        for (int p : piles) {
            right = Math.max(right, p);
        }
        // 模板二分
        while(left + 1 < right){
            long mid = left + (right - left) / 2;
            // 每次都判断mid是否可行，如果可行就缩小右边界，否则缩小左边界（应为要求满足的最小的k，所以要一直判断，一直缩小边界）
            if(canFinish(piles,mid,h)){
                right = mid;
            }else{
                left = mid;
            }
        }
        return (int)right;
    }
    // 判定函数,判断速度 k 是否可行，可行就返回 true，不可行就返回 false（注意每次二分之后都判断）
    public boolean canFinish(int[] piles, long k, int h) {
        // 总时间
        long hours = 0;
        // 【核心修正】总时间必须"每一堆分别向上取整，再累加"，
        // 不能把香蕉全加起来再除以 k 取一次整。
        // 原因：每个小时只能从"一堆"里吃，某堆剩下的零头（不足 k 根）
        // 必须在这个小时里吃完，这一小时就浪费掉了，不能拿去吃别的堆。
        // 所以每一堆的余数都是独立的浪费，必须分开算。
        // 反例（样例 2）：piles = [30,11,23,4,20], h = 5
        //   按总和算：ceil(88/18) = 5 <= 5，误判为"可行"；
        //   实际每堆：ceil(30/18)+ceil(11/18)+ceil(23/18)+ceil(4/18)+ceil(20/18)
        //           = 2 + 1 + 2 + 1 + 2 = 8 小时 > 5，其实"不可行"。
        // 原来的 sum 变量就是为了"先求和再除"，思路错了，所以一起删掉。
        for (int p : piles) {
            // 第 p 堆要花的小时数 = ceil(p / k)。
            // 注意整数除法是向下取整，向上取整要写成 (p + k - 1) / k。
            // 例：p = 7, k = 4 → (7 + 3) / 4 = 10 / 4 = 2 小时（不是 1 小时）。
            // 溢出说明：p 最大 1e9、k 最大 1e9，p + k - 1 最多约 2e9，
            //   而 int 上限是 2147483647，刚好放得下；但 k 是 long，
            //   所以整个表达式会自动按 long 算，绝对安全。
            //   （更保险的等价写法是 (p - 1) / k + 1，永远不会溢出。）
            hours += (p + k - 1) / k;
            // 【剪枝】时间已经超过 h 了，后面不用再算，直接判定不可行。
            // 这一步既是优化，也能防"累加到超出 long 范围"（本题不会到那一步，
            // 但养成习惯没坏处）。k 最小时 hours 最大，约 1e4 * 1e9 = 1e13，
            // long 能存到 9e18，所以不剪枝也不会溢出。
            if (hours > h) {
                return false;
            }
        }
        // 判断总时间是否小于h
        if(hours <= h){
            // 总时间小于h，说明k可行，代表着速度可以再慢一些，所以返回true
            return true;
        }else{
            // 总时间大于h，说明k不可行，代表着速度要快一些，所以返回false
            return false;
        }
    }
}