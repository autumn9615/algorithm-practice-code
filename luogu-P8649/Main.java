// ============================================================================
// 洛谷 P8649 [蓝桥杯 2017 省 B] k 倍区间
// ----------------------------------------------------------------------------
// 题目描述
// 给定一个长度为 N 的数列 A1, A2, ..., AN，如果其中一段连续的子序列
// Ai, A(i+1), ..., Aj (i <= j) 之和是 K 的倍数，我们就称这个区间 [i, j]
// 是 K 倍区间。
// 你能求出数列中总共有多少个 K 倍区间吗？
//
// 输入格式
// 第一行包含两个整数 N 和 K (1 <= N, K <= 10^5)。
// 以下 N 行每行包含一个整数 Ai (1 <= Ai <= 10^5)。
//
// 输出格式
// 输出一个整数，代表 K 倍区间的数目。
//
// 输入 #1
//   5 2
//   1
//   2
//   3
//   4
//   5
// 输出 #1
//   6
//
// 输入 #2（补的边界样例：K = 1 时任何区间都是 1 的倍数，4 个数的全部区间
//   数就是 4 * 5 / 2 = 10，用来核对"数法有没有漏"）
//   4 1
//   3
//   7
//   1
//   9
// 输出 #2
//   10
//
// 输入 #3（补的边界样例：三个数全是 3、K = 3，6 个区间全是 K 倍区间；专门
//   卡"忘了补空前缀 S[0] = 0"的写法——漏掉它时余数 0 只数出 3 个、答案是
//   3，而正确答案是 6）
//   3 3
//   3
//   3
//   3
// 输出 #3
//   6
//
// 输入 #4（补的边界样例：K = 5、数列 4 5 4，前缀余数是 0, 4, 4, 3，只有区
//   间 [2, 2]（数字 5）是 5 的倍数，答案是 1；专心只数"余数为 0 的配对"的
//   写法会输出 0）
//   3 5
//   4
//   5
//   4
// 输出 #4
//   1
//
// 输入 #5（补的边界样例：N = 1 最小规模，唯一一个数又是 5 的倍数，答案是
//   1；单个元素自己就是一个区间，别漏；要是把数换成 7，答案应是 0）
//   1 5
//   5
// 输出 #5
//   1
//
// 说明/提示
// 【样例说明】官方样例只有 #1 一组，用"前缀和 + 余数"来验算：前缀和
//   S0..S5 = 0, 1, 3, 6, 10, 15，除以 2 的余数依次是 0, 1, 1, 0, 0, 1。
//   余数 0 的有 S0、S3、S4 三个，两两配出 [1,3]（和 6）、[1,4]（和 10）、
//   [4,4]（和 4）；余数 1 的有 S1、S2、S5 三个，两两配出 [2,2]（和 2）、
//   [2,5]（和 14）、[3,5]（和 12），一共 6 个，和样例输出一致。
// 【补充样例说明】（都是用区间暴力程序跑过的，可用来对答案）
//   #2：K = 1 时 5 个前缀余数全是 0，两两配对 C(5,2) = 10；
//   #3：前缀和 0, 3, 6, 9，余数全是 0，配对 C(4,2) = 6（漏掉 S0 就只剩
//     C(3,2) = 3）；
//   #4：前缀余数 0, 4, 4, 3，只有余数 4 的两个前缀（S1、S2）配对，得到
//     区间 [2, 2]，和是 5，答案 1；
//   #5：只有 S0、S1 两个前缀，余数 0 和 0，配出 1 对，答案 1。
// 【评测用例规模与约定】
//   1 <= N, K <= 10^5；1 <= Ai <= 10^5。
//   洛谷标注时限 2 秒，内存 256 MB；「说明/提示」原文：时限 2 秒, 256M。
//   蓝桥杯 2017 年第八届。
//   大坑预警：答案可能超过 int 上限（约 2.1 * 10^9）。比如 N = 10^5、
//   K = 1 时所有区间都算数，答案是 10^5 * (10^5 + 1) / 2 = 5000050000，
//   必须用 long 存。
//
// 思路（只用数组、for 循环和 if，没有任何高级函数）
//   暴力思路是枚举所有区间：左端点 i、右端点 j 都试过来，把区间和累出来看
//   能不能被 K 整除。区间一共有 N * (N + 1) / 2 个，N = 10^5 时约 5 * 10^9
//   个，铁定超时，得换个数法。
//
//   引入前缀和：记 S[0] = 0，S[t] = A1 + A2 + ... + At（t 从 1 到 N），那么
//   区间 [i, j] 的和 = S[j] - S[i - 1]。而"两个数相减是 K 的倍数"等价于
//   "两个数除以 K 的余数相同"——所以区间 [i, j] 是 K 倍区间，当且仅当
//   S[j] 和 S[i - 1] 的余数相同。
//   这样问题就变了：把 S[0], S[1], ..., S[N] 这 N + 1 个前缀和按除以 K 的
//   余数分成 K 组，同一组里任取两个（一个在前一个在后）就恰好对应一个 K 倍
//   区间，把每个组"选两个"的方法数加起来就是答案。
//
//   做法：
//   ① 读入 N、K，开一个数组 cnt，大小 K，先全填 0；cnt[r] 表示"余数为 r
//      的前缀和出现了几次"；
//   ② 别忘了补上 S[0] = 0，它的余数是 0，所以先把 cnt[0] 置成 1；
//   ③ 一边读 N 个数一边维护"当前前缀和除以 K 的余数" cur：
//      cur = (cur + a) % K，然后 cnt[cur]++（读完第 t 个数时的 cur 就是
//      S[t] 的余数）；
//   ④ 全部读完再数答案：对 r = 0 到 K - 1，把 cnt[r] * (cnt[r] - 1) / 2
//      累加（这就是 C(cnt[r], 2)，同组两两配对的方法数）；
//   ⑤ 输出答案。
//
//   几个要想清楚的点：
//   ① 不要把完整的前缀和存下来：S[N] 最大约 10^10，int 装不下。但全程其实
//      只用到"余数"，所以干脆不存 S，只维护 cur 这一个余数。cur < K <=
//      10^5，再加上一个数最多到 2 * 10^5，int 绰绰有余，压根不会溢出。
//   ② 答案必须用 long！N = 10^5 时区间总数约 5 * 10^9，超过 int 上限。
//      同理 cnt[r] * (cnt[r] - 1) 也要先把一个因子转成 long 再乘，写成
//      (long) cnt[r] * (cnt[r] - 1) / 2；两个 int 先乘完再存就晚了（中间
//      已经溢出）。
//   ③ cnt[0] 初值 1 是这个算法的灵魂：它代表"空前缀" S[0] = 0，对应的是
//      "从第 1 个数开始"的区间。忘了置 1，所有起点是 A1 的区间都会漏掉
//      （补充样例 #3 就是专门卡这个的）。
//   ④ "余数相同"不是"余数都是 0"：余数 0 的组、余数 1 的组、余数 2 的组
//      ……每一组都要数（补充样例 #4 里成对的那个余数就是 4）。
//   ⑤ 单个元素也算区间（i = j 时区间里就一个数），样例 #1 里的 2 和 4 就是
//      这样的。这个算法天然覆盖，不用特殊处理。
//   ⑥ 余数一定落在 0 到 K - 1：题面保证 Ai >= 1 全是正数，前缀和一路递增，
//      Java 里正数 % K 的结果就是普通余数，不用考虑负数取余那种麻烦事。
//   ⑦ 复杂度 O(N + K)，N、K 最多 10^5，2 秒时限随便过；最多读 10^5 + 2
//      个数，Scanner 一个个读完全够快，不用快读。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        // 读入 N、K，开一个数组 cnt，大小 K，先全填 0
        int N = sc.nextInt();
        int K = sc.nextInt();
        int[] cnt = new int[K];
        // 别忘了补上 S[0] = 0，它的余数是 0，所以先把 cnt[0] 置成 1
        cnt[0] = 1;
        // 当前前缀和
        long sum = 0;
        // 答案
        long ans = 0;
        for (int i = 0; i < N; i++) {
            // 读入一个数
            int a = sc.nextInt();
            // 维护当前前缀和
            sum += a;
            // 计算当前前缀和除以 K 的余数
            int cur = (int)(sum % K);
            // 余数相同的前缀和出现了几次，就有多少个区间可以配对
            ans += cnt[cur];
            // 更新余数为 cur 的前缀和的出现次数
            cnt[cur]++;
        }
        System.out.println(ans);
    }
}
