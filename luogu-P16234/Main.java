// ============================================================================
// 洛谷 P16234 [蓝桥杯 2026 省 B] 循环右移
// ----------------------------------------------------------------------------
// 题目描述
// 给定三个整数 N、X、Y，请计算有多少个长度为 N 的整数数组 A 满足下面两个条件：
//   ① 数组中的每个元素 A_i 都满足 X <= A_i <= Y（只能在 X 到 Y 之间取值）；
//   ② 对数组 A 的任意一个连续子数组做一次循环右移，得到的新子数组与原数组完全一致。
//
// 循环右移：把长度为 k 的连续子数组 [B1, B2, ..., Bk] 变成 [Bk, B1, B2, ..., Bk-1]，
// 也就是把最后一个元素搬到最前面，其余元素保持原有顺序依次往后挪一位。
//
// 输入格式
// 第一行一个整数 T，表示测试数据的组数。
// 接下来的 T 行，每行三个由空格隔开的整数 N、X、Y。
//
// 输出格式
// 对于每组测试数据，输出一行，包含一个整数，表示满足条件的数组 A 的个数。
//
// 输入 #1
//   3
//   3 1 2
//   5 10 10
//   2 5 3
// 输出 #1
//   2
//   1
//   0
//
// 输入 #2（补的边界样例：答案会超过 int 范围必须用 long；N 取 1 或最大值都不影响答案）
//   2
//   1 1 1000000000000000000
//   1 3 3
// 输出 #2
//   1000000000000000000
//   1
//
// 说明/提示
// 【评测用例规模与约定】
//   对于 30% 的评测用例：1 <= T <= 20，1 <= N <= 100，1 <= X, Y <= 100；
//   对于 100% 的评测用例：1 <= T <= 1000，1 <= N <= 10^18，1 <= X, Y <= 10^18。
// 原题时限 1 秒，内存 512 MB。蓝桥杯 2026 年省赛 B 组。
// 洛谷注明：本题测试数据为洛谷自造，与官方数据可能存在差异，仅供学习参考。
//
// 思路（只用了 Scanner + long 变量 + for 循环，没有任何高级函数）
//   先想清楚条件②到底在要求什么。只看相邻两个元素组成的小子数组 [a, b]：
//   它循环右移一次变成 [b, a]，题目要求移完之后和原来一模一样，
//   所以必须 a == b；相邻两两相等，一路推下去，整个数组就只能所有元素全部相同。
//   反过来说，元素全相同的数组（比如 [5,5,5]）里，任意连续子数组都是 [c, c, ..., c]，
//   循环右移之后还是它自己，条件②一定满足。
//   所以满足条件的数组 = "所有元素都取同一个数 c" 的数组：
//   从 X 到 Y（含两端）每个整数 c 都正好对应一个数组，
//   X <= Y 时答案是 Y - X + 1；X > Y 时区间是空的，一个数都取不到，答案是 0。
//   注意 N 完全不影响答案——不管数组多长都只有"全相同"这一种情况；
//   N = 1 也一样（长度为 1 的数组本来就"全相同"，条件②自动满足）。
//   坑：X、Y、答案都可能到 10^18，int 最大才 21 亿多一点，装不下，
//       三个数都要用 long 读（sc.nextLong()），算出来的结果也是 long。
//   规模：T 最多 1000 组，每组只做一次减法，1 秒时限随手就过。
// ============================================================================

import java.util.*;

public class Main {
    public static void main(String[] args){
        // 读入m，表示要输入的数据组数
        Scanner sc = new Scanner(System.in);
        int m = sc.nextInt();
        // 循环读入每组数据
        long N = 0;
        long X = 0;
        long Y = 0;
        for(int i = 0; i < m ; i++){
            // 读入三个整数N、X、Y
            N = sc.nextLong();
            X = sc.nextLong();
            Y = sc.nextLong();
        // 计算答案
        long ans = 0;
        if(X > Y){
            ans = 0;
        }else if(X == Y){
            ans = 1;
        }else{
            ans = Y - X + 1;
        }
        System.out.println(ans);
        }
        sc.close();
    }
}
